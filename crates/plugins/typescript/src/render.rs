//! TypeScript target plugins.
//!
//! Each plugin owns one concern, so a project can combine models with exactly
//! the transports it wants. The generated source is plain TypeScript: Rust is
//! the only code that runs while generation is happening.

use std::fmt::Write;

use anyhow::Result;
use serde_json::{Value, json};

use kaji_core::GeneratedFile;
use kaji_core::ast::{AdditionalProperties, Api, SchemaKind, SchemaValue};

const NOTICE: &str = "// Generated by Kaji Codegen. Do not edit.\n";

/// Explicit settings for standalone auxiliary artifacts. These renderers return
/// files; plugin authors decide how to publish them and their dependencies.
#[derive(Clone, Debug)]
pub struct ArtifactOptions {
    pub output_dir: Option<String>,
    pub package_name: Option<String>,
    pub naming: Naming,
    pub openapi_spec: Option<String>,
    pub title: Option<String>,
    /// Import prefix from the generated artifact to the operation modules.
    pub clients_import: String,
    pub group_by_tag: bool,
}
impl Default for ArtifactOptions {
    fn default() -> Self {
        Self {
            output_dir: None,
            package_name: None,
            naming: Naming::CamelCase,
            openapi_spec: None,
            title: None,
            clients_import: "./clients".into(),
            group_by_tag: true,
        }
    }
}
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Naming {
    #[default]
    CamelCase,
    PascalCase,
    SnakeCase,
}

/// Emits reusable TypeScript types from the normalized schema graph.
#[derive(Default)]
pub struct TypeScriptModels;

impl TypeScriptModels {
    pub fn generate(&self, api: &Api, config: &ArtifactOptions) -> Result<Vec<GeneratedFile>> {
        Ok(vec![GeneratedFile::new(
            output_path(config, "models.ts"),
            render_models(api),
        )?])
    }
}

/// Emits `index.ts`, package metadata, and a strict TypeScript configuration.
#[derive(Default)]
pub struct TypeScriptPackage;

impl TypeScriptPackage {
    pub fn generate(&self, api: &Api, config: &ArtifactOptions) -> Result<Vec<GeneratedFile>> {
        let index = format!("{NOTICE}\nexport * from './models';\n");
        let package_name = config
            .package_name
            .clone()
            .unwrap_or_else(|| format!("@kaji/{}", package_slug(&api.name)));
        let package = json!({
            "name": package_name,
            "version": api.version,
            "description": format!("{} API client generated by Kaji Codegen", api.name),
            "type": "module",
            "sideEffects": false,
            "exports": { ".": { "types": "./dist/index.d.ts", "import": "./dist/index.js" } },
            "files": ["dist"],
            "scripts": { "build": "tsc -p tsconfig.json" },
            "devDependencies": { "typescript": "^7.0.0" }
        });
        Ok(vec![
            GeneratedFile::new(output_path(config, "index.ts"), index)?,
            GeneratedFile::new(
                output_path(config, "package.json"),
                format!("{}\n", serde_json::to_string_pretty(&package)?),
            )?,
            GeneratedFile::new(output_path(config, "tsconfig.json"), tsconfig())?,
        ])
    }
}

fn output_path(config: &ArtifactOptions, file: &str) -> String {
    let directory = config.output_dir.as_deref().unwrap_or("typescript");
    match directory {
        "" | "." => file.to_owned(),
        _ => format!("{directory}/{file}"),
    }
}

fn render_models(api: &Api) -> String {
    let mut output = format!("{NOTICE}\n");
    for schema in &api.schemas {
        render_description(&mut output, schema.value.description.as_deref());
        let _ = writeln!(
            output,
            "export type {} = {};\n",
            type_identifier(&schema.name),
            render_value(&schema.value)
        );
    }
    output
}

fn render_value(value: &SchemaValue) -> String {
    let primitive = match &value.kind {
        SchemaKind::Any => "unknown".to_owned(),
        SchemaKind::Null => "null".to_owned(),
        SchemaKind::Boolean => "boolean".to_owned(),
        SchemaKind::Integer | SchemaKind::Number => "number".to_owned(),
        SchemaKind::String => "string".to_owned(),
        SchemaKind::Array { items } => format!("Array<{}>", render_value(items)),
        SchemaKind::Object {
            fields,
            additional_properties,
        } => render_object(fields, additional_properties),
        SchemaKind::Reference { reference } => {
            type_identifier(reference.rsplit('/').next().unwrap_or(reference))
        }
        SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => {
            join_types(variants, " | ")
        }
        SchemaKind::AllOf { variants } => join_types(variants, " & "),
        // TypeScript has no sound type-level complement operator. `unknown` is
        // safer than emitting an invented constraint that rejects valid values.
        SchemaKind::Not { .. } => "unknown".to_owned(),
    };

    let constrained = if let Some(constant) = value.const_value.as_ref().and_then(ts_literal) {
        constant
    } else if !value.enum_values.is_empty() {
        let members = value
            .enum_values
            .iter()
            .filter_map(ts_literal)
            .collect::<Vec<_>>();
        if members.is_empty() {
            primitive
        } else {
            members.join(" | ")
        }
    } else {
        primitive
    };

    if value.nullable && constrained != "null" {
        format!("{constrained} | null")
    } else {
        constrained
    }
}

fn render_object(
    fields: &[kaji_core::ast::Field],
    additional_properties: &AdditionalProperties,
) -> String {
    let mut members = Vec::new();
    for field in fields {
        let optional = if field.required { "" } else { "?" };
        let mut member = String::new();
        if let Some(description) = field.value.description.as_deref() {
            member.push_str("/** ");
            member.push_str(&description.replace("*/", "* /"));
            member.push_str(" */ ");
        }
        let _ = write!(
            member,
            "{}{}: {}",
            property_name(&field.name),
            optional,
            render_value(&field.value)
        );
        members.push(member);
    }
    match additional_properties {
        AdditionalProperties::Any | AdditionalProperties::Unspecified => {
            members.push("[key: string]: unknown".to_owned());
        }
        AdditionalProperties::Schema { value } => {
            members.push(format!("[key: string]: {}", render_value(value)));
        }
        AdditionalProperties::Forbidden => {}
    }
    if members.is_empty() {
        "Record<string, never>".to_owned()
    } else {
        format!("{{ {} }}", members.join("; "))
    }
}

fn join_types(values: &[SchemaValue], separator: &str) -> String {
    if values.is_empty() {
        "unknown".to_owned()
    } else {
        values
            .iter()
            .map(|value| {
                let rendered = render_value(value);
                // `&` binds more tightly than `|` in TypeScript. Parenthesize
                // union members of an intersection so `allOf` keeps its JSON
                // Schema grouping instead of changing its meaning on render.
                if separator == " & " && rendered.contains(" | ") {
                    format!("({rendered})")
                } else {
                    rendered
                }
            })
            .collect::<Vec<_>>()
            .join(separator)
    }
}

fn ts_literal(value: &Value) -> Option<String> {
    match value {
        Value::Null | Value::Bool(_) | Value::Number(_) | Value::String(_) => {
            serde_json::to_string(value).ok()
        }
        Value::Array(values) => values
            .iter()
            .map(ts_literal)
            .collect::<Option<Vec<_>>>()
            .map(|values| format!("readonly [{}]", values.join(", "))),
        Value::Object(values) => values
            .iter()
            .map(|(name, value)| {
                ts_literal(value).map(|value| format!("{}: {value}", js_string(name)))
            })
            .collect::<Option<Vec<_>>>()
            .map(|values| format!("{{ {} }}", values.join("; "))),
    }
}

fn render_description(output: &mut String, description: Option<&str>) {
    if let Some(description) = description {
        output.push_str("/**\n");
        for line in description.lines() {
            let _ = writeln!(output, " * {}", line.replace("*/", "* /"));
        }
        output.push_str(" */\n");
    }
}

fn model_import(api: &Api) -> String {
    if api.schemas.is_empty() {
        String::new()
    } else {
        format!(
            "import type {{ {} }} from './models';\n",
            api.schemas
                .iter()
                .map(|schema| type_identifier(&schema.name))
                .collect::<Vec<_>>()
                .join(", ")
        )
    }
}

fn tsconfig() -> &'static str {
    r#"{
  "compilerOptions": {
    "declaration": true,
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "outDir": "dist",
    "strict": true,
    "target": "ES2022"
  },
  "include": ["*.ts"]
}
"#
}

fn package_slug(name: &str) -> String {
    let slug = name
        .chars()
        .flat_map(char::to_lowercase)
        .map(|character| {
            if character.is_ascii_alphanumeric() {
                character
            } else {
                '-'
            }
        })
        .collect::<String>();
    match slug.trim_matches('-') {
        "" => "api".to_owned(),
        value => value.to_owned(),
    }
}

fn property_name(name: &str) -> String {
    if is_identifier(name) && !reserved(name) {
        name.to_owned()
    } else {
        js_string(name)
    }
}

pub(crate) fn type_identifier(name: &str) -> String {
    let result = identifier(name, true);
    if reserved(&result) {
        format!("{result}Type")
    } else {
        result
    }
}

fn operation_identifier(name: &str, config: &ArtifactOptions) -> String {
    let mut result = match config.naming {
        Naming::PascalCase => identifier(name, true),
        Naming::SnakeCase => snake_case(name),
        Naming::CamelCase => identifier(name, false),
    };
    if reserved(&result) {
        result.push_str("Operation");
    }
    result
}

fn identifier(value: &str, upper_first: bool) -> String {
    let mut result = String::new();
    let mut uppercase_next = upper_first;
    for character in value.chars() {
        if character.is_ascii_alphanumeric() || character == '_' {
            if result.is_empty() && character.is_ascii_digit() {
                result.push('_');
            }
            if uppercase_next {
                result.extend(character.to_uppercase());
                uppercase_next = false;
            } else {
                result.push(character);
            }
        } else {
            uppercase_next = true;
        }
    }
    if result.is_empty() {
        "unnamed".to_owned()
    } else {
        result
    }
}

fn snake_case(value: &str) -> String {
    let mut result = String::new();
    for (index, character) in value.chars().enumerate() {
        if character.is_ascii_uppercase() && index > 0 {
            result.push('_');
        }
        if character.is_ascii_alphanumeric() || character == '_' {
            result.push(character.to_ascii_lowercase());
        } else if !result.ends_with('_') {
            result.push('_');
        }
    }
    match result.trim_matches('_') {
        "" => "unnamed".to_owned(),
        value => value.to_owned(),
    }
}

fn is_identifier(value: &str) -> bool {
    let mut chars = value.chars();
    matches!(chars.next(), Some(character) if character.is_ascii_alphabetic() || character == '_' || character == '$')
        && chars.all(|character| {
            character.is_ascii_alphanumeric() || character == '_' || character == '$'
        })
}

