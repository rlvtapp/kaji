/// Emits a portable MCP tool manifest. A future server runtime can consume the
/// same manifest without making the codegen crate depend on an MCP SDK.
#[derive(Default)]
pub struct McpToolManifest;

impl McpToolManifest {
    pub fn generate(&self, api: &Api, config: &ArtifactOptions) -> Result<Vec<GeneratedFile>> {
        let tools = api.operations.iter().map(|operation| {
            let mut properties = serde_json::Map::from_iter([(
                "path".to_owned(),
                json!({ "type": "string", "default": operation.path }),
            )]);
            if operation.request_body.is_some() {
                properties.insert("body".to_owned(), json!({}));
            }
            json!({
                "name": operation_identifier(&operation.id, config),
                "description": format!("{} {}", operation.method.as_str(), operation.path),
                "inputSchema": {
                    "type": "object",
                    "properties": properties,
                    "required": if operation.request_body.as_ref().is_some_and(|body| body.required) { json!(["body"]) } else { json!([]) },
                },
            })
        }).collect::<Vec<_>>();
        let manifest = json!({ "name": api.name, "version": api.version, "tools": tools });
        Ok(vec![GeneratedFile::new(
            extra_output_path(config, "mcp", "tools.json"),
            format!("{}\n", serde_json::to_string_pretty(&manifest)?),
        )?])
    }
}

fn extra_output_path(config: &ArtifactOptions, default_directory: &str, file: &str) -> String {
    if config.output_dir.is_some() {
        output_path(config, file)
    } else {
        format!("{default_directory}/{file}")
    }
}

fn render_zod(value: &SchemaValue) -> String {
    let primitive = match &value.kind {
        SchemaKind::Any => "z.unknown()".to_owned(),
        SchemaKind::Null => "z.null()".to_owned(),
        SchemaKind::Boolean => "z.boolean()".to_owned(),
        SchemaKind::Integer => "z.number().int()".to_owned(),
        SchemaKind::Number => "z.number()".to_owned(),
        SchemaKind::String => "z.string()".to_owned(),
        SchemaKind::Array { items } => format!("z.array({})", render_zod(items)),
        SchemaKind::Object {
            fields,
            additional_properties,
        } => {
            let fields = fields
                .iter()
                .map(|field| {
                    let optional = if field.required { "" } else { ".optional()" };
                    format!(
                        "{}: {}{}",
                        js_string(&field.name),
                        render_zod(&field.value),
                        optional
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            let object = format!("z.object({{ {fields} }})");
            match additional_properties {
                AdditionalProperties::Forbidden => format!("{object}.strict()"),
                AdditionalProperties::Any | AdditionalProperties::Unspecified => {
                    format!("{object}.catchall(z.unknown())")
                }
                AdditionalProperties::Schema { value } => {
                    format!("{object}.catchall({})", render_zod(value))
                }
            }
        }
        SchemaKind::Reference { reference } => format!(
            "z.lazy(() => {}Schema)",
            type_identifier(reference.rsplit('/').next().unwrap_or(reference))
        ),
        SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => {
            match variants.as_slice() {
                [] => "z.unknown()".to_owned(),
                [one] => render_zod(one),
                values => format!(
                    "z.union([{}])",
                    values.iter().map(render_zod).collect::<Vec<_>>().join(", ")
                ),
            }
        }
        SchemaKind::AllOf { variants } => match variants.as_slice() {
            [] => "z.unknown()".to_owned(),
            [one] => render_zod(one),
            values => values
                .iter()
                .skip(1)
                .fold(render_zod(&values[0]), |current, next| {
                    format!("z.intersection({current}, {})", render_zod(next))
                }),
        },
        SchemaKind::Not { .. } => "z.unknown()".to_owned(),
    };
    let constrained = if let Some(constant) = value.const_value.as_ref().and_then(zod_literal) {
        constant
    } else if !value.enum_values.is_empty() {
        let values = value
            .enum_values
            .iter()
            .filter_map(zod_literal)
            .collect::<Vec<_>>();
        if values.len() == 1 {
            values[0].clone()
        } else if values.is_empty() {
            primitive
        } else {
            format!("z.union([{}])", values.join(", "))
        }
    } else {
        primitive
    };
    if value.nullable {
        format!("{constrained}.nullable()")
    } else {
        constrained
    }
}

fn zod_literal(value: &Value) -> Option<String> {
    ts_literal(value).map(|literal| format!("z.literal({literal})"))
}

fn render_hooks(api: &Api, options: &ArtifactOptions, framework: &str, swr: bool) -> String {
    let mut output = if swr {
        format!("{NOTICE}\nimport useSWR from 'swr';\n")
    } else {
        format!("{NOTICE}\nimport {{ useMutation, useQuery }} from '{framework}';\n")
    };
    for operation in &api.operations {
        let read = matches!(operation.method, kaji_core::HttpMethod::Get);
        if swr && !read {
            continue;
        }
        let function = crate::sdk::lower_camel_identifier(&operation.id);
        let name = operation_identifier(&operation.id, options);
        let pascal = type_identifier(&operation.id);
        let group = if options.group_by_tag {
            format!("{}/", crate::sdk::operation_group(operation))
        } else {
            String::new()
        };
        let import = format!(
            "{}/{group}{function}",
            options.clients_import.trim_end_matches('/')
        );
        let _ = writeln!(
            output,
            "import {{ {function} }} from {};",
            js_string(&import)
        );
        if read {
            let _ = writeln!(
                output,
                "export const {name}QueryKey = (options: Parameters<typeof {function}>[0]) => [{}, options] as const;",
                js_string(&operation.id)
            );
            let hook = if swr {
                format!("useSWR({name}QueryKey(options), () => {function}(options))")
            } else {
                format!(
                    "useQuery({{ queryKey: {name}QueryKey(options), queryFn: () => {function}(options) }})"
                )
            };
            let _ = writeln!(
                output,
                "export function use{pascal}(options: Parameters<typeof {function}>[0]) {{ return {hook}; }}\n"
            );
        } else {
            let _ = writeln!(
                output,
                "export function use{pascal}() {{ return useMutation({{ mutationFn: (options: Parameters<typeof {function}>[0]) => {function}(options) }}); }}\n"
            );
        }
    }
    output
}

fn render_faker(value: &SchemaValue) -> String {
    if let Some(constant) = value.const_value.as_ref().and_then(ts_literal) {
        return constant;
    }
    if !value.enum_values.is_empty() {
        let values = value
            .enum_values
            .iter()
            .filter_map(ts_literal)
            .collect::<Vec<_>>();
        if !values.is_empty() {
            return format!("faker.helpers.arrayElement([{}])", values.join(", "));
        }
    }
    match &value.kind {
        SchemaKind::Any => {
            "faker.helpers.arrayElement([null, true, faker.string.alpha({ length: 8 })])".to_owned()
        }
        SchemaKind::Null => "null".to_owned(),
        SchemaKind::Boolean => "faker.datatype.boolean()".to_owned(),
        SchemaKind::Integer => "faker.number.int()".to_owned(),
        SchemaKind::Number => "faker.number.float()".to_owned(),
        SchemaKind::String => "faker.string.alpha({ length: 12 })".to_owned(),
        SchemaKind::Array { items } => {
            format!("Array.from({{ length: 2 }}, () => {})", render_faker(items))
        }
        SchemaKind::Object { fields, .. } => format!(
            "{{ {} }}",
            fields
                .iter()
                .map(|field| format!("{}: {}", js_string(&field.name), render_faker(&field.value)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        SchemaKind::Reference { reference } => format!(
            "create{}()",
            type_identifier(reference.rsplit('/').next().unwrap_or(reference))
        ),
        SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => variants
            .first()
            .map(render_faker)
            .unwrap_or_else(|| "undefined".to_owned()),
        SchemaKind::AllOf { variants } => variants
            .first()
            .map(render_faker)
            .unwrap_or_else(|| "undefined".to_owned()),
        SchemaKind::Not { .. } => "undefined".to_owned(),
    }
}

fn openapi_path_to_msw(path: &str) -> String {
    let mut output = String::new();
    for character in path.chars() {
        match character {
            '{' => output.push(':'),
            '}' => {}
            _ => output.push(character),
        }
    }
    output
}

fn html_escape(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

