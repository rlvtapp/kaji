/// Emits deterministic-looking Faker factories for every reusable schema.
#[derive(Default)]
pub struct TypeScriptFaker;

impl TypeScriptFaker {
    pub fn generate(&self, api: &Api, config: &ArtifactOptions) -> Result<Vec<GeneratedFile>> {
        let mut output = format!(
            "{NOTICE}\nimport {{ faker }} from '@faker-js/faker';\n{}
",
            model_import(api)
        );
        for schema in &api.schemas {
            let name = type_identifier(&schema.name);
            let _ = writeln!(output, "export function create{name}(): {name} {{");
            let _ = writeln!(
                output,
                "  return {} as {name};",
                render_faker(&schema.value)
            );
            output.push_str("}\n\n");
        }
        Ok(vec![GeneratedFile::new(
            extra_output_path(config, "typescript", "faker.ts"),
            output,
        )?])
    }
}

