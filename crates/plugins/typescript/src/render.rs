/// Explicit settings for standalone auxiliary artifacts. These renderers return
/// files; plugin authors decide how to publish them and their dependencies.
#[derive(Clone, Debug)]
pub struct ArtifactOptions {
    pub output_dir: Option<String>,
    pub package_name: Option<String>,
    pub naming: Naming,
    pub openapi_spec: Option<String>,
    pub title: Option<String>,
    /// Import prefix from the generated artifact to the operation modules.
    pub clients_import: String,
    pub group_by_tag: bool,
    /// Split auxiliary output at declaration boundaries near this byte budget.
    pub max_file_bytes: usize,
    pub layout: Option<kaji_core::SourceLayout>,
    pub fixture_options: crate::FixtureOptions,
    pub cypress_options: crate::CypressOptions,
}
impl Default for ArtifactOptions {
    fn default() -> Self {
        Self {
            output_dir: None,
            package_name: None,
            naming: Naming::CamelCase,
            openapi_spec: None,
            title: None,
            clients_import: "./clients".into(),
            group_by_tag: true,
            max_file_bytes: 128 * 1024,
            layout: None,
            fixture_options: Default::default(),
            cypress_options: Default::default(),
        }
    }
}
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Naming {
    #[default]
    CamelCase,
    PascalCase,
    SnakeCase,
}

/// Emits reusable TypeScript types from the normalized schema graph.
