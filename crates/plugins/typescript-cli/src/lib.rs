//! Generates a runnable TypeScript command-line client from Poolster's neutral API.
//!
//! The generated CLI intentionally owns only command wiring. Authentication,
//! OAuth refresh, credential persistence, request encoding, and output handling
//! live in one generated runtime module so every command follows the same rules.

use anyhow::{Result, bail};
use poolster_core::{
    Api, GeneratedFile, Operation, SchemaKind, SchemaValue, SecuritySchemeCatalog,
    SecuritySchemeKind,
    engine::{Language, Meta, Package, Plugin, PluginContext},
};
use serde_json::{Value, json};
use std::collections::BTreeMap;

const NOTICE: &str = "// Generated by Poolster. Do not edit.\n";

pub struct TypeScriptCli;

#[derive(Default)]
pub struct Settings {
    pub package_name: Option<String>,
}

impl Language for TypeScriptCli {
    const NAME: &'static str = "typescript-cli";
    type Settings = Settings;
    type Workspace = ();
}

pub fn package(dir: impl Into<String>) -> Package<TypeScriptCli> {
    Package::new(dir)
}

pub trait PackageExt {
    fn name(self, name: impl Into<String>) -> Self;
}

impl PackageExt for Package<TypeScriptCli> {
    fn name(mut self, name: impl Into<String>) -> Self {
        self.settings_mut().package_name = Some(name.into());
        self
    }
}

/// Provider-specific OAuth metadata. The OpenAPI security scheme describes
/// OAuth's standard authorization/token URLs; this configuration supplies the
/// public CLI client identity and optional device endpoint that OpenAPI cannot.
#[derive(Clone, Debug, Default)]
pub struct OAuthConfig {
    pub security_scheme: Option<String>,
    pub client_id: String,
    pub scopes: Vec<String>,
    pub preferred_flow: Option<String>,
    pub authorization_url: Option<String>,
    pub device_authorization_url: Option<String>,
    pub token_url: Option<String>,
    pub redirect_uri: Option<String>,
}

impl OAuthConfig {
    pub fn client_id(mut self, value: impl Into<String>) -> Self {
        self.client_id = value.into();
        self
    }
    pub fn security_scheme(mut self, value: impl Into<String>) -> Self {
        self.security_scheme = Some(value.into());
        self
    }
    pub fn scopes(mut self, values: impl IntoIterator<Item = impl Into<String>>) -> Self {
        self.scopes = values.into_iter().map(Into::into).collect();
        self
    }
    pub fn preferred_flow(mut self, value: impl Into<String>) -> Self {
        self.preferred_flow = Some(value.into());
        self
    }
    pub fn authorization_url(mut self, value: impl Into<String>) -> Self {
        self.authorization_url = Some(value.into());
        self
    }
    pub fn device_authorization_url(mut self, value: impl Into<String>) -> Self {
        self.device_authorization_url = Some(value.into());
        self
    }
    pub fn token_url(mut self, value: impl Into<String>) -> Self {
        self.token_url = Some(value.into());
        self
    }
    pub fn redirect_uri(mut self, value: impl Into<String>) -> Self {
        self.redirect_uri = Some(value.into());
        self
    }
}

pub struct Cli {
    meta: Meta,
    command_name: Option<String>,
    base_url: Option<String>,
    oauth: Option<OAuthConfig>,
}

pub fn cli() -> Cli {
    Cli {
        meta: Meta::new(),
        command_name: None,
        base_url: None,
        oauth: None,
    }
}

impl Cli {
    pub fn command_name(mut self, value: impl Into<String>) -> Self {
        self.command_name = Some(value.into());
        self
    }
    pub fn base_url(mut self, value: impl Into<String>) -> Self {
        self.base_url = Some(value.into());
        self
    }
    pub fn oauth(mut self, value: OAuthConfig) -> Self {
        self.oauth = Some(value);
        self
    }
}

impl Plugin<TypeScriptCli> for Cli {
    fn kind(&self) -> &'static str {
        "typescript-cli"
    }
    fn meta(&self) -> &Meta {
        &self.meta
    }
    fn generate(&self, cx: &mut PluginContext<'_, TypeScriptCli>) -> Result<()> {
        let command_name = self
            .command_name
            .clone()
            .unwrap_or_else(|| kebab_case(&cx.api.name));
        if command_name.is_empty() {
            bail!("TypeScript CLI command name cannot be empty");
        }
        let package_name = cx
            .settings
            .package_name
            .clone()
            .unwrap_or_else(|| format!("{}-cli", command_name));
        let config = render_config(
            &command_name,
            self.base_url.as_deref(),
            self.oauth.as_ref(),
            cx.security_schemes,
        )?;
        cx.files.emit(GeneratedFile::new(
            "package.json",
            render_package_json(&package_name, &command_name, &cx.api.version),
        )?)?;
        cx.files
            .emit(GeneratedFile::new("tsconfig.json", render_tsconfig())?)?;
        for (path, source) in render_command_modules(cx.api, &command_name, &config) {
            cx.files.emit(GeneratedFile::new(path, source)?)?;
        }
        cx.files
            .emit(GeneratedFile::new("src/runtime.ts", render_runtime())?)?;
        cx.files.emit_custom(GeneratedFile::new(
            "src/poolster.extension.ts",
            render_extension(),
        )?)?;
        cx.files.emit(GeneratedFile::new(
            "README.md",
            render_readme(cx.api, &package_name, &command_name, self.oauth.is_some()),
        )?)?;
        for (group, reference) in render_skill_references(cx.api, &command_name) {
            cx.files.emit(GeneratedFile::new(
                format!("references/{group}.md"),
                reference,
            )?)?;
        }
        Ok(())
    }
}

fn render_package_json(package_name: &str, command_name: &str, version: &str) -> String {
    format!(
        "{{\n  \"name\": {package_name:?},\n  \"version\": {version:?},\n  \"private\": true,\n  \"description\": \"Generated API CLI\",\n  \"type\": \"module\",\n  \"bin\": {{ {command_name:?}: \"dist/index.js\" }},\n  \"files\": [\"dist\", \"references\", \"README.md\"],\n  \"scripts\": {{ \"build\": \"tsc\", \"start\": \"node dist/index.js\" }},\n  \"engines\": {{ \"node\": \">=20\" }},\n  \"dependencies\": {{ \"commander\": \"^13.0.0\" }},\n  \"devDependencies\": {{ \"@types/node\": \"^22.0.0\", \"typescript\": \"^5.7.0\" }}\n}}\n"
    )
}

fn render_tsconfig() -> &'static str {
    "{\n  \"compilerOptions\": {\n    \"target\": \"ES2022\",\n    \"module\": \"NodeNext\",\n    \"moduleResolution\": \"NodeNext\",\n    \"outDir\": \"dist\",\n    \"rootDir\": \"src\",\n    \"strict\": true,\n    \"esModuleInterop\": true,\n    \"skipLibCheck\": true\n  },\n  \"include\": [\"src/**/*.ts\"]\n}\n"
}

fn render_extension() -> &'static str {
    "// This file is created once and never overwritten by Poolster.\n// Add provider-specific authentication, login, logging, tracing, or request customization here.\nimport type { CliExtension } from './runtime.js';\n\nexport const extension: CliExtension = {\n  // async authenticate({ headers }) { headers.set('authorization', `Bearer ${await readFromKeychain()}`); return 'handled'; },\n  // async login({ defaultLogin }) { return defaultLogin(); },\n  // async beforeRequest({ operation, url }) { console.debug(operation.id, url.toString()); },\n  // async afterResponse({ operation, response }) { console.info(operation.id, response.status); },\n};\n"
}

fn render_config(
    command_name: &str,
    base_url: Option<&str>,
    oauth: Option<&OAuthConfig>,
    catalog: Option<&SecuritySchemeCatalog>,
) -> Result<Value> {
    let schemes = catalog
        .map(|catalog| {
            catalog
                .schemes
                .iter()
                .map(|scheme| {
                    let value = match &scheme.kind {
                        SecuritySchemeKind::ApiKey { name, location } => json!({
                            "type": "apiKey", "name": name, "location": location,
                        }),
                        SecuritySchemeKind::Http { scheme, .. } => {
                            json!({ "type": "http", "scheme": scheme })
                        }
                        SecuritySchemeKind::OAuth2 { flows, .. } => json!({
                            "type": "oauth2",
                            "flows": flows.iter().map(|flow| json!({
                                "type": flow.flow_type,
                                "authorizationUrl": flow.authorization_url,
                                "tokenUrl": flow.token_url,
                                "scopes": flow.scopes,
                            })).collect::<Vec<_>>(),
                        }),
                        SecuritySchemeKind::OpenIdConnect { discovery_url } => {
                            json!({ "type": "openIdConnect", "discoveryUrl": discovery_url })
                        }
                        SecuritySchemeKind::Other { type_name } => {
                            json!({ "type": "other", "name": type_name })
                        }
                    };
                    (scheme.name.clone(), value)
                })
                .collect::<serde_json::Map<String, Value>>()
        })
        .unwrap_or_default();
    let oauth = oauth.map(|oauth| {
        let inferred = oauth
            .security_scheme
            .as_ref()
            .and_then(|name| schemes.get(name))
            .and_then(|scheme| scheme.get("flows"))
            .and_then(Value::as_array)
            .and_then(|flows| flows.first());
        json!({
            "securityScheme": oauth.security_scheme,
            "clientId": oauth.client_id,
            "scopes": oauth.scopes,
            "preferredFlow": oauth.preferred_flow.as_deref().unwrap_or("device"),
            "authorizationUrl": oauth.authorization_url.as_deref().or_else(|| inferred.and_then(|flow| flow.get("authorizationUrl")).and_then(Value::as_str)),
            "deviceAuthorizationUrl": oauth.device_authorization_url,
            "tokenUrl": oauth.token_url.as_deref().or_else(|| inferred.and_then(|flow| flow.get("tokenUrl")).and_then(Value::as_str)),
            "redirectUri": oauth.redirect_uri.as_deref().unwrap_or("http://127.0.0.1:8765/callback"),
        })
    });
    if let Some(oauth) = &oauth {
        if oauth["clientId"].as_str().is_none_or(str::is_empty) {
            bail!("typescript-cli oauth.client_id cannot be empty");
        }
        if oauth["tokenUrl"].as_str().is_none_or(str::is_empty) {
            bail!(
                "typescript-cli OAuth requires token_url or an OAuth2 OpenAPI security scheme with tokenUrl"
            );
        }
    }
    Ok(json!({
        "commandName": command_name,
        "baseUrl": base_url,
        "baseUrlEnvironment": format!("{}_BASE_URL", env_name(command_name)),
        "tokenEnvironment": format!("{}_TOKEN", env_name(command_name)),
        "oauth": oauth,
        "schemes": schemes,
    }))
}

/// Keep small CLIs source-compatible, but isolate large command metadata from
/// startup/runtime code. Bound chunks by both serialized bytes and operation count.
fn render_command_modules(api: &Api, command_name: &str, config: &Value) -> Vec<(String, String)> {
    let operations = api
        .operations
        .iter()
        .map(|op| operation_json(api, op, command_name))
        .collect::<Vec<_>>();
    let literal = serde_json::to_string_pretty(&operations).unwrap();
    let index = render_index(api, command_name, config);
    if operations.len() <= 50 && literal.len() <= 128 * 1024 {
        return vec![("src/index.ts".into(), index)];
    }
    let mut chunks = Vec::new();
    let mut current = Vec::new();
    let mut bytes = 0usize;
    for operation in operations {
        let size = serde_json::to_string_pretty(&operation).unwrap().len();
        if !current.is_empty() && (current.len() >= 50 || bytes + size > 128 * 1024) {
            chunks.push(std::mem::take(&mut current));
            bytes = 0;
        }
        bytes += size;
        current.push(operation);
    }
    if !current.is_empty() {
        chunks.push(current);
    }
    let mut imports = String::new();
    let mut references = Vec::new();
    let mut files = Vec::new();
    for (index, chunk) in chunks.into_iter().enumerate() {
        let name = format!("operations{index:04}");
        imports.push_str(&format!(
            "import {{ {name} }} from './commands/chunk_{index:04}.js';\n"
        ));
        references.push(format!("...{name}"));
        files.push((format!("src/commands/chunk_{index:04}.ts"), format!("{NOTICE}import type {{ Operation }} from '../runtime.js';\nexport const {name}: readonly Operation[] = {};\n",serde_json::to_string_pretty(&chunk).unwrap())));
    }
    let index = index.replace(
        &format!("const operations: readonly Operation[] = {literal};"),
        &format!(
            "const operations: readonly Operation[] = [{}];",
            references.join(", ")
        ),
    );
    files.insert(0, ("src/index.ts".into(), format!("{imports}{index}")));
    files
}

fn render_index(api: &Api, command_name: &str, config: &Value) -> String {
    let operations = api
        .operations
        .iter()
        .map(|operation| operation_json(api, operation, command_name))
        .collect::<Vec<_>>();
    let template = r#"import { Command } from 'commander';
import { extension } from './poolster.extension.js';
import { authLogin, authLogout, authProfiles, authSetKey, authSetToken, authStatus, authUseProfile, formatCliError, runOperation, type CliConfig, type Operation } from './runtime.js';

const config = __CONFIG__ as const satisfies CliConfig;
const operations: readonly Operation[] = __OPERATIONS__;

const program = new Command().name(__COMMAND_NAME__).description(__API_NAME__).version(__API_VERSION__);

const auth = program.command('auth').description('Manage API credentials');
auth.command('set-token [token]').description('Store an API token in the local credential store').option('--profile <name>', 'credential profile').option('--scheme <name>', 'OpenAPI security scheme').action(async (token, options) => authSetToken(config, options.profile, options.scheme, token));
auth.command('set-key [key]').description('Store an API key; infers the OpenAPI API-key scheme').option('--profile <name>', 'credential profile').option('--scheme <name>', 'only needed when the API has multiple key schemes').action(async (key, options) => authSetKey(config, options.profile, options.scheme, key));
auth.command('login').description('Sign in with OAuth').option('--profile <name>', 'credential profile').option('--flow <device|browser>', 'OAuth flow').action(async (options) => authLogin(config, options.profile, options.flow, extension));
auth.command('status').description('Show local credential status').option('--profile <name>', 'credential profile').action(async (options) => authStatus(config, options.profile));
auth.command('profiles').description('List credential profiles').action(async () => authProfiles(config));
auth.command('use <name>').description('Use a profile by default').action(async (name) => authUseProfile(config, name));
auth.command('logout').description('Remove a local credential profile').option('--profile <name>', 'credential profile').action(async (options) => authLogout(config, options.profile));

for (const operation of operations) {
  let command = program;
  for (const name of operation.command) {
    command = command.commands.find((candidate) => candidate.name() === name) ?? command.command(name);
  }
  command.description(`${operation.method} ${operation.path}`);
  command.option('--profile <name>', 'credential profile');
  command.option('--base-url <url>', 'API base URL');
  command.option('--json', 'print compact JSON');
  command.option('--data <json>', 'JSON request body (for complex bodies)');
  command.option('--data-file <file>', 'JSON request body file (for complex bodies)');
  for (const parameter of operation.parameters) {
    command.option(`--${parameter.option} <value>`, parameter.description ?? parameter.name);
  }
  for (const field of operation.bodyFields) {
    if (field.array) command.option(`--${field.option} <value>`, field.description ?? field.name, (value: string, previous: string[] = []) => [...previous, value]);
    else command.option(`--${field.option} <value>`, field.description ?? field.name);
    if (field.file) command.option(`--${field.option}-file <file>`, `read ${field.name} from a file`);
  }
  command.action(async (options) => runOperation(config, operation, options, extension));
}

program.parseAsync().catch((error: unknown) => {
  console.error(formatCliError(error));
  process.exitCode = 1;
});
"#;
    format!(
        "{NOTICE}{}",
        template
            .replace(
                "__CONFIG__",
                &serde_json::to_string_pretty(config).expect("serializable CLI config")
            )
            .replace(
                "__OPERATIONS__",
                &serde_json::to_string_pretty(&operations).expect("serializable CLI operations")
            )
            .replace(
                "__COMMAND_NAME__",
                &serde_json::to_string(command_name).expect("serializable command name")
            )
            .replace(
                "__API_NAME__",
                &serde_json::to_string(&api.name).expect("serializable API name")
            )
            .replace(
                "__API_VERSION__",
                &serde_json::to_string(&api.version).expect("serializable API version")
            )
    )
}

