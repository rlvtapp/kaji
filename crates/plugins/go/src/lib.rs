fn render_cursor_pager(output: &mut String, api: &Api, operation: &Operation) {
    let Some(pagination) = cursor_pagination(api, operation) else {
        return;
    };
    let GoResponseKind::Json(response_type) = operation_response_kind(operation) else {
        return;
    };
    let operation_name = go_type_name(&operation.id);
    let request_name = operation_request_name(api, operation);
    let pager_name = format!("{operation_name}Pager");
    let cursor_update = match &pagination.location {
        GoCursorLocation::Parameter { name, optional } => {
            let field = name;
            if *optional {
                format!("\tif pager.started {{ pager.input.{field} = &pager.cursor }}\n")
            } else {
                format!("\tif pager.started {{ pager.input.{field} = pager.cursor }}\n")
            }
        }
        GoCursorLocation::RequestBody {
            body_type,
            field_name,
            body_required,
        } => {
            if *body_required {
                format!(
                    "\tif pager.started {{\n\t\tbodyCopy := pager.input.Body\n\t\tbodyCopy.{field_name} = &pager.cursor\n\t\tpager.input.Body = bodyCopy\n\t}}\n"
                )
            } else {
                format!(
                    "\tif pager.started {{\n\t\tif pager.input.Body == nil {{ return nil, fmt.Errorf(\"poolster: cursor pagination requires a {body_type} body\") }}\n\t\tbodyCopy := *pager.input.Body\n\t\tbodyCopy.{field_name} = &pager.cursor\n\t\tpager.input.Body = &bodyCopy\n\t}}\n"
                )
            }
        }
    };
    let body_preflight = match &pagination.location {
        GoCursorLocation::RequestBody {
            body_type,
            body_required: false,
            ..
        } => format!(
            "\tif pager.input.Body == nil {{ return nil, fmt.Errorf(\"poolster: cursor pagination requires a {body_type} body\") }}\n"
        ),
        _ => String::new(),
    };
    let _ = writeln!(
        output,
        "// {pager_name} iterates pages returned by {operation_name}."
    );
    let _ = writeln!(output, "type {pager_name} struct {{");
    let _ = writeln!(
        output,
        "\tclient *Client\n\tinput *{request_name}\n\tcursor string\n\tstarted bool\n\tdone bool\n}}"
    );
    let _ = writeln!(
        output,
        "// {operation_name}Pages starts cursor pagination without guessing fields from a response."
    );
    let _ = writeln!(
        output,
        "func (client *Client) {operation_name}Pages(input *{request_name}) *{pager_name} {{"
    );
    let _ = writeln!(output, "\tcopyInput := &{request_name}{{}}");
    output.push_str("\tif input != nil { *copyInput = *input }\n");
    let _ = writeln!(
        output,
        "\treturn &{pager_name}{{client: client, input: copyInput}}\n}}"
    );
    let _ = writeln!(
        output,
        "// Next returns the next full response page, or io.EOF after the final page."
    );
    let _ = writeln!(
        output,
        "func (pager *{pager_name}) Next(ctx context.Context) (*{response_type}, error) {{"
    );
    output.push_str("\tif pager.done { return nil, io.EOF }\n");
    output.push_str(&body_preflight);
    output.push_str(&cursor_update);
    let _ = writeln!(
        output,
        "\tresponse, err := pager.client.{operation_name}(ctx, pager.input)"
    );
    output.push_str("\tif err != nil { return nil, err }\n");
    let _ = writeln!(
        output,
        "\tcursor, ok := poolsterPaginationString(response, {:?})",
        pagination.next_cursor_path
    );
    output.push_str("\tif !ok { pager.done = true; return response, nil }\n\tpager.cursor = cursor\n\tpager.started = true\n\treturn response, nil\n}\n\n");
}

fn render_offset_pager(output: &mut String, api: &Api, operation: &Operation) {
    let Some(pagination) = offset_pagination(api, operation) else {
        return;
    };
    let GoResponseKind::Json(response_type) = operation_response_kind(operation) else {
        return;
    };
    let operation_name = go_type_name(&operation.id);
    let request_name = operation_request_name(api, operation);
    let pager_name = format!("{operation_name}Pager");
    let offset_field = &pagination.offset_name;
    let limit_field = &pagination.limit_name;
    let _ = writeln!(
        output,
        "// {pager_name} iterates declared offset/limit pages returned by {operation_name}."
    );
    let _ = writeln!(output, "type {pager_name} struct {{");
    let _ = writeln!(
        output,
        "\tclient *Client\n\tinput *{request_name}\n\toffset int64\n\tlimit *int64\n\tdone bool\n}}"
    );
    let _ = writeln!(
        output,
        "// {operation_name}Pages starts declared offset/limit pagination."
    );
    let _ = writeln!(
        output,
        "func (client *Client) {operation_name}Pages(input *{request_name}) *{pager_name} {{"
    );
    let _ = writeln!(output, "\tcopyInput := &{request_name}{{}}");
    output.push_str("\tif input != nil { *copyInput = *input }\n");
    let _ = writeln!(output, "\toffset := int64(0)");
    let _ = writeln!(
        output,
        "\tif copyInput.{offset_field} != nil {{ offset = *copyInput.{offset_field} }}"
    );
    let _ = writeln!(
        output,
        "\treturn &{pager_name}{{client: client, input: copyInput, offset: offset, limit: copyInput.{limit_field}}}\n}}"
    );
    let _ = writeln!(
        output,
        "// Next returns the next full response page, or io.EOF after the final page."
    );
    let _ = writeln!(
        output,
        "func (pager *{pager_name}) Next(ctx context.Context) (*{response_type}, error) {{"
    );
    output.push_str("\tif pager.done { return nil, io.EOF }\n");
    let _ = writeln!(output, "\tpager.input.{offset_field} = &pager.offset");
    let _ = writeln!(
        output,
        "\tresponse, err := pager.client.{operation_name}(ctx, pager.input)"
    );
    output.push_str("\tif err != nil { return nil, err }\n");
    let _ = writeln!(
        output,
        "\tcount, ok := poolsterPaginationArrayLen(response, {:?})",
        pagination.results_path
    );
    output.push_str("\tif !ok || count == 0 { pager.done = true; return response, nil }\n");
    output.push_str("\tpager.offset += int64(count)\n");
    output
        .push_str("\tif pager.limit != nil && int64(count) < *pager.limit { pager.done = true }\n");
    output.push_str("\treturn response, nil\n}\n\n");
}

fn render_url_pager(output: &mut String, api: &Api, operation: &Operation) {
    let Some(pagination) = url_pagination(api, operation) else {
        return;
    };
    let GoResponseKind::Json(response_type) = operation_response_kind(operation) else {
        return;
    };
    let operation_name = go_type_name(&operation.id);
    let request_name = operation_request_name(api, operation);
    let pager_name = format!("{operation_name}Pager");
    let has_input = !operation.parameters.is_empty() || operation.request_body.is_some();
    let input_field = if has_input {
        format!("\tinput *{request_name}\n")
    } else {
        String::new()
    };
    let constructor_input = if has_input {
        format!("input *{request_name}")
    } else {
        String::new()
    };
    let constructor_copy = if has_input {
        format!(
            "\tcopyInput := &{request_name}{{}}\n\tif input != nil {{ *copyInput = *input }}\n\treturn &{pager_name}{{client: client, input: copyInput}}\n"
        )
    } else {
        format!("\treturn &{pager_name}{{client: client}}\n")
    };
    let initial_call = if has_input {
        format!("pager.client.{operation_name}(ctx, pager.input)")
    } else {
        format!("pager.client.{operation_name}(ctx)")
    };
    let mut continuation_prep = String::from("\theaders := http.Header{}\n");
    if has_input {
        render_pagination_headers(&mut continuation_prep, operation);
    }
    if has_input && operation.request_body.is_some() {
        continuation_prep.push_str("\tbody := pager.input.Body\n");
    } else {
        continuation_prep.push_str("\tvar body any\n");
    }
    let error_expression = operation_error_expression(operation, "err");
    let _ = writeln!(
        output,
        "// {pager_name} follows declared same-origin continuation URLs for {operation_name}."
    );
    let _ = writeln!(output, "type {pager_name} struct {{");
    let _ = writeln!(
        output,
        "\tclient *Client\n{input_field}\tnextURL string\n\tstarted bool\n\tdone bool\n}}"
    );
    let _ = writeln!(
        output,
        "// {operation_name}Pages starts URL pagination using the operation's normal typed request.\nfunc (client *Client) {operation_name}Pages({constructor_input}) *{pager_name} {{"
    );
    output.push_str(&constructor_copy);
    output.push_str("}\n");
    let _ = writeln!(
        output,
        "// Next returns the next full response page, or io.EOF after the final page.\nfunc (pager *{pager_name}) Next(ctx context.Context) (*{response_type}, error) {{"
    );
    output.push_str("\tif pager.done { return nil, io.EOF }\n");
    output.push_str("\tif !pager.started {\n");
    let _ = writeln!(output, "\t\tresponse, err := {initial_call}");
    output.push_str("\t\tif err != nil { return nil, err }\n");
    let _ = writeln!(
        output,
        "\t\tnextURL, ok := poolsterPaginationString(response, {:?})",
        pagination.next_url_path
    );
    output.push_str("\t\tpager.started = true\n\t\tif !ok { pager.done = true; return response, nil }\n\t\tpager.nextURL = nextURL\n\t\treturn response, nil\n\t}\n");
    output.push_str(&continuation_prep);
    let _ = writeln!(
        output,
        "\trequest, err := pager.client.newPaginationRequest(ctx, {:?}, pager.nextURL, headers, body)",
        operation.method.as_str()
    );
    let _ = writeln!(
        output,
        "\tif err != nil {{ return nil, {error_expression} }}"
    );
    let _ = writeln!(output, "\tvar response {response_type}");
    let _ = writeln!(
        output,
        "\tif err := pager.client.doWithRetry(request, &response); err != nil {{ return nil, {error_expression} }}"
    );
    let _ = writeln!(
        output,
        "\tnextURL, ok := poolsterPaginationString(&response, {:?})",
        pagination.next_url_path
    );
    output.push_str("\tif !ok { pager.done = true } else { pager.nextURL = nextURL }\n\treturn &response, nil\n}\n\n");
}

fn render_pagination_headers(output: &mut String, operation: &Operation) {
    for parameter in &operation.parameters {
        if parameter.location != "header" {
            continue;
        }
        let field = format!("pager.input.{}", parameter_field_name(operation, parameter));
        if parameter.required {
            let _ = writeln!(
                output,
                "\theaders.Set({:?}, fmt.Sprint({field}))",
                parameter.name
            );
        } else {
            let _ = writeln!(
                output,
                "\tif {field} != nil {{ headers.Set({:?}, fmt.Sprint(*{field})) }}",
                parameter.name
            );
        }
    }
}

fn parameter_field_name(operation: &Operation, parameter: &OperationParameter) -> String {
    let preferred: Vec<_> = operation
        .parameters
        .iter()
        .map(|parameter| go_type_name(&parameter.name))
        .collect();
    let mut reserved: BTreeSet<_> = preferred.iter().cloned().collect();
    let mut used = BTreeSet::new();
    if operation.request_body.is_some() {
        reserved.insert("Body".into());
        used.insert("Body".into());
    }
    for (index, candidate) in operation.parameters.iter().enumerate() {
        let base = &preferred[index];
        let collision =
            preferred.iter().filter(|name| *name == base).count() > 1 || used.contains(base);
        let mut name = if collision {
            format!("{}{base}", go_type_name(&candidate.location))
        } else {
            base.clone()
        };
        let seed = name.clone();
        let mut suffix = 2;
        while used.contains(&name) || (name != *base && reserved.contains(&name)) {
            name = format!("{seed}{suffix}");
            suffix += 1;
        }
        used.insert(name.clone());
        if std::ptr::eq(candidate, parameter) {
            return name;
        }
    }
    unreachable!("parameter belongs to the operation")
}

fn render_parameter_field(output: &mut String, parameter: &OperationParameter, name: &str) {
    let mut value_type = parameter
        .schema
        .as_ref()
        .map(go_type)
        .unwrap_or_else(|| "any".into());
    if !parameter.required && parameter.location != "path" && !value_type.starts_with('*') {
        value_type = format!("*{value_type}");
    }
    let _ = writeln!(
        output,
        "\t{name} {value_type} `json:\"{},omitempty\"`",
        parameter.name
    );
}

fn render_parameter_use(
    output: &mut String,
    parameter: &OperationParameter,
    name: &str,
    response_kind: &GoResponseKind,
) {
    let field = format!("input.{name}");
    if parameter.location != "querystring" {
        if let Some(content) = poolster_core::openapi32::parameter_content(parameter)
            .expect("validated parameter content")
            .first()
        {
            let value = format!("poolsterContent{name}");
            let present = format!("poolsterPresent{name}");
            let error = format!("poolsterError{name}");
            let _ = writeln!(
                output,
                "\t{value}, {present}, {error} := poolsterParameterContent({field}, {:?})\n\tif {error} != nil {{",
                content.content_type
            );
            render_error_return(output, response_kind, &error);
            output.push_str("\t}\n");
            let _ = writeln!(output, "\tif {present} {{");
            match parameter.location.as_str() {
                "query" => {
                    let _ = writeln!(output, "\t\tquery.Add({:?}, {value})", parameter.name);
                }
                "path" => {
                    let _ = writeln!(
                        output,
                        "\t\tpath = strings.ReplaceAll(path, {:?}, url.PathEscape({value}))",
                        format!("{{{}}}", parameter.name)
                    );
                }
                "header" => {
                    let _ = writeln!(output, "\t\theaders.Set({:?}, {value})", parameter.name);
                }
                "cookie" => {
                    let _ = writeln!(
                        output,
                        "\t\theaders.Add(\"Cookie\", {:?} + \"=\" + strings.ReplaceAll(url.QueryEscape({value}), \"+\", \"%20\"))",
                        parameter.name
                    );
                }
                _ => {}
            }
            output.push_str("\t}\n");
            return;
        }
    }
    match parameter.location.as_str() {
        "path" => {
            let _ = writeln!(
                output,
                "\tpath = strings.ReplaceAll(path, {:?}, url.PathEscape(fmt.Sprint({field})))",
                format!("{{{}}}", parameter.name)
            );
        }
        "querystring" => {
            let content = poolster_core::openapi32::parameter_content(parameter)
                .expect("validated content metadata")
                .into_iter()
                .next()
                .unwrap_or_else(|| poolster_core::openapi32::ContentDefinition {
                    content_type: "text/plain".into(),
                    ..Default::default()
                });
            let content_type = content.content_type.clone();
            let metadata = serde_json::to_string(&content).expect("typed content metadata");
            let _ = writeln!(
                output,
                "\tencodedQuery, queryError := poolsterWholeQuery({field}, {content_type:?}, {metadata:?})\n\tif queryError != nil {{"
            );
            render_error_return(output, response_kind, "queryError");
            output.push_str("\t}\n\twholeQuery = encodedQuery\n");
        }
        "query" => {
            let _ = writeln!(
                output,
                "\tif err := addQuery(query, {:?}, {field}); err != nil {{",
                parameter.name
            );
            render_error_return(output, response_kind, "err");
            output.push_str("\t}\n");
        }
        "header" => {
            if parameter.required {
                let _ = writeln!(
                    output,
                    "\theaders.Set({:?}, fmt.Sprint({field}))",
                    parameter.name
                );
            } else {
                let _ = writeln!(
                    output,
                    "\tif {field} != nil {{ headers.Set({:?}, fmt.Sprint(*{field})) }}",
                    parameter.name
                );
            }
        }
        _ => {}
    }
}

fn render_error_return(output: &mut String, response_kind: &GoResponseKind, error: &str) {
    match response_kind {
        GoResponseKind::None => {
            let _ = writeln!(output, "\t\treturn {error}");
        }
        GoResponseKind::Text => {
            let _ = writeln!(output, "\t\treturn \"\", {error}");
        }
        GoResponseKind::Json(_) | GoResponseKind::Binary | GoResponseKind::EventStream => {
            let _ = writeln!(output, "\t\treturn nil, {error}");
        }
    }
}

fn operation_response_type(operation: &Operation) -> Option<String> {
    operation.success_schema().map(go_type)
}

fn go_type(value: &SchemaValue) -> String {
    let value_type = match &value.kind {
        SchemaKind::Any | SchemaKind::Null | SchemaKind::Not { .. } => "any".into(),
        SchemaKind::Boolean => "bool".into(),
        SchemaKind::Integer => "int64".into(),
        SchemaKind::Number => "float64".into(),
        SchemaKind::String => match value.format.as_deref() {
            Some("binary") | Some("byte") => "[]byte".into(),
            _ => "string".into(),
        },
        SchemaKind::Array { items } => format!("[]{}", go_type(items)),
        SchemaKind::Object {
            additional_properties,
            ..
        } => match additional_properties {
            AdditionalProperties::Schema { value } => format!("map[string]{}", go_type(value)),
            _ => "map[string]any".into(),
        },
        SchemaKind::Reference { reference } => go_type_name(
            &reference
                .rsplit('/')
                .next()
                .unwrap_or(reference)
                .replace("~1", "/")
                .replace("~0", "~"),
        ),
        SchemaKind::OneOf { .. } | SchemaKind::AnyOf { .. } | SchemaKind::AllOf { .. } => {
            "json.RawMessage".into()
        }
    };
    if (value.nullable || value.nullish) && value_type != "any" && !value_type.starts_with('*') {
        format!("*{value_type}")
    } else {
        value_type
    }
}

fn resource_operations(api: &Api) -> BTreeMap<String, Vec<&Operation>> {
    let mut resources = BTreeMap::<String, Vec<&Operation>>::new();
    for operation in &api.operations {
        resources
            .entry(go_type_name(&resource_name(operation)))
            .or_default()
            .push(operation);
    }
    resources
}

fn resource_name(operation: &Operation) -> String {
    operation
        .annotations
        .get("tags")
        .and_then(|tags| tags.as_array())
        .and_then(|tags| tags.first())
        .and_then(|tag| tag.as_str())
        .filter(|tag| !tag.trim().is_empty())
        .map(str::to_owned)
        .or_else(|| {
            operation
                .path
                .split('/')
                .filter(|segment| !segment.is_empty() && !segment.starts_with('{'))
                .find(|segment| {
                    !matches!(*segment, "api" | "email") && !is_version_segment(segment)
                })
                .map(str::to_owned)
        })
        .unwrap_or_else(|| "api".into())
}

fn is_version_segment(segment: &str) -> bool {
    let mut characters = segment.chars();
    matches!(characters.next(), Some('v' | 'V'))
        && characters
            .next()
            .is_some_and(|character| character.is_ascii_digit())
}

/// Go selectors share a namespace with methods. A resource whose generated
/// field matches any direct operation therefore receives a stable `Resource`
/// suffix instead of producing an uncompilable client (for example an
/// `auth-check` resource alongside `Client.AuthCheck`).
fn resource_facade_names(
    resources: &BTreeMap<String, Vec<&Operation>>,
) -> BTreeMap<String, String> {
    let operations: BTreeSet<_> = resources
        .values()
        .flatten()
        .map(|operation| go_type_name(&operation.id))
        .collect();
    let mut reserved = operations.clone();
    reserved.extend(resources.keys().cloned());
    let mut names = BTreeMap::new();
    for resource in resources.keys() {
        let mut name = resource.clone();
        if operations.contains(resource) {
            name.push_str("Resource");
            while reserved.contains(&name) {
                name.push_str("Resource");
            }
        }
        reserved.insert(name.clone());
        names.insert(resource.clone(), name);
    }
    names
}

fn resource_method_name(operation: &str, resource: &str) -> String {
    let singular = resource.strip_suffix('s').unwrap_or(resource);
    let mut method = operation;
    while let Some(shorter) = method
        .strip_prefix(resource)
        .or_else(|| method.strip_prefix(singular))
        .filter(|value| !value.is_empty() && value.len() < method.len())
    {
        method = shorter;
    }
    method
        .strip_suffix(resource)
        .or_else(|| method.strip_suffix(singular))
        .filter(|method| !method.is_empty())
        .unwrap_or(method)
        .into()
}

fn render_namespaced_operation(
    output: &mut String,
    api: &Api,
    resource: &str,
    facade: &str,
    method: &str,
    direct: &str,
    operation: &Operation,
) {
    let request = operation_request_name(api, operation);
    let has_input = !operation.parameters.is_empty() || operation.request_body.is_some();
    let parameters = if has_input {
        format!(", input *{request}")
    } else {
        String::new()
    };
    let result = match operation_response_kind(operation) {
        GoResponseKind::None => "error".to_owned(),
        GoResponseKind::Json(response) => format!("(*{response}, error)"),
        GoResponseKind::Text => "(string, error)".to_owned(),
        GoResponseKind::Binary => "([]byte, error)".to_owned(),
        GoResponseKind::EventStream => "(io.ReadCloser, error)".to_owned(),
    };
    let _ = writeln!(
        output,
        "// {method} invokes {direct} through the {resource} namespace.\nfunc (service *{facade}Service) {method}(ctx context.Context{parameters}) {result} {{"
    );
    if has_input {
        let _ = writeln!(output, "\treturn service.client.{direct}(ctx, input)\n}}\n");
    } else {
        let _ = writeln!(output, "\treturn service.client.{direct}(ctx)\n}}\n");
    }
}

