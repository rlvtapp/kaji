fn resource_operations(api: &Api) -> BTreeMap<String, Vec<&Operation>> {
    let mut resources = BTreeMap::<String, Vec<&Operation>>::new();
    for operation in &api.operations {
        resources
            .entry(resource_name(operation))
            .or_default()
            .push(operation);
    }
    resources
}

fn resource_name(operation: &Operation) -> String {
    operation
        .annotations
        .get("tags")
        .and_then(|tags| tags.as_array())
        .and_then(|tags| tags.first())
        .and_then(|tag| tag.as_str())
        .filter(|tag| !tag.trim().is_empty())
        .map(str::to_owned)
        .or_else(|| {
            operation
                .path
                .split('/')
                .filter(|segment| !segment.is_empty() && !segment.starts_with('{'))
                .find(|segment| {
                    !matches!(*segment, "api" | "email") && !is_version_segment(segment)
                })
                .map(str::to_owned)
        })
        .unwrap_or_else(|| "api".into())
}

fn is_version_segment(segment: &str) -> bool {
    let mut characters = segment.chars();
    matches!(characters.next(), Some('v' | 'V'))
        && characters
            .next()
            .is_some_and(|character| character.is_ascii_digit())
}

fn render_resource_chunk(
    api: &Api,
    resource: &str,
    all_operations: &[&Operation],
    operations: &[&Operation],
    index: usize,
) -> String {
    let class = format!("{}Resource", pascal_case(resource));
    let attribute = resource_attribute(resource, operations);
    let parent = if index == 0 {
        String::new()
    } else {
        format!("({class}Part{:03})", index - 1)
    };
    let mut output = format!(
        "{NOTICE}from __future__ import annotations\n\nfrom typing import Any, Iterator\n\n{}\n\nclass {class}Part{index:03}{parent}:\n    \"\"\"Bounded typed {attribute} resource operations.\"\"\"\n\n    def __init__(self, client: Any) -> None:\n        self._client = client\n",
        if index == 0 {
            String::new()
        } else {
            format!(
                "from .{}_part_{:03} import {class}Part{:03}",
                schema_file_name(resource),
                index - 1,
                index - 1
            )
        },
    );
    // Resource methods must remain unique across parts. Seed this partition's
    // name allocator with every preceding operation exactly as the original
    // single-file renderer did.
    let mut used_methods = BTreeMap::<String, usize>::new();
    for operation in all_operations.iter().take(index * 100) {
        let direct = python_identifier(&snake_case(&operation.id));
        let preferred = resource_method_name(&direct, resource);
        let previously_seen = *used_methods.get(&preferred).unwrap_or(&0);
        if previously_seen != 0 {
            used_methods.entry(direct).or_default();
        }
        *used_methods.entry(preferred).or_default() += 1;
    }
    for operation in operations {
        let direct = python_identifier(&snake_case(&operation.id));
        let preferred = resource_method_name(&direct, &attribute);
        let seen = used_methods.entry(preferred.clone()).or_default();
        let method = if *seen == 0 {
            preferred
        } else {
            direct.clone()
        };
        *seen += 1;
        let response = response_type(operation);
        let (signature, arguments) = operation_signature(operation);
        let forwarded = arguments
            .iter()
            .map(|argument| format!("{argument}={argument}"))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(
            output,
            "    def {method}(self{signature}) -> {response}:\n        return self._client.{direct}({forwarded})\n"
        );
        if cursor_pagination(api, operation).is_some()
            || offset_pagination(operation).is_some()
            || url_pagination(operation).is_some()
        {
            let _ = writeln!(
                output,
                "    def {method}_pages(self{signature}) -> Iterator[{response}]:\n        return self._client.{direct}_pages({forwarded})\n"
            );
        }
    }
    output
}

fn render_resource_facade(resource: &str, chunks: usize) -> String {
    let class = format!("{}Resource", pascal_case(resource));
    let file = schema_file_name(resource);
    let last = chunks.saturating_sub(1);
    format!(
        "{NOTICE}from __future__ import annotations\n\nfrom .{file}_part_{last:03} import {class}Part{last:03}\n\n\nclass {class}({class}Part{last:03}):\n    \"\"\"Typed resource namespace exposed by :class:`Client`.\"\"\"\n\n    pass\n"
    )
}

fn resource_method_name(operation: &str, resource: &str) -> String {
    let singular = resource.strip_suffix('s').unwrap_or(resource);
    let method = operation
        .strip_suffix(resource)
        .or_else(|| operation.strip_suffix(singular))
        .or_else(|| operation.strip_prefix(resource))
        .unwrap_or(operation)
        .trim_matches('_');
    if method.is_empty() {
        operation.into()
    } else {
        method.into()
    }
}

/// Uses the resource name unless it would hide one of Client's direct
/// generated methods. This keeps the flat surface available in namespaced
/// mode: an `auth-check` resource with `authCheck` becomes
/// `client.auth_check_resource`, while `client.auth_check(...)` still works.
fn resource_attribute(resource: &str, operations: &[&Operation]) -> String {
    let direct_methods = operations
        .iter()
        .map(|operation| python_identifier(&snake_case(&operation.id)))
        .collect::<std::collections::BTreeSet<_>>();
    let mut attribute = python_identifier(resource);
    while direct_methods.contains(&attribute) {
        attribute.push_str("_resource");
    }
    attribute
}

fn response_type(operation: &Operation) -> String {
    if operation_is_sse_response(operation) {
        return "Iterator[Any]".into();
    }
    if matches!(
        analyze_operation(operation, None).streaming,
        Some(StreamingKind::Binary)
    ) {
        return "bytes".into();
    }
    operation
        .responses
        .iter()
        .find(|response| response.status.starts_with('2'))
        .and_then(|response| response.media_types.first())
        .and_then(|media| media.schema.as_ref())
        .map(python_type)
        .unwrap_or_else(|| "None".into())
}

fn operation_is_sse_response(operation: &Operation) -> bool {
    operation
        .responses
        .iter()
        .find(|response| response.status.starts_with('2'))
        .and_then(|response| response.media_types.first())
        .is_some_and(|media| media.content_type.eq_ignore_ascii_case("text/event-stream"))
}

fn operation_is_binary_response(operation: &Operation) -> bool {
    matches!(
        analyze_operation(operation, None).streaming,
        Some(StreamingKind::Binary)
    )
}

/// Returns an object model name when the selected successful response is a
/// component object. Those models can be reconstructed from response JSON at
/// runtime instead of merely being a static `cast`.
fn response_object_model(api: &Api, operation: &Operation) -> Option<String> {
    let candidate = operation
        .responses
        .iter()
        .find(|response| response.status.starts_with('2'))
        .and_then(|response| response.media_types.first())
        .and_then(|media| media.schema.as_ref())
        .and_then(|schema| match &schema.kind {
            SchemaKind::Reference { reference } => {
                Some(reference.rsplit('/').next().unwrap_or(reference).to_owned())
            }
            _ => None,
        })?;
    api.schemas
        .iter()
        .find(|schema| schema.name == candidate)
        .and_then(|schema| {
            matches!(schema.value.kind, SchemaKind::Object { .. }).then_some(candidate)
        })
        .map(|name| python_type_name(&name))
}

fn python_literal(value: &serde_json::Value) -> String {
    match value {
        serde_json::Value::Null => "None".into(),
        serde_json::Value::Bool(value) => {
            if *value {
                "True".into()
            } else {
                "False".into()
            }
        }
        serde_json::Value::Number(value) => value.to_string(),
        serde_json::Value::String(value) => format!("{value:?}"),
        serde_json::Value::Array(values) => format!(
            "[{}]",
            values
                .iter()
                .map(python_literal)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        serde_json::Value::Object(values) => format!(
            "{{{}}}",
            values
                .iter()
                .map(|(key, value)| format!("{key:?}: {}", python_literal(value)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

fn python_type(value: &SchemaValue) -> String {
    let base = match &value.kind {
        SchemaKind::Any | SchemaKind::Not { .. } => "Any".into(),
        SchemaKind::Null => "None".into(),
        SchemaKind::Boolean => "bool".into(),
        SchemaKind::Integer => "int".into(),
        SchemaKind::Number => "float".into(),
        SchemaKind::String => "str".into(),
        SchemaKind::Array { items } => format!("list[{}]", python_type(items)),
        SchemaKind::Object {
            additional_properties: AdditionalProperties::Schema { value },
            ..
        } => format!("dict[str, {}]", python_type(value)),
        SchemaKind::Object { .. } => "dict[str, Any]".into(),
        SchemaKind::Reference { reference } => {
            python_type_name(reference.rsplit('/').next().unwrap_or(reference))
        }
        SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => variants
            .iter()
            .map(python_type)
            .collect::<Vec<_>>()
            .join(" | "),
        SchemaKind::AllOf { .. } => "dict[str, Any]".into(),
    };
    if value.nullable && base != "None" {
        format!("{base} | None")
    } else {
        base
    }
}

fn python_type_name(name: &str) -> String {
    pascal_case(name)
}

fn python_module_name(name: &str) -> String {
    let value = name
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() {
                character.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect::<String>();
    let value = value.trim_matches('_');
    let value = if value.is_empty() {
        "generated_sdk"
    } else {
        value
    };
    if value
        .chars()
        .next()
        .is_some_and(|character| character.is_ascii_digit())
    {
        format!("sdk_{value}")
    } else {
        value.into()
    }
}

/// A stable, bounded filename for component/tag names.  OpenAPI component
/// names and Graph-style tags can be arbitrarily long; preserving the full
/// name in a path is both fragile on macOS and unnecessary for imports.
fn schema_file_name(name: &str) -> String {
    let stem = python_module_name(name);
    let prefix = &stem[..stem.len().min(96)];
    let hash = name
        .as_bytes()
        .iter()
        .fold(0xcbf29ce484222325_u64, |hash, byte| {
            (hash ^ u64::from(*byte)).wrapping_mul(0x100000001b3)
        });
    format!("{prefix}_{hash:016x}")
}

fn python_identifier(value: &str) -> String {
    let mut value = snake_case(value);
    if value.is_empty() {
        value = "value".into();
    }
    if value
        .chars()
        .next()
        .is_some_and(|character| character.is_ascii_digit())
    {
        value.insert_str(0, "value_");
    }
    if matches!(
        value.as_str(),
        "False"
            | "None"
            | "True"
            | "and"
            | "as"
            | "assert"
            | "async"
            | "await"
            | "break"
            | "class"
            | "continue"
            | "def"
            | "del"
            | "elif"
            | "else"
            | "except"
            | "finally"
            | "for"
            | "from"
            | "global"
            | "if"
            | "import"
            | "in"
            | "is"
            | "lambda"
            | "nonlocal"
            | "not"
            | "or"
            | "pass"
            | "raise"
            | "return"
            | "try"
            | "while"
            | "with"
            | "yield"
    ) {
        value.push('_');
    }
    value
}

fn snake_case(value: &str) -> String {
    let mut output = String::new();
    let mut previous_is_lower = false;
    for character in value.chars() {
        if character.is_ascii_alphanumeric() {
            if character.is_ascii_uppercase() && previous_is_lower {
                output.push('_');
            }
            output.push(character.to_ascii_lowercase());
            previous_is_lower = character.is_ascii_lowercase() || character.is_ascii_digit();
        } else if !output.ends_with('_') && !output.is_empty() {
            output.push('_');
            previous_is_lower = false;
        }
    }
    output.trim_matches('_').into()
}

fn pascal_case(value: &str) -> String {
    let mut output = String::new();
    let mut capitalize = true;
    for character in value.chars() {
        if character.is_ascii_alphanumeric() {
            if capitalize {
                output.push(character.to_ascii_uppercase());
                capitalize = false;
            } else {
                output.push(character);
            }
        } else {
            capitalize = true;
        }
    }
    if output.is_empty() {
        "GeneratedValue".into()
    } else if output
        .chars()
        .next()
        .is_some_and(|character| character.is_ascii_digit())
    {
        format!("Value{output}")
    } else {
        output
    }
}

fn kebab_case(value: &str) -> String {
    snake_case(value).replace('_', "-")
}

fn python_package_version(version: &str) -> String {
    let values = version.split('-').collect::<Vec<_>>();
    if values.len() == 3 && values.iter().all(|value| value.parse::<u64>().is_ok()) {
        return values.join(".");
    }
    if version.split('.').count() == 3
        && version.split('.').all(|value| value.parse::<u64>().is_ok())
    {
        return version.into();
    }
    "0.1.0".into()
}

