const NOTICE: &str = "# Generated by Poolster. Do not edit.\n";

fn pagination_annotation(operation: &Operation) -> Option<&Value> {
    operation
        .annotations
        .get("x-poolster-pagination")
        .or_else(|| operation.annotations.get("x-kaji-pagination"))
        .or_else(|| operation.annotations.get("x-speakeasy-pagination"))
}

fn idempotency_annotation(operation: &Operation) -> Option<&Value> {
    operation
        .annotations
        .get("x-poolster-idempotency-resolved")
        .or_else(|| operation.annotations.get("x-kaji-idempotency-resolved"))
}

/// Generates an installable, typed Python SDK below `output_dir`.
///
/// The package uses only the Python standard library at runtime. `package_name`
/// controls both the distribution name in `pyproject.toml` and the import
/// package (with hyphens normalized to underscores). When omitted it is
/// derived from the API title.
#[cfg(test)]
fn render_test_sdk(
    api: &Api,
    output_dir: &str,
    package_name: Option<&str>,
) -> Result<GeneratedTree> {
    render_sdk(api, output_dir, package_name, SdkClientStyle::Flat)
}

/// Generates a Python SDK with either direct operations or resource namespaces.
fn render_sdk(
    api: &Api,
    output_dir: &str,
    package_name: Option<&str>,
    client_style: SdkClientStyle,
) -> Result<GeneratedTree> {
    let prepared = symbols::prepare(api);
    let api = prepared.as_ref();
    for operation in &api.operations {
        if pagination_annotation(operation)
            .and_then(|v| v.get("type"))
            .and_then(Value::as_str)
            == Some("page")
        {
            poolster_core::pagination::normalize_pagination(api, operation, None)?;
        }
    }
    let root = output_dir.trim_matches('/');
    if root.is_empty() {
        bail!("Python SDK output directory cannot be empty");
    }

    let distribution = package_name
        .map(str::to_owned)
        .unwrap_or_else(|| format!("{}-sdk", kebab_case(&api.name)));
    let module = python_module_name(&distribution);
    let mut tree = GeneratedTree::default();
    tree.insert(GeneratedFile::new(
        format!("{root}/pyproject.toml"),
        render_pyproject(&distribution, &api.version),
    )?)?;
    // Keep source files comfortably navigable for very large descriptions.
    // `models` remains a normal import package, so `from sdk.models import X`
    // stays exactly the same for callers.
    tree.insert(GeneratedFile::new(
        format!("{root}/src/{module}/models/__init__.py"),
        render_models_init(api),
    )?)?;
    tree.insert(GeneratedFile::new(
        format!("{root}/src/{module}/models/chunks/__init__.py"),
        format!("{NOTICE}# Bounded model re-export partitions.\n"),
    )?)?;
    for (index, schemas) in api.schemas.chunks(100).enumerate() {
        tree.insert(GeneratedFile::new(
            format!("{root}/src/{module}/models/chunks/exports_{index:03}.py"),
            render_model_exports(schemas),
        )?)?;
    }
    tree.insert(GeneratedFile::new(
        format!("{root}/src/{module}/models/_model_codec.py"),
        include_str!("../templates/model_codec.py"),
    )?)?;
    for schema in &api.schemas {
        tree.insert(GeneratedFile::new(
            format!(
                "{root}/src/{module}/models/{}.py",
                schema_file_name(&schema.name)
            ),
            render_model(schema),
        )?)?;
    }
    tree.insert(GeneratedFile::new(
        format!("{root}/src/{module}/runtime.py"),
        render_runtime(api),
    )?)?;
    tree.insert(GeneratedFile::new(
        format!("{root}/src/{module}/presence.py"),
        include_str!("../templates/presence.py"),
    )?)?;
    for (path, contents) in render_partitioned_errors(api) {
        tree.insert(GeneratedFile::new(
            format!("{root}/src/{module}/{path}"),
            contents,
        )?)?;
    }
    for (path, contents) in response_validation::render_partitioned(api) {
        tree.insert(GeneratedFile::new(
            format!("{root}/src/{module}/{path}"),
            contents,
        )?)?;
    }
    tree.insert(GeneratedFile::new(
        format!("{root}/src/{module}/multipart.py"),
        include_str!("../templates/multipart.py"),
    )?)?;
    if api
        .operations
        .iter()
        .any(|operation| operation_body_kind(operation).ends_with("multipart"))
    {
        tree.insert(GeneratedFile::new(
            format!("{root}/MULTIPART.md"),
            include_str!("../templates/multipart_readme.md"),
        )?)?;
    }
    tree.insert(GeneratedFile::new(
        format!("{root}/src/{module}/oauth.py"),
        include_str!("../templates/oauth.py"),
    )?)?;
    for (index, range) in python_operation_groups(api).into_iter().enumerate() {
        let operations = &api.operations[range];
        tree.insert(GeneratedFile::new(
            format!("{root}/src/{module}/operations_{index:03}.py"),
            render_operation_chunk(api, operations, index),
        )?)?;
    }
    if client_style == SdkClientStyle::Namespaced {
        let resource_names = resource_operations(api).keys().cloned().collect::<Vec<_>>();
        tree.insert(GeneratedFile::new(
            format!("{root}/src/{module}/resources/__init__.py"),
            render_resources_init(resource_names.len()),
        )?)?;
        tree.insert(GeneratedFile::new(
            format!("{root}/src/{module}/resources/chunks/__init__.py"),
            format!("{NOTICE}# Bounded resource re-export partitions.\n"),
        )?)?;
        for (index, resources) in resource_names.chunks(100).enumerate() {
            tree.insert(GeneratedFile::new(
                format!("{root}/src/{module}/resources/chunks/exports_{index:03}.py"),
                render_resource_exports(resources),
            )?)?;
        }
        for (resource, resource_operations) in resource_operations(api) {
            let file = schema_file_name(&resource);
            let groups = python_resource_groups(api, &resource, &resource_operations);
            let group_count = groups.len();
            for (index, range) in groups.into_iter().enumerate() {
                let operations = &resource_operations[range];
                tree.insert(GeneratedFile::new(
                    format!("{root}/src/{module}/resources/{file}_part_{index:03}.py"),
                    render_resource_chunk(api, &resource, &resource_operations, operations, index),
                )?)?;
            }
            tree.insert(GeneratedFile::new(
                format!("{root}/src/{module}/resources/{file}.py"),
                render_resource_facade(&resource, group_count),
            )?)?;
        }
    }
    tree.insert(GeneratedFile::new(
        format!("{root}/src/{module}/client.py"),
        render_client_facade(api, client_style),
    )?)?;
    tree.insert(GeneratedFile::new(
        format!("{root}/src/{module}/__init__.py"),
        render_init(api, client_style),
    )?)?;
    tree.insert(GeneratedFile::new(
        format!("{root}/README.md"),
        render_readme(api, &distribution, &module, client_style),
    )?)?;
    tree.insert(GeneratedFile::new(
        format!("{root}/api.md"),
        render_api_reference(api),
    )?)?;
    if client_style == SdkClientStyle::Namespaced {
        tree.insert(GeneratedFile::new(
            format!("{root}/STYLE_GUIDE.md"),
            render_style_guide(api, &module),
        )?)?;
    }
    Ok(tree)
}

/// Add native async operations while sharing the exact synchronous model package.
fn render_sdk_with_async(
    api: &Api,
    output_dir: &str,
    package_name: Option<&str>,
    style: SdkClientStyle,
    enabled: bool,
) -> Result<GeneratedTree> {
    let mut tree = render_sdk(api, output_dir, package_name, style)?;
    if !enabled {
        return Ok(tree);
    }
    let root = output_dir.trim_matches('/');
    let distribution = package_name
        .map(str::to_owned)
        .unwrap_or_else(|| format!("{}-sdk", kebab_case(&api.name)));
    let module = python_module_name(&distribution);
    let prefix = format!("{root}/src/{module}/");
    let mut files = Vec::new();
    for (path, contents) in tree.iter() {
        let path = path.to_string_lossy();
        let Some(relative) = path.strip_prefix(&prefix) else {
            continue;
        };
        if relative.starts_with("operations_") {
            files.push((
                format!("{prefix}async_{relative}"),
                async_operation_source(contents),
            ));
        } else if let Some(resource) = relative.strip_prefix("resources/") {
            files.push((
                format!("{prefix}async_resources/{resource}"),
                async_resource_source(contents),
            ));
        }
    }
    for (path, contents) in files {
        tree.insert(GeneratedFile::new(path, contents)?)?;
    }
    tree.insert(GeneratedFile::new(
        format!("{prefix}async_runtime.py"),
        include_str!("../templates/async_runtime.py"),
    )?)?;
    let facade = render_client_facade(api, style)
        .replace(
            "from .runtime import BaseClient",
            "from .async_runtime import AsyncBaseClient",
        )
        .replace("from .operations_", "from .async_operations_")
        .replace("from .resources.", "from .async_resources.")
        .replace("class Client(", "class AsyncClient(")
        .replace(", BaseClient)", ", AsyncBaseClient)")
        .replace(
            "class AsyncClient(BaseClient)",
            "class AsyncClient(AsyncBaseClient)",
        );
    tree.insert(GeneratedFile::new(
        format!("{prefix}async_client.py"),
        facade,
    )?)?;
    let init_path = format!("{prefix}__init__.py");
    let init = format!(
        "{}\nfrom .async_client import AsyncClient\n",
        tree.get(&init_path).unwrap()
    );
    tree.replace(GeneratedFile::new(init_path, init)?)?;
    let manifest_path = format!("{root}/pyproject.toml");
    let manifest = format!(
        "{}\n[project.optional-dependencies]\nasync = [\"httpx>=0.27,<1\"]\n",
        tree.get(&manifest_path).unwrap()
    );
    tree.replace(GeneratedFile::new(manifest_path, manifest)?)?;
    Ok(tree)
}

// These transformations apply only to Poolster's own generated operation grammar.
// Models, wire codecs, signatures and pagination declarations remain shared.
fn async_operation_source(source: &str) -> String {
    source
        .replace("Any, Iterator, cast", "Any, AsyncIterator, cast")
        .replace("Iterator[", "AsyncIterator[")
        .replace("    def ", "    async def ")
        .replace("result = self._request(", "result = await self._request(")
        .replace(
            "result = self._event_stream(",
            "result = await self._event_stream(",
        )
        .replace("response = self.", "response = await self.")
}
fn async_resource_source(source: &str) -> String {
    let source = source
        .replace("Any, Iterator", "Any, AsyncIterator")
        .replace("Iterator[", "AsyncIterator[");
    let mut output = String::new();
    for line in source.lines() {
        let line = if line.starts_with("    def ")
            && !line.contains("__init__")
            && !line.contains("_pages(")
        {
            line.replacen("    def ", "    async def ", 1)
        } else if line.contains("return self._client.") && !line.contains("_pages(") {
            line.replacen("return self._client.", "return await self._client.", 1)
        } else {
            line.to_owned()
        };
        output.push_str(&line);
        output.push('\n');
    }
    output
}

fn render_pyproject(package_name: &str, version: &str) -> String {
    format!(
        "[build-system]\nrequires = [\"hatchling\"]\nbuild-backend = \"hatchling.build\"\n\n[project]\nname = {package_name:?}\nversion = {:?}\ndescription = \"Generated Python client for {}\"\nrequires-python = \">=3.10\"\nlicense = {{ text = \"MIT\" }}\nclassifiers = [\n  \"Programming Language :: Python :: 3\",\n  \"Programming Language :: Python :: 3 :: Only\",\n  \"Typing :: Typed\",\n]\n\n[tool.hatch.build.targets.wheel]\npackages = [\"src/{}\"]\n",
        python_package_version(version),
        package_name,
        python_module_name(package_name),
    )
}

fn render_models_init(api: &Api) -> String {
    let mut output = format!(
        "{NOTICE}\nfrom __future__ import annotations\n\nfrom dataclasses import MISSING as _MISSING, fields as _fields, is_dataclass as _is_dataclass\nfrom typing import Any as _Any\n\n\ndef _to_wire(value: _Any) -> _Any:\n    \"\"\"Convert generated dataclasses into JSON-compatible values.\"\"\"\n    if _is_dataclass(value) and not isinstance(value, type):\n        result = {{}}\n        present = next((getattr(value, item.name) for item in _fields(value) if item.metadata.get(\"present_fields\")), None)\n        for item in _fields(value):\n            current = getattr(value, item.name)\n            if item.metadata.get(\"additional_properties\"):\n                result.update(_to_wire(current))\n        for item in _fields(value):\n            current = getattr(value, item.name)\n            if not item.metadata.get(\"internal\") and not item.metadata.get(\"additional_properties\") and (current is not None or (present is not None and item.metadata.get(\"wire_name\", item.name) in present) or (item.default is _MISSING and item.default_factory is _MISSING)):\n                result[item.metadata.get(\"wire_name\", item.name)] = _to_wire(current)\n        return result\n    if isinstance(value, list):\n        return [_to_wire(item) for item in value]\n    if isinstance(value, dict):\n        return {{key: _to_wire(item) for key, item in value.items()}}\n    return value\n\n"
    );
    for index in 0..api.schemas.len().div_ceil(100) {
        let _ = writeln!(output, "from .chunks.exports_{index:03} import *");
    }
    output
}

fn render_model_exports(schemas: &[Schema]) -> String {
    let mut output = format!("{NOTICE}from __future__ import annotations\n\n");
    for schema in schemas {
        let name = python_type_name(&schema.name);
        let file = schema_file_name(&schema.name);
        let _ = writeln!(output, "from ..{file} import {name}");
    }
    output
}

fn render_resources_init(resources: usize) -> String {
    let mut output = format!("{NOTICE}from __future__ import annotations\n\n");
    for index in 0..resources.div_ceil(100) {
        let _ = writeln!(output, "from .chunks.exports_{index:03} import *");
    }
    output
}

fn render_resource_exports(resources: &[String]) -> String {
    let mut output = format!("{NOTICE}from __future__ import annotations\n\n");
    for resource in resources {
        let file = schema_file_name(resource);
        let class = format!("{}Resource", pascal_case(resource));
        let _ = writeln!(output, "from ..{file} import {class}");
    }
    output
}

fn render_model(schema: &Schema) -> String {
    let mut output = format!(
        "{NOTICE}from __future__ import annotations\n\nfrom dataclasses import dataclass, field as _poolster_field\nfrom typing import Any, Literal, TYPE_CHECKING\nfrom ._model_codec import decode_model_value\n\nif TYPE_CHECKING:\n    from typing import TypeAlias\n\n"
    );
    let mut references = std::collections::BTreeSet::new();
    python_references(&schema.value, &mut references);
    references.remove(&python_type_name(&schema.name));
    if !references.is_empty() {
        output.push_str("if TYPE_CHECKING:\n");
        for reference in references {
            let _ = writeln!(output, "    from . import {reference}");
        }
        output.push('\n');
    }
    render_schema(&mut output, schema);
    output
}

fn python_references(value: &SchemaValue, names: &mut std::collections::BTreeSet<String>) {
    match &value.kind {
        SchemaKind::Reference { reference } => {
            names.insert(python_type_name(
                reference.rsplit('/').next().unwrap_or(reference),
            ));
        }
        SchemaKind::Array { items } => python_references(items, names),
        SchemaKind::Object {
            fields,
            additional_properties,
        } => {
            for field in fields {
                python_references(&field.value, names);
            }
            if let AdditionalProperties::Schema { value } = additional_properties {
                python_references(value, names);
            }
        }
        SchemaKind::OneOf { variants }
        | SchemaKind::AnyOf { variants }
        | SchemaKind::AllOf { variants } => {
            for variant in variants {
                python_references(variant, names);
            }
        }
        SchemaKind::Not { schema } => python_references(schema, names),
        _ => {}
    }
}

fn python_decode_shape(value: &SchemaValue) -> String {
    match &value.kind {
        SchemaKind::Reference { reference } => format!(
            "(\"ref\", {:?})",
            python_type_name(reference.rsplit('/').next().unwrap_or(reference))
        ),
        SchemaKind::Array { items } => format!("(\"array\", {})", python_decode_shape(items)),
        SchemaKind::Object { fields, .. } => format!(
            "(\"object\", {{{}}})",
            fields
                .iter()
                .map(|field| format!("{:?}: {}", field.name, python_decode_shape(&field.value)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        _ => "None".into(),
    }
}

fn render_schema(output: &mut String, schema: &Schema) {
    let name = python_type_name(&schema.name);
    match &schema.value.kind {
        SchemaKind::Object {
            fields,
            additional_properties,
        } => {
            let mut additional_field = "additional_properties".to_owned();
            while fields
                .iter()
                .any(|item| python_field_identifier(fields, item) == additional_field)
            {
                additional_field.insert(0, '_');
            }
            let mut present_field = "_poolster_present_fields".to_owned();
            while fields
                .iter()
                .any(|item| python_field_identifier(fields, item) == present_field)
                || present_field == additional_field
            {
                present_field.insert(0, '_');
            }
            output.push_str("@dataclass\n");
            let _ = writeln!(output, "class {name}:");
            // Required fields must precede fields with defaults in a dataclass.
            for required in [true, false] {
                for item in fields.iter().filter(|item| item.required == required) {
                    let field_name = python_field_identifier(fields, item);
                    let field_type = python_type(&item.value);
                    if item.required {
                        if field_name == item.name {
                            let _ = writeln!(output, "    {field_name}: {field_type}");
                        } else {
                            let _ = writeln!(
                                output,
                                "    {field_name}: {field_type} = _poolster_field(metadata={{\"wire_name\": {:?}}})",
                                item.name
                            );
                        }
                    } else if field_name == item.name {
                        let _ = writeln!(output, "    {field_name}: {field_type} | None = None");
                    } else {
                        let _ = writeln!(
                            output,
                            "    {field_name}: {field_type} | None = _poolster_field(default=None, metadata={{\"wire_name\": {:?}}})",
                            item.name
                        );
                    }
                }
            }
            if !matches!(additional_properties, AdditionalProperties::Forbidden) {
                let additional_type = match additional_properties {
                    AdditionalProperties::Schema { value } => python_type(value),
                    _ => "Any".to_owned(),
                };
                let _ = writeln!(
                    output,
                    "    {additional_field}: dict[str, {}] = _poolster_field(default_factory=dict, metadata={{\"additional_properties\": True}})",
                    additional_type
                );
            }
            let _ = writeln!(
                output,
                "    {present_field}: frozenset[str] | None = _poolster_field(default=None, init=False, repr=False, compare=False, metadata={{\"internal\": True, \"present_fields\": True}})"
            );
            output.push_str("\n    @classmethod\n");
            let _ = writeln!(
                output,
                "    def from_dict(cls, value: dict[str, Any]) -> \"{name}\":"
            );
            if fields.is_empty() && matches!(additional_properties, AdditionalProperties::Forbidden)
            {
                output.push_str("        return cls()\n");
            } else {
                output.push_str("        instance = cls(\n");
                for item in fields {
                    let field_name = python_field_identifier(fields, item);
                    let accessor = if item.required {
                        format!("value[{key:?}]", key = item.name)
                    } else {
                        format!("value.get({key:?})", key = item.name)
                    };
                    let shape = python_decode_shape(&item.value);
                    let accessor = if shape == "None" {
                        accessor
                    } else {
                        format!("decode_model_value({accessor}, {shape})")
                    };
                    let _ = writeln!(output, "            {field_name}={accessor},");
                }
                if !matches!(additional_properties, AdditionalProperties::Forbidden) {
                    let declared = fields
                        .iter()
                        .map(|item| format!("{:?}", item.name))
                        .collect::<Vec<_>>()
                        .join(", ");
                    let item = match additional_properties {
                        AdditionalProperties::Schema { value } => {
                            format!("decode_model_value(item, {})", python_decode_shape(value))
                        }
                        _ => "item".into(),
                    };
                    let _ = writeln!(
                        output,
                        "            {additional_field}={{key: {item} for key, item in value.items() if key not in [{declared}]}},"
                    );
                }
                let _ = writeln!(
                    output,
                    "        )\n        instance.{present_field} = frozenset(value)\n        return instance"
                );
            }
        }
        _ if !schema.value.enum_values.is_empty() => {
            let values = schema
                .value
                .enum_values
                .iter()
                .map(python_literal)
                .collect::<Vec<_>>();
            let future = if schema
                .value
                .extensions
                .get("x-poolster-open-enum")
                .or_else(|| schema.value.extensions.get("x-kaji-open-enum"))
                .and_then(serde_json::Value::as_bool)
                == Some(true)
            {
                let mut primitives = std::collections::BTreeSet::new();
                for value in &schema.value.enum_values {
                    primitives.insert(if value.is_string() {
                        "str"
                    } else if value.is_boolean() {
                        "bool"
                    } else if value.is_i64() || value.is_u64() {
                        "int"
                    } else if value.is_number() {
                        "float"
                    } else {
                        "None"
                    });
                }
                format!(
                    " | {}",
                    primitives.into_iter().collect::<Vec<_>>().join(" | ")
                )
            } else {
                String::new()
            };
            let _ = writeln!(output, "{name} = Literal[{}]{future}", values.join(", "));
        }
        _ => {
            let mut references = std::collections::BTreeSet::new();
            python_references(&schema.value, &mut references);
            let annotation = python_type(&schema.value);
            if references.is_empty() {
                let _ = writeln!(output, "{name} = {annotation}");
            } else {
                // Future annotations do not defer a type alias assignment. A
                // PEP 613 forward alias also avoids circular model imports.
                let _ = writeln!(output, "{name}: TypeAlias = {annotation:?}");
            }
        }
    }
}

