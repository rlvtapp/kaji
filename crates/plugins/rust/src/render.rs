fn render_resource_clients(api: &Api) -> String {
    let resources = resource_operations(api);
    let direct_methods = api
        .operations
        .iter()
        .map(|operation| rust_field_name(&operation.id))
        .collect::<Vec<_>>();
    let mut output = String::new();

    for (resource, operations) in &resources {
        let accessor = resource_accessor_name(resource, &direct_methods);
        let client_type = format!("{}Client", type_name(resource));
        let _ = writeln!(
            output,
            "impl Client {{\n    /// Returns the {resource} resource client.\n    pub fn {accessor}(&self) -> {client_type}<'_> {{\n        {client_type} {{ client: self }}\n    }}\n}}\n"
        );
        let _ = writeln!(
            output,
            "/// Resource-first operations for {resource}.\npub struct {client_type}<'a> {{\n    client: &'a Client,\n}}\n"
        );
        let _ = writeln!(output, "impl {client_type}<'_> {{");
        let mut used_methods = BTreeMap::<String, usize>::new();
        for operation in operations {
            let direct = rust_field_name(&operation.id);
            let preferred = resource_method_name(&direct, resource);
            let seen = used_methods.entry(preferred.clone()).or_default();
            let method = if *seen == 0 { preferred } else { direct };
            *seen += 1;
            output.push_str(&render_resource_operation(&method, operation));
            if rust_pagination(operation).is_some() {
                output.push_str(&render_resource_pagination_operation(&method, operation));
            }
        }
        output.push_str("}\n\n");
    }
    output
}

fn render_resource_operation(method: &str, operation: &Operation) -> String {
    let direct = rust_field_name(&operation.id);
    let response = operation_response_type(operation);
    let error = operation_error_name(operation);
    let parameters = if operation_has_parameters(operation) {
        format!(", input: {}", operation_request_name(operation))
    } else {
        String::new()
    };
    let request_body = operation
        .request_type
        .as_deref()
        .map(rust_type_name)
        .map(|request| format!(", body: &{request}"))
        .unwrap_or_default();
    let input = if operation_has_parameters(operation) {
        "input"
    } else {
        ""
    };
    let separator = if operation_has_parameters(operation) && operation.request_type.is_some() {
        ", "
    } else {
        ""
    };
    let body = if operation.request_type.is_some() {
        "body"
    } else {
        ""
    };
    format!(
        "    /// Invokes {} {} through this resource.\n    pub async fn {method}(&self{parameters}{request_body}) -> Result<{response}, {error}> {{\n        self.client.{direct}({input}{separator}{body}).await\n    }}\n\n",
        operation.method.as_str(),
        operation.path,
    )
}

fn render_resource_pagination_operation(method: &str, operation: &Operation) -> String {
    let direct = rust_field_name(&operation.id);
    let request = operation_request_name(operation);
    let response = operation_response_type(operation);
    let error = operation_error_name(operation);
    format!(
        "    /// Lazily fetches all pages through this resource client.\n    pub fn {method}_pages(&self, input: {request}) -> impl futures_util::Stream<Item = Result<{response}, {error}>> {{\n        self.client.{direct}_pages(input)\n    }}\n\n"
    )
}

fn resource_operations(api: &Api) -> BTreeMap<String, Vec<&Operation>> {
    let mut resources = BTreeMap::<String, Vec<&Operation>>::new();
    for operation in &api.operations {
        resources
            .entry(resource_name(operation))
            .or_default()
            .push(operation);
    }
    resources
}

fn resource_name(operation: &Operation) -> String {
    operation
        .annotations
        .get("tags")
        .and_then(serde_json::Value::as_array)
        .and_then(|tags| tags.first())
        .and_then(serde_json::Value::as_str)
        .filter(|tag| !tag.trim().is_empty())
        .map(rust_field_name)
        .or_else(|| {
            operation
                .path
                .split('/')
                .filter(|segment| !segment.is_empty() && !segment.starts_with('{'))
                .find(|segment| {
                    !matches!(*segment, "api" | "email") && !is_version_segment(segment)
                })
                .map(rust_field_name)
        })
        .unwrap_or_else(|| "api".into())
}

fn is_version_segment(segment: &str) -> bool {
    let mut characters = segment.chars();
    matches!(characters.next(), Some('v' | 'V'))
        && characters
            .next()
            .is_some_and(|character| character.is_ascii_digit())
}

fn resource_accessor_name(resource: &str, direct_methods: &[String]) -> String {
    if direct_methods.iter().any(|method| method == resource) {
        format!("{resource}_resource")
    } else {
        resource.into()
    }
}

fn resource_method_name(direct: &str, resource: &str) -> String {
    let singular = resource.strip_suffix('s').unwrap_or(resource);
    direct
        .strip_suffix(resource)
        .or_else(|| direct.strip_suffix(singular))
        .or_else(|| direct.strip_prefix(resource))
        .map(|method| method.trim_matches('_'))
        .filter(|method| !method.is_empty())
        .unwrap_or(direct)
        .into()
}

