//! Native Rust SDK rendering.
//!
//! The generated client uses `reqwest`, `serde`, and `serde_json`, which are
//! conventional, well-maintained Rust choices. Complex JSON Schema constructs
//! that do not map soundly to a named Rust type are represented as
//! `serde_json::Value` rather than silently narrowed.

use std::{collections::BTreeMap, fmt::Write};

use anyhow::Result;
use serde_json::Value;

use kaji_core::ast::{
    AdditionalProperties, Api, Operation, OperationParameter, Schema, SchemaKind, SchemaValue,
};
use kaji_core::{GeneratedFile, GeneratedTree, SdkClientStyle};

const NOTICE: &str = "// Generated by Kaji Codegen. Do not edit.\n";

pub(super) struct RenderOptions {
    pub crate_name: Option<String>,
    pub client_style: SdkClientStyle,
    pub operation_prefix: Option<String>,
    pub open_unions: bool,
}

impl Default for RenderOptions {
    fn default() -> Self {
        Self {
            crate_name: None,
            client_style: SdkClientStyle::Namespaced,
            operation_prefix: None,
            open_unions: false,
        }
    }
}

pub(super) fn generate_sdk(api: &Api, options: &RenderOptions) -> Result<GeneratedTree> {
    let mut tree = GeneratedTree::default();
    for file in RustModels
        .generate(api, options)?
        .into_iter()
        .chain(RustReqwest.generate(api, options)?)
        .chain(RustPackage.generate(api, options)?)
    {
        tree.insert(file)?;
    }
    tree.insert(GeneratedFile::new(
        "src/transport.rs",
        super::composition::DEFAULT_TRANSPORT,
    )?)?;
    Ok(tree)
}

#[derive(Default)]
pub(crate) struct RustModels;

impl RustModels {
    pub(crate) fn generate(
        &self,
        api: &Api,
        options: &RenderOptions,
    ) -> Result<Vec<GeneratedFile>> {
        let mut files = Vec::with_capacity(api.schemas.len() + 64);
        let mut root_index = String::new();
        for (chunk_index, schemas) in api.schemas.chunks(MODELS_PER_FILE).enumerate() {
            let chunk = format!("chunk_{:04}", chunk_index + 1);
            let _ = writeln!(root_index, "mod {chunk};");
            let _ = writeln!(root_index, "pub use {chunk}::*;");
            let mut chunk_index_source = String::new();
            for (offset, schema) in schemas.iter().enumerate() {
                let index = chunk_index * MODELS_PER_FILE + offset;
                let module = schema_module_name(&schema.name, index);
                let _ = writeln!(chunk_index_source, "mod {module};");
                let _ = writeln!(chunk_index_source, "pub use {module}::*;");
                files.push(GeneratedFile::new(
                    format!("src/models/{chunk}/{module}.rs"),
                    render_model(schema, options.open_unions),
                )?);
            }
            files.push(GeneratedFile::new(
                format!("src/models/{chunk}/mod.rs"),
                format!("{NOTICE}\n{chunk_index_source}"),
            )?);
        }
        files.insert(
            0,
            GeneratedFile::new("src/models/mod.rs", format!("{NOTICE}\n#[allow(dead_code)]\npub(crate) fn kaji_deserialize_optional_nullable<'de, D, T>(deserializer: D) -> Result<Option<Option<T>>, D::Error> where D: serde::Deserializer<'de>, T: serde::Deserialize<'de> {{ <Option<T> as serde::Deserialize>::deserialize(deserializer).map(Some) }}\n{root_index}"))?,
        );
        Ok(files)
    }
}

#[derive(Default)]
struct RustReqwest;

impl RustReqwest {
    fn generate(&self, api: &Api, options: &RenderOptions) -> Result<Vec<GeneratedFile>> {
        render_client_files(api, options)
    }
}

#[derive(Default)]
struct RustPackage;

impl RustPackage {
    fn generate(&self, api: &Api, options: &RenderOptions) -> Result<Vec<GeneratedFile>> {
        let crate_name = options
            .crate_name
            .clone()
            .unwrap_or_else(|| format!("{}-sdk", kebab_case(&api.name)));
        Ok(vec![
            GeneratedFile::new("src/lib.rs", render_lib())?,
            GeneratedFile::new("Cargo.toml", render_cargo_toml_for_api(&crate_name, api))?,
            GeneratedFile::new("README.md", render_readme(api, &crate_name, options))?,
        ])
    }
}

fn render_model(schema: &Schema, open_unions: bool) -> String {
    let mut output = format!(
        "{NOTICE}\n\n#[allow(unused_imports)]\nuse crate::models::*;\n#[allow(unused_imports)]\nuse serde::{{Deserialize, Serialize}};\n\n"
    );
    render_schema(&mut output, schema, open_unions);
    output
}

/// A file-system-safe module name. Including the source index makes otherwise
/// equivalent normalized OpenAPI component names distinct without relying on
/// a platform-specific hash implementation.
fn schema_module_name(name: &str, index: usize) -> String {
    format!("{}_{}", bounded_module_stem(name), index + 1)
}

fn bounded_module_stem(name: &str) -> String {
    let mut value = rust_field_name(name).replace("r#", "");
    if value.len() > 72 {
        value.truncate(72);
        value = value.trim_matches('_').to_owned();
    }
    if value.is_empty() {
        "value".into()
    } else {
        value
    }
}

fn render_schema(output: &mut String, schema: &Schema, open_unions: bool) {
    let name = type_name(&schema.name);
    match &schema.value.kind {
        SchemaKind::Object {
            fields,
            additional_properties,
        } => {
            output.push_str("#[derive(Clone, Debug, Deserialize, Serialize)]\n");
            let _ = writeln!(output, "pub struct {name} {{");
            for field in fields {
                if field.name != rust_field_name(&field.name) {
                    let _ = writeln!(output, "    #[serde(rename = {:?})]", field.name);
                }
                if !field.required {
                    output.push_str("    #[serde(skip_serializing_if = \"Option::is_none\")]\n");
                }
                if !field.required && (field.value.nullable || field.value.nullish) {
                    output.push_str("    #[serde(default, deserialize_with = \"crate::models::kaji_deserialize_optional_nullable\")]\n");
                }
                let field_type = rust_type(&field.value);
                let field_type = if field.required {
                    field_type
                } else {
                    format!("Option<{field_type}>")
                };
                let _ = writeln!(
                    output,
                    "    pub {}: {},",
                    rust_field_name(&field.name),
                    field_type
                );
            }
            let extra_type = match additional_properties {
                AdditionalProperties::Schema { value } => Some(rust_type(value)),
                AdditionalProperties::Any | AdditionalProperties::Unspecified => {
                    Some("serde_json::Value".into())
                }
                AdditionalProperties::Forbidden => None,
            };
            if let Some(extra_type) = extra_type {
                output.push_str("    #[serde(flatten)]\n");
                let _ = writeln!(
                    output,
                    "    pub additional_properties: std::collections::BTreeMap<String, {extra_type}>,"
                );
            }
            output.push_str("}\n");
        }
        SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => {
            output
                .push_str("#[derive(Clone, Debug, Deserialize, Serialize)]\n#[serde(untagged)]\n");
            let _ = writeln!(output, "pub enum {name} {{");
            for (index, variant) in variants.iter().enumerate() {
                let _ = writeln!(output, "    Variant{index}({}),", rust_type(variant));
            }
            if open_unions {
                output.push_str("    /// Retains a future variant without discarding its wire value.\n    Unknown(serde_json::Value),\n");
            }
            output.push_str("}\n");
        }
        _ => {
            let _ = writeln!(output, "pub type {name} = {};", rust_type(&schema.value));
        }
    }
}

fn rust_type(value: &SchemaValue) -> String {
    let base = match &value.kind {
        SchemaKind::Any | SchemaKind::Not { .. } => "serde_json::Value".into(),
        SchemaKind::Null => "()".into(),
        SchemaKind::Boolean => "bool".into(),
        SchemaKind::Integer => "i64".into(),
        SchemaKind::Number => "f64".into(),
        SchemaKind::String => match value.format.as_deref() {
            Some("binary") | Some("byte") => "Vec<u8>".into(),
            _ => "String".into(),
        },
        SchemaKind::Array { items } => format!("Vec<{}>", rust_type(items)),
        SchemaKind::Object { .. } => "serde_json::Value".into(),
        SchemaKind::Reference { reference } => {
            format!(
                "crate::models::{}",
                type_name(reference.rsplit('/').next().unwrap_or(reference))
            )
        }
        SchemaKind::OneOf { .. } | SchemaKind::AnyOf { .. } | SchemaKind::AllOf { .. } => {
            "serde_json::Value".into()
        }
    };
    if (value.nullable || value.nullish) && base != "()" {
        format!("Option<{base}>")
    } else {
        base
    }
}

const MODELS_PER_FILE: usize = 100;
const OPERATIONS_PER_FILE: usize = 25;
const RESOURCE_METHODS_PER_FILE: usize = 25;

fn render_client_files(api: &Api, config: &RenderOptions) -> Result<Vec<GeneratedFile>> {
    let mut files = Vec::new();
    files.push(GeneratedFile::new(
        "src/client/mod.rs",
        render_client_runtime(api, resource_client_enabled(config)),
    )?);
    files.extend(render_operation_files(api, config)?);
    if resource_client_enabled(config) {
        files.extend(render_resource_files(api, config)?);
    }
    Ok(files)
}

