/// OpenAPI's `info.version` is free-form; Cargo package versions are SemVer.
/// Preserve date-based release versions where possible and use a stable safe
/// fallback for opaque API release labels.
fn cargo_package_version(version: &str) -> String {
    let parts = version.split('-').collect::<Vec<_>>();
    if parts.len() == 3 && parts.iter().all(|part| part.parse::<u64>().is_ok()) {
        return parts
            .iter()
            .map(|part| match part.trim_start_matches('0') {
                "" => "0",
                normalized => normalized,
            })
            .collect::<Vec<_>>()
            .join(".");
    }
    let parts = version.split('.').collect::<Vec<_>>();
    if parts.len() == 3 && parts.iter().all(|part| part.parse::<u64>().is_ok()) {
        return version.into();
    }
    "0.1.0".into()
}

fn rust_type_name(source_type: &str) -> String {
    match source_type {
        "void" => "()".into(),
        "string" => "String".into(),
        "number" => "f64".into(),
        "boolean" => "bool".into(),
        "unknown" => "serde_json::Value".into(),
        name if name.ends_with("[]") => format!("Vec<{}>", rust_type_name(&name[..name.len() - 2])),
        name => type_name(name),
    }
}

fn type_name(name: &str) -> String {
    let mut output = String::new();
    let mut uppercase = true;
    for character in name.chars() {
        if character.is_ascii_alphanumeric() {
            if uppercase {
                output.extend(character.to_uppercase());
            } else {
                output.push(character);
            }
            uppercase = false;
        } else {
            uppercase = true;
        }
    }
    if output.is_empty() {
        "Value".into()
    } else {
        output
    }
}

fn rust_field_name(name: &str) -> String {
    let mut output = String::new();
    let mut previous_is_lower = false;
    for character in name.chars() {
        if character.is_ascii_alphanumeric() {
            if character.is_ascii_uppercase() && previous_is_lower {
                output.push('_');
            }
            output.extend(character.to_lowercase());
            previous_is_lower = character.is_ascii_lowercase() || character.is_ascii_digit();
        } else if !output.ends_with('_') {
            output.push('_');
            previous_is_lower = false;
        }
    }
    let output = output.trim_matches('_').to_owned();
    match output.as_str() {
        "type" | "match" | "ref" | "self" | "super" | "crate" | "move" | "mod" | "struct"
        | "enum" | "use" => format!("r#{output}"),
        "" => "value".into(),
        _ => output,
    }
}

fn kebab_case(name: &str) -> String {
    rust_field_name(name).replace('_', "-")
}

