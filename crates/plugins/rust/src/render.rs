//! Rust SDK target plugins.
//!
//! The generated client uses `reqwest`, `serde`, and `serde_json`, which are
//! conventional, well-maintained Rust choices. Complex JSON Schema constructs
//! that do not map soundly to a named Rust type are represented as
//! `serde_json::Value` rather than silently narrowed.

use std::{collections::BTreeMap, fmt::Write};

use anyhow::Result;
use serde_json::Value;

use kaji_core::ast::{
    AdditionalProperties, Api, Operation, OperationParameter, Schema, SchemaKind, SchemaValue,
};
use kaji_core::{CodegenPlugin, GeneratedFile, GeneratorConfig};

const NOTICE: &str = "// Generated by Kaji Codegen. Do not edit.\n";

#[derive(Default)]
pub struct RustModels;

impl CodegenPlugin for RustModels {
    fn name(&self) -> &'static str {
        "rust-models"
    }

    fn generate(&self, api: &Api, config: &GeneratorConfig) -> Result<Vec<GeneratedFile>> {
        Ok(vec![GeneratedFile::new(
            output_path(config, "src/models.rs"),
            render_models(api),
        )?])
    }
}

#[derive(Default)]
pub struct RustReqwest;

impl CodegenPlugin for RustReqwest {
    fn name(&self) -> &'static str {
        "rust-reqwest"
    }

    fn generate(&self, api: &Api, config: &GeneratorConfig) -> Result<Vec<GeneratedFile>> {
        Ok(vec![GeneratedFile::new(
            output_path(config, "src/client.rs"),
            render_client(api, config),
        )?])
    }
}

#[derive(Default)]
pub struct RustPackage;

impl CodegenPlugin for RustPackage {
    fn name(&self) -> &'static str {
        "rust-package"
    }

    fn generate(&self, api: &Api, config: &GeneratorConfig) -> Result<Vec<GeneratedFile>> {
        let crate_name = config
            .get("crate_name")
            .cloned()
            .unwrap_or_else(|| format!("{}-sdk", kebab_case(&api.name)));
        Ok(vec![
            GeneratedFile::new(output_path(config, "src/lib.rs"), render_lib())?,
            GeneratedFile::new(
                output_path(config, "Cargo.toml"),
                render_cargo_toml(&crate_name, &api.version),
            )?,
            GeneratedFile::new(
                output_path(config, "README.md"),
                render_readme(api, &crate_name, config),
            )?,
        ])
    }
}

fn output_path(config: &GeneratorConfig, file: &str) -> String {
    let directory = config
        .get("output_dir")
        .map(String::as_str)
        .unwrap_or("rust")
        .trim_matches('/');
    match directory {
        "" | "." => file.to_owned(),
        _ => format!("{directory}/{file}"),
    }
}

fn render_models(api: &Api) -> String {
    let mut output = format!("{NOTICE}\nuse serde::{{Deserialize, Serialize}};\n\n");
    for schema in &api.schemas {
        render_schema(&mut output, schema);
        output.push('\n');
    }
    output
}

fn render_schema(output: &mut String, schema: &Schema) {
    let name = type_name(&schema.name);
    match &schema.value.kind {
        SchemaKind::Object {
            fields,
            additional_properties,
        } => {
            output.push_str("#[derive(Clone, Debug, Deserialize, Serialize)]\n");
            let _ = writeln!(output, "pub struct {name} {{");
            for field in fields {
                if field.name != rust_field_name(&field.name) {
                    let _ = writeln!(output, "    #[serde(rename = {:?})]", field.name);
                }
                if !field.required {
                    output.push_str("    #[serde(skip_serializing_if = \"Option::is_none\")]\n");
                }
                let field_type = rust_type(&field.value);
                let field_type = if field.required {
                    field_type
                } else {
                    format!("Option<{field_type}>")
                };
                let _ = writeln!(
                    output,
                    "    pub {}: {},",
                    rust_field_name(&field.name),
                    field_type
                );
            }
            if let AdditionalProperties::Schema { value } = additional_properties {
                output.push_str("    #[serde(flatten)]\n");
                let _ = writeln!(
                    output,
                    "    pub additional_properties: std::collections::BTreeMap<String, {}>,",
                    rust_type(value)
                );
            }
            output.push_str("}\n");
        }
        SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => {
            output
                .push_str("#[derive(Clone, Debug, Deserialize, Serialize)]\n#[serde(untagged)]\n");
            let _ = writeln!(output, "pub enum {name} {{");
            for (index, variant) in variants.iter().enumerate() {
                let _ = writeln!(output, "    Variant{index}({}),", rust_type(variant));
            }
            output.push_str("}\n");
        }
        _ => {
            let _ = writeln!(output, "pub type {name} = {};", rust_type(&schema.value));
        }
    }
}

fn rust_type(value: &SchemaValue) -> String {
    let base = match &value.kind {
        SchemaKind::Any | SchemaKind::Not { .. } => "serde_json::Value".into(),
        SchemaKind::Null => "()".into(),
        SchemaKind::Boolean => "bool".into(),
        SchemaKind::Integer => "i64".into(),
        SchemaKind::Number => "f64".into(),
        SchemaKind::String => match value.format.as_deref() {
            Some("binary") | Some("byte") => "Vec<u8>".into(),
            _ => "String".into(),
        },
        SchemaKind::Array { items } => format!("Vec<{}>", rust_type(items)),
        SchemaKind::Object { .. } => "serde_json::Value".into(),
        SchemaKind::Reference { reference } => {
            type_name(reference.rsplit('/').next().unwrap_or(reference))
        }
        SchemaKind::OneOf { .. } | SchemaKind::AnyOf { .. } | SchemaKind::AllOf { .. } => {
            "serde_json::Value".into()
        }
    };
    if value.nullable && base != "()" {
        format!("Option<{base}>")
    } else {
        base
    }
}

fn render_client(api: &Api, config: &GeneratorConfig) -> String {
    let has_pagination = api
        .operations
        .iter()
        .any(|operation| rust_pagination(operation).is_some());
    let mut output = format!(
        "{NOTICE}\nuse reqwest::Method;\nuse serde::Serialize;\nuse crate::models::*;\n\n/// The raw HTTP response retained when a response cannot be decoded or is not declared by the OpenAPI document.\n#[derive(Debug)]\npub struct ApiResponse {{\n    pub status: reqwest::StatusCode,\n    pub headers: reqwest::header::HeaderMap,\n    pub body: Vec<u8>,\n}}\n\nimpl ApiResponse {{\n    pub fn text(&self) -> String {{ String::from_utf8_lossy(&self.body).into_owned() }}\n\n    pub fn json<T: serde::de::DeserializeOwned>(&self) -> Result<T, serde_json::Error> {{\n        serde_json::from_slice(&self.body)\n    }}\n}}\n\n#[derive(Clone)]\npub struct Client {{\n    base_url: String,\n    http: reqwest::Client,\n    bearer_token: Option<String>,\n}}\n\nfn kaji_query_value<T: Serialize>(value: &T) -> String {{\n    match serde_json::to_value(value).unwrap_or(serde_json::Value::Null) {{\n        serde_json::Value::String(value) => value,\n        serde_json::Value::Number(value) => value.to_string(),\n        serde_json::Value::Bool(value) => value.to_string(),\n        value => value.to_string(),\n    }}\n}}\n\nfn kaji_path_segment(value: &str) -> String {{\n    let mut encoded = String::new();\n    for byte in value.bytes() {{\n        if byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'.' | b'_' | b'~') {{\n            encoded.push(byte as char);\n        }} else {{\n            use std::fmt::Write as _;\n            let _ = write!(encoded, \"%{{byte:02X}}\");\n        }}\n    }}\n    encoded\n}}\n\n"
    );
    // Keep the base renderer compact while augmenting its generated runtime
    // with configuration that applies uniformly to every operation.
    output = output.replacen(
        "use reqwest::Method;\n",
        "use std::{sync::Arc, time::Duration};\n\nuse reqwest::Method;\n",
        1,
    );
    output = output.replacen(
        "    bearer_token: Option<String>,\n",
        "    bearer_token: Option<String>,\n    retry: RetryConfig,\n    hooks: Option<Arc<dyn ClientHooks>>,\n",
        1,
    );
    output = output.replacen(
        "\nfn kaji_query_value",
        "\n/// Retry policy applied to safe generated requests. The default makes three attempts.\n#[derive(Clone, Debug)]\npub struct RetryConfig {\n    pub max_attempts: usize,\n    pub initial_delay: Duration,\n    pub max_delay: Duration,\n}\n\nimpl Default for RetryConfig {\n    fn default() -> Self {\n        Self { max_attempts: 3, initial_delay: Duration::from_millis(250), max_delay: Duration::from_secs(8) }\n    }\n}\n\n/// Metadata passed to lifecycle hooks. Request headers and bodies are omitted to avoid exposing credentials.\n#[derive(Clone, Debug)]\npub struct RequestInfo {\n    pub method: Method,\n    pub url: String,\n}\n\n/// The final HTTP response observed by lifecycle hooks.\n#[derive(Clone, Debug)]\npub struct ResponseInfo {\n    pub request: RequestInfo,\n    pub status: reqwest::StatusCode,\n    pub headers: reqwest::header::HeaderMap,\n}\n\n/// Optional package-level observability and policy callbacks. Hooks run once for the final outcome, not every retry attempt.\npub trait ClientHooks: Send + Sync {\n    fn before_request(&self, _request: &RequestInfo) {}\n    fn after_response(&self, _response: &ResponseInfo) {}\n    fn on_error(&self, _request: &RequestInfo, _error: &str) {}\n}\n\nfn kaji_query_value",
        1,
    );
    if has_pagination {
        output.push_str(render_pagination_runtime());
    }
    for operation in &api.operations {
        output.push_str(&render_operation_error(operation));
        if operation_has_parameters(operation) {
            output.push_str(&render_operation_request(operation));
        }
    }
    output.push_str(
        "impl Client {\n    pub fn new(base_url: impl Into<String>) -> Self {\n        Self { base_url: base_url.into().trim_end_matches('/').to_owned(), http: reqwest::Client::new(), bearer_token: None }\n    }\n\n    /// Configures a bearer token for operations that declare OpenAPI security.\n    /// Other credential kinds are intentionally not guessed by this generated client.\n    pub fn with_bearer_token(mut self, token: impl Into<String>) -> Self {\n        self.bearer_token = Some(token.into());\n        self\n    }\n\n",
    );
    output = output.replacen(
        "Self { base_url: base_url.into().trim_end_matches('/').to_owned(), http: reqwest::Client::new(), bearer_token: None }",
        "Self { base_url: base_url.into().trim_end_matches('/').to_owned(), http: reqwest::Client::new(), bearer_token: None, retry: RetryConfig::default(), hooks: None }",
        1,
    );
    output = output.replacen(
        "    /// Configures a bearer token for operations that declare OpenAPI security.\n",
        "    /// Replaces the conservative default retry policy. Set `max_attempts` to one to disable retries.\n    pub fn with_retry(mut self, retry: RetryConfig) -> Self {\n        self.retry = retry;\n        self\n    }\n\n    /// Adds package-level lifecycle hooks without changing generated operation signatures.\n    pub fn with_hooks(mut self, hooks: Arc<dyn ClientHooks>) -> Self {\n        self.hooks = Some(hooks);\n        self\n    }\n\n    fn kaji_before_request(&self, request: &RequestInfo) {\n        if let Some(hooks) = &self.hooks { hooks.before_request(request); }\n    }\n\n    fn kaji_after_response(&self, request: &RequestInfo, response: &reqwest::Response) {\n        if let Some(hooks) = &self.hooks {\n            hooks.after_response(&ResponseInfo { request: request.clone(), status: response.status(), headers: response.headers().clone() });\n        }\n    }\n\n    fn kaji_on_error(&self, request: &RequestInfo, error: &str) {\n        if let Some(hooks) = &self.hooks { hooks.on_error(request, error); }\n    }\n\n    fn kaji_retry_delay(&self, completed_attempts: usize, retry_after: Option<Duration>) -> Duration {\n        if let Some(retry_after) = retry_after { return retry_after.min(self.retry.max_delay); }\n        let factor = 1_u32 << completed_attempts.saturating_sub(1).min(16);\n        self.retry.initial_delay.saturating_mul(factor).min(self.retry.max_delay)\n    }\n\n    /// Configures a bearer token for operations that declare OpenAPI security.\n",
        1,
    );
    for operation in &api.operations {
        output.push_str(&render_operation(operation, config));
    }
    output.push_str("}\n");
    if resource_client_enabled(config) {
        output.push('\n');
        output.push_str(&render_resource_clients(api));
    }
    output
}

fn render_operation(operation: &Operation, config: &GeneratorConfig) -> String {
    let method_name = rust_field_name(
        config
            .get("operation_prefix")
            .map(|prefix| format!("{prefix}_{}", operation.id))
            .unwrap_or_else(|| operation.id.clone())
            .as_str(),
    );
    let response = operation_response_type(operation);
    let error = operation_error_name(operation);
    let pagination = rust_pagination(operation);
    let parameters = if operation_has_parameters(operation) {
        format!(", input: {}", operation_request_name(operation))
    } else {
        String::new()
    };
    let request_body = operation
        .request_type
        .as_deref()
        .map(rust_type_name)
        .map(|request| format!(", body: &{request}"))
        .unwrap_or_default();
    let path_binding = if operation
        .parameters
        .iter()
        .any(|parameter| parameter.location == "path")
    {
        "mut "
    } else {
        ""
    };
    let query_binding = if operation
        .parameters
        .iter()
        .any(|parameter| parameter.location == "query")
    {
        "mut "
    } else {
        ""
    };
    let mut output = format!(
        "    /// Invokes {} {}.\n    pub async fn {method_name}(&self{parameters}{request_body}) -> Result<{response}, {error}> {{\n        let {path_binding}path = {:?}.to_owned();\n        let {query_binding}query: Vec<(String, String)> = Vec::new();\n",
        operation.method.as_str(),
        operation.path,
        operation.path,
    );
    for parameter in &operation.parameters {
        render_parameter_use(&mut output, parameter);
    }
    let retry_allowed = rust_retry_allowed(operation);
    output.push_str(&format!(
        "        let request_url = format!(\"{{}}{{}}\", self.base_url, path);\n        let request_info = RequestInfo {{ method: Method::{}, url: request_url.clone() }};\n        self.kaji_before_request(&request_info);\n        let retry_allowed = {retry_allowed};\n        let max_attempts = self.retry.max_attempts.max(1);\n        let mut attempt = 0_usize;\n        loop {{\n            attempt += 1;\n            let mut request = self.http.request(Method::{}, request_url.clone());\n            if !query.is_empty() {{ request = request.query(&query); }}\n",
        operation.method.as_str(),
        operation.method.as_str(),
    ));
    for parameter in &operation.parameters {
        if parameter.location == "header" {
            render_header_use(&mut output, parameter);
        }
    }
    if !operation.security.is_empty() {
        output.push_str("        if let Some(token) = &self.bearer_token { request = request.bearer_auth(token); }\n");
    }
    if operation.request_type.is_some() {
        match request_media_kind(operation) {
            RequestMediaKind::Json | RequestMediaKind::Unknown => {
                output.push_str("        request = request.json(body);\n");
            }
            RequestMediaKind::Unsupported(content_type) => {
                let _ = writeln!(
                    output,
                    "        return Err({error}::UnsupportedRequestMedia({content_type:?}));"
                );
            }
        }
    }
    output.push_str(&format!(
        "            let response = match request.send().await {{\n                Ok(response) => response,\n                Err(source) => {{\n                    if retry_allowed && attempt < max_attempts {{\n                        tokio::time::sleep(self.kaji_retry_delay(attempt, None)).await;\n                        continue;\n                    }}\n                    self.kaji_on_error(&request_info, &source.to_string());\n                    return Err({error}::Transport(source));\n                }}\n            }};\n            let status = response.status();\n            let retry_after = response.headers().get(reqwest::header::RETRY_AFTER).and_then(|value| value.to_str().ok()).and_then(|value| value.parse::<u64>().ok()).map(Duration::from_secs);\n            if retry_allowed && attempt < max_attempts && matches!(status.as_u16(), 408 | 429 | 500 | 502 | 503 | 504) {{\n                tokio::time::sleep(self.kaji_retry_delay(attempt, retry_after)).await;\n                continue;\n            }}\n            self.kaji_after_response(&request_info, &response);\n            if !status.is_success() {{\n                let headers = response.headers().clone();\n                let body = response.bytes().await.map_err({error}::Transport)?.to_vec();\n                self.kaji_on_error(&request_info, &format!(\"HTTP {{}}\", status));\n                return Err({});\n            }}\n",
        render_error_response(operation, &error),
    ));
    match response_kind(operation) {
        ResponseKind::Empty => output.push_str("            return Ok(());\n"),
        ResponseKind::Binary => output.push_str(&format!(
            "            return response.bytes().await.map(|body| body.to_vec()).map_err({error}::Transport);\n"
        )),
        ResponseKind::ServerSentEvents => output.push_str("            return Ok(response);\n"),
        ResponseKind::Text => output.push_str(&format!(
            "            return response.bytes().await.map(|body| String::from_utf8_lossy(&body).into_owned()).map_err({error}::Transport);\n"
        )),
        ResponseKind::Json => output.push_str(&format!(
            "            let headers = response.headers().clone();\n            let body = response.bytes().await.map_err({error}::Transport)?.to_vec();\n            return match serde_json::from_slice::<{response}>(&body) {{\n                Ok(value) => Ok(value),\n                Err(source) => {{\n                    self.kaji_on_error(&request_info, &source.to_string());\n                    Err({error}::Decode {{ source, response: ApiResponse {{ status, headers, body }} }})\n                }}\n            }};\n"
        )),
    }
    output.push_str("        }\n    }\n\n");
    if let Some(pagination) = pagination {
        output.push_str(&render_rust_pagination_iterator(
            &method_name,
            operation,
            &pagination,
        ));
    }
    output
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum ResponseKind {
    Empty,
    Json,
    Text,
    Binary,
    ServerSentEvents,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum RequestMediaKind<'a> {
    Json,
    Unknown,
    Unsupported(&'a str),
}

/// Pagination that can be expressed without changing the generated operation
/// contract. Every continuation re-enters the normal generated operation, so
/// path escaping, header serialization, auth, retries, and hooks stay intact.
#[derive(Clone, Debug)]
enum RustPagination {
    Cursor {
        field: RustPaginationField,
        next_cursor_path: String,
    },
    OffsetLimit {
        step: RustOffsetStep,
        limit_field: Option<String>,
        results_path: Option<String>,
        num_pages_path: Option<String>,
    },
}

#[derive(Clone, Debug)]
enum RustOffsetStep {
    Page { field: String },
    Offset { field: String },
}

/// A scalar request field Kaji can replace without reconstructing the request.
/// Required fields deliberately remain required: the caller supplies the first
/// value and the pager replaces it only after receiving a declared next value.
#[derive(Clone, Debug)]
struct RustPaginationField {
    name: String,
    optional: bool,
}

/// Read Kaji's native pagination declaration and its Speakeasy-compatible
/// spelling. Header and path cursor fields are safe because the generated
/// operation remains the only place that serializes them. OpenAPI requires
/// path parameters to be required, so Kaji never invents a first path value.
fn rust_pagination(operation: &Operation) -> Option<RustPagination> {
    if response_kind(operation) != ResponseKind::Json {
        return None;
    }
    let extension = operation
        .annotations
        .get("x-kaji-pagination")
        .or_else(|| operation.annotations.get("x-speakeasy-pagination"))?
        .as_object()?;
    let inputs = extension.get("inputs")?.as_array()?;
    let outputs = extension.get("outputs")?.as_object()?;
    match extension.get("type").and_then(Value::as_str) {
        Some("cursor") => {
            let field = rust_cursor_parameter_field(operation, inputs, "cursor")?;
            Some(RustPagination::Cursor {
                field,
                next_cursor_path: outputs.get("nextCursor")?.as_str()?.to_owned(),
            })
        }
        Some("offsetLimit") => {
            let page = rust_pagination_query_field(operation, inputs, "page", true);
            let offset = rust_pagination_query_field(operation, inputs, "offset", true);
            let step = match (page, offset) {
                (Some(field), _) => RustOffsetStep::Page { field },
                (None, Some(field)) => RustOffsetStep::Offset { field },
                (None, None) => return None,
            };
            let results_path = outputs
                .get("results")
                .and_then(Value::as_str)
                .map(str::to_owned);
            let num_pages_path = outputs
                .get("numPages")
                .and_then(Value::as_str)
                .map(str::to_owned);
            if matches!(&step, RustOffsetStep::Page { .. }) && num_pages_path.is_none() {
                // Page numbers without a declared final page are ambiguous;
                // don't replace that ambiguity with a guessed empty-result rule.
                return None;
            }
            if matches!(&step, RustOffsetStep::Offset { .. }) && results_path.is_none() {
                return None;
            }
            Some(RustPagination::OffsetLimit {
                step,
                limit_field: rust_pagination_query_field(operation, inputs, "limit", true),
                results_path,
                num_pages_path,
            })
        }
        _ => None,
    }
}

/// Finds a declared string cursor in a query, header, or path parameter.
/// A path cursor must be required under OpenAPI; optional path parameters are
/// invalid and are intentionally rejected even if they reach the AST.
fn rust_cursor_parameter_field(
    operation: &Operation,
    inputs: &[Value],
    kind: &str,
) -> Option<RustPaginationField> {
    let declared = inputs
        .iter()
        .find(|input| input.get("type").and_then(Value::as_str) == Some(kind))?
        .as_object()?;
    if !matches!(
        declared.get("in").and_then(Value::as_str),
        Some("parameters") | None
    ) {
        return None;
    }
    let name = declared.get("name")?.as_str()?;
    let parameter = operation.parameters.iter().find(|parameter| {
        parameter.name == name
            && matches!(parameter.location.as_str(), "query" | "header" | "path")
            && parameter
                .schema
                .as_ref()
                .is_some_and(|schema| matches!(schema.kind, SchemaKind::String))
    })?;
    if parameter.location == "path" && !parameter.required {
        return None;
    }
    Some(RustPaginationField {
        name: rust_field_name(&parameter.name),
        optional: !parameter.required,
    })
}

/// Returns the generated Rust request field for a compatible optional query
/// parameter. `integer` accepts JSON Schema's common integer representation;
/// cursor inputs require strings because OpenAPI cursor output is a string.
fn rust_pagination_query_field(
    operation: &Operation,
    inputs: &[Value],
    kind: &str,
    integer: bool,
) -> Option<String> {
    let declared = inputs
        .iter()
        .find(|input| input.get("type").and_then(Value::as_str) == Some(kind))?
        .as_object()?;
    if !matches!(
        declared.get("in").and_then(Value::as_str),
        Some("parameters") | None
    ) {
        return None;
    }
    let name = declared.get("name")?.as_str()?;
    let parameter = operation.parameters.iter().find(|parameter| {
        parameter.name == name && parameter.location == "query" && !parameter.required
    })?;
    let kind = parameter.schema.as_ref().map(|schema| &schema.kind)?;
    match (integer, kind) {
        (false, SchemaKind::String) | (true, SchemaKind::Integer) => Some(rust_field_name(name)),
        _ => None,
    }
}

fn render_pagination_runtime() -> &'static str {
    r#"
/// Looks up a conservative JSONPath used by a declared pagination extension.
/// Object segments and a single numeric (including negative) array index per
/// segment are supported, for example `$.data[-1].nextCursor`.
fn kaji_json_path<'a>(value: &'a serde_json::Value, path: &str) -> Option<&'a serde_json::Value> {
    let mut current = value;
    for segment in path.strip_prefix('$')?.split('.').filter(|segment| !segment.is_empty()) {
        let (key, index) = match segment.find('[') {
            Some(start) => {
                let end = segment.strip_suffix(']')?;
                let index = end.get(start + 1..)?.parse::<isize>().ok()?;
                (&segment[..start], Some(index))
            }
            None => (segment, None),
        };
        if !key.is_empty() {
            current = current.get(key)?;
        }
        if let Some(index) = index {
            let values = current.as_array()?;
            let index = if index < 0 { values.len().checked_add_signed(index)? } else { index as usize };
            current = values.get(index)?;
        }
    }
    Some(current)
}

"#
}

fn render_rust_pagination_iterator(
    method_name: &str,
    operation: &Operation,
    pagination: &RustPagination,
) -> String {
    let request = operation_request_name(operation);
    let response = operation_response_type(operation);
    let error = operation_error_name(operation);
    let pages_method = format!("{method_name}_pages");
    let (state, next) = match pagination {
        RustPagination::Cursor {
            field,
            next_cursor_path,
        } => {
            let assignment = if field.optional {
                format!("input.{} = Some(cursor.to_owned());", field.name)
            } else {
                format!("input.{} = cursor.to_owned();", field.name)
            };
            (
                "true".to_owned(),
                format!(
                    "            let next = serde_json::to_value(&response).map_err({error}::Pagination)?;\n            let Some(cursor) = kaji_json_path(&next, {next_cursor_path:?}).and_then(serde_json::Value::as_str).filter(|cursor| !cursor.is_empty()) else {{\n                return Ok(Some((response, (client, input, false))));\n            }};\n            {assignment}\n            Ok(Some((response, (client, input, true))))"
                ),
            )
        }
        RustPagination::OffsetLimit {
            step,
            limit_field,
            results_path,
            num_pages_path,
        } => {
            let field = match step {
                RustOffsetStep::Page { field } | RustOffsetStep::Offset { field } => field,
            };
            let continue_condition = match step {
                RustOffsetStep::Page { .. } => format!(
                    "            let Some(current) = input.{field} else {{ return Ok(Some((response, (client, input, false)))); }};\n            let next = serde_json::to_value(&response).map_err({error}::Pagination)?;\n            let Some(num_pages) = kaji_json_path(&next, {path:?}).and_then(serde_json::Value::as_i64) else {{ return Ok(Some((response, (client, input, false)))); }};\n            let next_page = current.saturating_add(1);\n            if next_page > num_pages {{ return Ok(Some((response, (client, input, false)))); }};\n            input.{field} = Some(next_page);\n            Ok(Some((response, (client, input, true))))",
                    path = num_pages_path
                        .as_deref()
                        .expect("validated page pagination"),
                ),
                RustOffsetStep::Offset { .. } => {
                    let results_path = results_path
                        .as_deref()
                        .expect("validated offset pagination");
                    let limit = limit_field
                        .as_ref()
                        .map_or_else(|| "None".to_owned(), |field| format!("input.{field}"));
                    format!(
                        "            let Some(current) = input.{field} else {{ return Ok(Some((response, (client, input, false)))); }};\n            let next = serde_json::to_value(&response).map_err({error}::Pagination)?;\n            let Some(items) = kaji_json_path(&next, {results_path:?}).and_then(serde_json::Value::as_array) else {{ return Ok(Some((response, (client, input, false)))); }};\n            let item_count = items.len() as i64;\n            let limit = {limit};\n            if item_count == 0 || limit.is_some_and(|limit| item_count < limit) {{ return Ok(Some((response, (client, input, false)))); }};\n            input.{field} = Some(current.saturating_add(item_count));\n            Ok(Some((response, (client, input, true))))"
                    )
                }
            };
            ("true".to_owned(), continue_condition)
        }
    };
    format!(
        "    /// Lazily fetches every page using this operation's declared pagination contract.\n    pub fn {pages_method}(&self, input: {request}) -> impl futures_util::Stream<Item = Result<{response}, {error}>> {{\n        let client = self.clone();\n        futures_util::stream::try_unfold((client, input, {state}), |(client, mut input, has_next)| async move {{\n            if !has_next {{ return Ok(None); }}\n            let response = client.{method_name}(input.clone()).await?;\n{next}\n        }})\n    }}\n\n"
    )
}

/// The Rust target intentionally preserves binary and SSE responses instead
/// of attempting to deserialize them as JSON. SSE is returned as a live
/// `reqwest::Response`, which lets callers select their preferred event-stream
/// parser without Kaji silently buffering an unbounded stream.
fn response_kind(operation: &Operation) -> ResponseKind {
    if operation.response_type == "void" {
        return ResponseKind::Empty;
    }
    let content_type = operation
        .responses
        .iter()
        .filter(|response| response.status.starts_with('2'))
        .flat_map(|response| &response.media_types)
        .map(|media| media.content_type.as_str())
        .next();
    match content_type {
        Some("text/event-stream") => ResponseKind::ServerSentEvents,
        Some("application/octet-stream" | "application/pdf" | "image/png" | "image/jpeg") => {
            ResponseKind::Binary
        }
        Some(content_type) if content_type.starts_with("text/") => ResponseKind::Text,
        _ => ResponseKind::Json,
    }
}

fn operation_response_type(operation: &Operation) -> String {
    match response_kind(operation) {
        ResponseKind::Empty => "()".into(),
        ResponseKind::Binary => "Vec<u8>".into(),
        ResponseKind::ServerSentEvents => "reqwest::Response".into(),
        ResponseKind::Text => "String".into(),
        ResponseKind::Json => rust_type_name(&operation.response_type),
    }
}

/// Determines whether a generated operation may participate in automatic
/// retries. POST is deliberately opt-in through a declared idempotency key;
/// optional keys only enable retries when the caller supplied one.
fn rust_retry_allowed(operation: &Operation) -> String {
    match operation.method {
        kaji_core::ast::HttpMethod::Get
        | kaji_core::ast::HttpMethod::Put
        | kaji_core::ast::HttpMethod::Patch
        | kaji_core::ast::HttpMethod::Delete => "true".into(),
        kaji_core::ast::HttpMethod::Post => operation
            .parameters
            .iter()
            .find(|parameter| {
                parameter.location == "header"
                    && parameter.name.eq_ignore_ascii_case("idempotency-key")
            })
            .map(|parameter| {
                if parameter.required {
                    "true".into()
                } else {
                    format!("input.{}.is_some()", rust_field_name(&parameter.name))
                }
            })
            .unwrap_or_else(|| "false".into()),
    }
}

fn request_media_kind(operation: &Operation) -> RequestMediaKind<'_> {
    match operation
        .request_body
        .as_ref()
        .and_then(|body| body.media_types.first())
        .map(|media| media.content_type.as_str())
    {
        None => RequestMediaKind::Unknown,
        Some("application/json" | "application/problem+json") => RequestMediaKind::Json,
        Some(content_type) => RequestMediaKind::Unsupported(content_type),
    }
}

fn operation_error_name(operation: &Operation) -> String {
    format!("{}Error", type_name(&operation.id))
}

fn render_operation_error(operation: &Operation) -> String {
    let error = operation_error_name(operation);
    let mut output = format!(
        "/// Errors returned by `{}`. Declared OpenAPI error bodies are decoded into typed variants.\n#[derive(Debug)]\npub enum {error} {{\n    Transport(reqwest::Error),\n    Decode {{ source: serde_json::Error, response: ApiResponse }},\n    UnsupportedRequestMedia(&'static str),\n",
        operation.id,
    );
    if rust_pagination(operation).is_some() {
        output.push_str("    Pagination(serde_json::Error),\n");
    }
    for response in declared_error_responses(operation) {
        if let Some(body_type) = error_body_type(response) {
            let _ = writeln!(
                output,
                "    {} {{ body: {body_type}, response: ApiResponse }},",
                error_variant_name(&response.status),
            );
        }
    }
    output.push_str("    Unexpected(ApiResponse),\n}\n\n");
    output
}

fn declared_error_responses(
    operation: &Operation,
) -> impl Iterator<Item = &kaji_core::ast::OperationResponse> {
    operation.responses.iter().filter(|response| {
        response.status == "default"
            || response
                .status
                .parse::<u16>()
                .is_ok_and(|status| (400..600).contains(&status))
    })
}

fn error_body_type(response: &kaji_core::ast::OperationResponse) -> Option<String> {
    response
        .media_types
        .first()
        .and_then(|media| media.schema.as_ref())
        .map(rust_type)
}

fn error_variant_name(status: &str) -> String {
    match status {
        "400" => "BadRequest".into(),
        "401" => "Unauthorized".into(),
        "402" => "PaymentRequired".into(),
        "403" => "Forbidden".into(),
        "404" => "NotFound".into(),
        "409" => "Conflict".into(),
        "422" => "UnprocessableEntity".into(),
        "429" => "TooManyRequests".into(),
        "500" => "InternalServerError".into(),
        "501" => "NotImplemented".into(),
        "502" => "BadGateway".into(),
        "503" => "ServiceUnavailable".into(),
        "504" => "GatewayTimeout".into(),
        "default" => "Default".into(),
        status => format!("Status{}", type_name(status)),
    }
}

fn render_error_response(operation: &Operation, error: &str) -> String {
    let mut output = String::from("match status.as_u16() {\n");
    for response in declared_error_responses(operation) {
        let Ok(status) = response.status.parse::<u16>() else {
            continue;
        };
        let Some(body_type) = error_body_type(response) else {
            continue;
        };
        let variant = error_variant_name(&response.status);
        let _ = writeln!(
            output,
            "                {status} => match serde_json::from_slice::<{body_type}>(&body) {{ Ok(body) => {error}::{variant} {{ body, response: ApiResponse {{ status, headers, body: body.clone() }} }}, Err(_) => {error}::Unexpected(ApiResponse {{ status, headers, body }}) }},"
        );
    }
    let default_body_type = declared_error_responses(operation)
        .find(|response| response.status == "default")
        .and_then(error_body_type);
    if let Some(body_type) = default_body_type {
        let _ = writeln!(
            output,
            "                _ => match serde_json::from_slice::<{body_type}>(&body) {{ Ok(body) => {error}::Default {{ body, response: ApiResponse {{ status, headers, body: body.clone() }} }}, Err(_) => {error}::Unexpected(ApiResponse {{ status, headers, body }}) }},"
        );
    } else {
        output.push_str(&format!(
            "                _ => {error}::Unexpected(ApiResponse {{ status, headers, body }}),\n"
        ));
    }
    output.push_str("            }");
    output
}

fn operation_has_parameters(operation: &Operation) -> bool {
    !operation.parameters.is_empty()
}

fn operation_request_name(operation: &Operation) -> String {
    format!("{}Request", type_name(&operation.id))
}

fn render_operation_request(operation: &Operation) -> String {
    let all_optional = operation
        .parameters
        .iter()
        .all(|parameter| !parameter.required);
    let derive = if all_optional {
        "#[derive(Clone, Debug, Default)]"
    } else {
        "#[derive(Clone, Debug)]"
    };
    let mut output = format!(
        "{derive}\npub struct {} {{\n",
        operation_request_name(operation)
    );
    for parameter in &operation.parameters {
        let name = rust_field_name(&parameter.name);
        let mut value_type = parameter
            .schema
            .as_ref()
            .map(rust_type)
            .unwrap_or_else(|| "serde_json::Value".into());
        if !parameter.required && !value_type.starts_with("Option<") {
            value_type = format!("Option<{value_type}>");
        }
        let _ = writeln!(output, "    pub {name}: {value_type},");
    }
    output.push_str("}\n\n");
    output
}

fn render_parameter_use(output: &mut String, parameter: &OperationParameter) {
    let field = format!("input.{}", rust_field_name(&parameter.name));
    match parameter.location.as_str() {
        "path" => {
            if parameter.required {
                let _ = writeln!(
                    output,
                    "        path = path.replace({:?}, &kaji_path_segment(&kaji_query_value(&{field})));",
                    format!("{{{}}}", parameter.name),
                );
            } else {
                let _ = writeln!(
                    output,
                    "        if let Some(value) = {field}.as_ref() {{ path = path.replace({:?}, &kaji_path_segment(&kaji_query_value(value))); }}",
                    format!("{{{}}}", parameter.name),
                );
            }
        }
        "query" => {
            if parameter.required {
                let _ = writeln!(
                    output,
                    "        query.push(({:?}.into(), kaji_query_value(&{field})));",
                    parameter.name,
                );
            } else {
                let _ = writeln!(
                    output,
                    "        if let Some(value) = {field}.as_ref() {{ query.push(({:?}.into(), kaji_query_value(value))); }}",
                    parameter.name,
                );
            }
        }
        _ => {}
    }
}

fn render_header_use(output: &mut String, parameter: &OperationParameter) {
    let field = format!("input.{}", rust_field_name(&parameter.name));
    if parameter.required {
        let _ = writeln!(
            output,
            "        request = request.header({:?}, kaji_query_value(&{field}));",
            parameter.name,
        );
    } else {
        let _ = writeln!(
            output,
            "        if let Some(value) = {field}.as_ref() {{ request = request.header({:?}, kaji_query_value(value)); }}",
            parameter.name,
        );
    }
}

