//! Native Rust SDK rendering.
//!
//! The generated client uses `reqwest`, `serde`, and `serde_json`, which are
//! conventional, well-maintained Rust choices. Complex JSON Schema constructs
//! that do not map soundly to a named Rust type are represented as
//! `serde_json::Value` rather than silently narrowed.

use std::{collections::BTreeMap, fmt::Write};

use anyhow::Result;
use serde_json::Value;

use poolster_core::ast::{
    AdditionalProperties, Api, Operation, OperationParameter, Schema, SchemaKind, SchemaValue,
};
use poolster_core::{GeneratedFile, GeneratedTree, SdkClientStyle};

fn append_source_layout_diagnostics(files: &mut Vec<GeneratedFile>, path: &str) -> Result<()> {
    let oversized = files.iter().filter(|file| file.path.extension().and_then(|value| value.to_str()) == Some("rs") && file.contents.len() > 128 * 1024).map(|file| serde_json::json!({"path":file.path,"bytes":file.contents.len(),"max_file_bytes":128*1024,"reason":"Atomic Rust declaration exceeds grouping budget; source retained intact to preserve typed public API."})).collect::<Vec<_>>();
    if !oversized.is_empty() {
        files.push(GeneratedFile::new(
            path,
            serde_json::to_string_pretty(&oversized)?,
        )?);
    }
    Ok(())
}

const NOTICE: &str = "// Generated by Poolster Codegen. Do not edit.\n";

pub(super) struct RenderOptions {
    pub crate_name: Option<String>,
    pub client_style: SdkClientStyle,
    pub operation_prefix: Option<String>,
    pub open_unions: bool,
    pub open_enums: bool,
}

impl Default for RenderOptions {
    fn default() -> Self {
        Self {
            crate_name: None,
            client_style: SdkClientStyle::Namespaced,
            operation_prefix: None,
            open_unions: false,
            open_enums: false,
        }
    }
}

pub(super) fn generate_sdk(api: &Api, options: &RenderOptions) -> Result<GeneratedTree> {
    let prepared = prepare_api(api);
    let api = &prepared;
    let mut tree = GeneratedTree::default();
    for file in RustModels
        .generate(api, options)?
        .into_iter()
        .chain(RustReqwest.generate(api, options)?)
        .chain(RustPackage.generate(api, options)?)
    {
        tree.insert(file)?;
    }
    tree.insert(GeneratedFile::new(
        "src/transport.rs",
        super::composition::DEFAULT_TRANSPORT,
    )?)?;
    let oversized = tree.iter().filter(|(path, source)| path.extension().and_then(|value| value.to_str()) == Some("rs") && source.len() > 128 * 1024).map(|(path, source)| serde_json::json!({"path":path,"bytes":source.len(),"max_file_bytes":128*1024,"reason":"Atomic Rust model, request or operation declaration exceeds the grouping budget; retained intact to preserve native types."})).collect::<Vec<_>>();
    if !oversized.is_empty() {
        tree.insert(GeneratedFile::new(
            ".poolster/source-layout-diagnostics.json",
            serde_json::to_string_pretty(&oversized)?,
        )?)?;
    }
    Ok(tree)
}

#[derive(Default)]
pub(crate) struct RustModels;

impl RustModels {
    pub(crate) fn generate(
        &self,
        api: &Api,
        options: &RenderOptions,
    ) -> Result<Vec<GeneratedFile>> {
        let prepared = prepare_api(api);
        let api = &prepared;
        let mut files = Vec::with_capacity(api.schemas.len() + 64);
        let mut root_index = String::new();
        for (chunk_index, schemas) in api.schemas.chunks(MODELS_PER_FILE).enumerate() {
            let chunk = format!("chunk_{:04}", chunk_index + 1);
            let _ = writeln!(root_index, "mod {chunk};");
            let _ = writeln!(root_index, "pub use {chunk}::*;");
            let mut chunk_index_source = String::new();
            for (offset, schema) in schemas.iter().enumerate() {
                let index = chunk_index * MODELS_PER_FILE + offset;
                let module = schema_module_name(&schema.name, index);
                let _ = writeln!(chunk_index_source, "mod {module};");
                let _ = writeln!(chunk_index_source, "pub use {module}::*;");
                files.push(GeneratedFile::new(
                    format!("src/models/{chunk}/{module}.rs"),
                    render_model_for_api(api, schema, options.open_unions, options.open_enums),
                )?);
            }
            files.push(GeneratedFile::new(
                format!("src/models/{chunk}/mod.rs"),
                format!("{NOTICE}\n{chunk_index_source}"),
            )?);
        }
        files.insert(
            0,
            GeneratedFile::new("src/models/mod.rs", format!("{NOTICE}\n#[allow(dead_code)]\npub(crate) fn poolster_deserialize_optional_nullable<'de, D, T>(deserializer: D) -> Result<Option<Option<T>>, D::Error> where D: serde::Deserializer<'de>, T: serde::Deserialize<'de> {{ <Option<T> as serde::Deserialize>::deserialize(deserializer).map(Some) }}\n{root_index}"))?,
        );
        append_source_layout_diagnostics(
            &mut files,
            ".poolster/source-layout-model-diagnostics.json",
        )?;
        Ok(files)
    }
}

#[derive(Default)]
struct RustReqwest;

impl RustReqwest {
    fn generate(&self, api: &Api, options: &RenderOptions) -> Result<Vec<GeneratedFile>> {
        render_client_files(api, options)
    }
}

#[derive(Default)]
struct RustPackage;

impl RustPackage {
    fn generate(&self, api: &Api, options: &RenderOptions) -> Result<Vec<GeneratedFile>> {
        let crate_name = options
            .crate_name
            .clone()
            .unwrap_or_else(|| format!("{}-sdk", kebab_case(&api.name)));
        Ok(vec![
            GeneratedFile::new("src/lib.rs", render_lib())?,
            GeneratedFile::new("Cargo.toml", render_cargo_toml_for_api(&crate_name, api))?,
            GeneratedFile::new("README.md", render_readme(api, &crate_name, options))?,
        ])
    }
}

