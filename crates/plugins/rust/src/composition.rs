pub const DEFAULT_TRANSPORT: &str = r#"// Generated by Poolster. Do not edit.
use std::{future::Future, pin::Pin};
pub type TransportFuture<'a> = Pin<Box<dyn Future<Output = Result<reqwest::Response, reqwest::Error>> + Send + 'a>>;
/// Executors may inspect or transform fully encoded requests. Cancellation
/// propagates when the returned future is dropped. Responses retain reqwest ABI.
pub trait Transport: Send + Sync { fn execute(&self, request: reqwest::Request) -> TransportFuture<'_>; }
/// A request middleware owns its request and may modify it before calling next,
/// transform the response/error afterwards, or return without calling next.
/// Runs once per transport attempt, inside the generated client's retry policy.
/// HTTP status/decode errors are classified by the client after this layer.
pub trait Middleware: Send + Sync {
    fn handle<'a>(&'a self, request: reqwest::Request, next: &'a dyn Transport) -> TransportFuture<'a>;
}
/// Composable executor: outer middleware runs first on requests and last on responses.
pub struct MiddlewareTransport<M, T> { middleware: M, inner: T }
impl<M, T> MiddlewareTransport<M, T> {
    pub fn new(middleware: M, inner: T) -> Self { Self { middleware, inner } }
}
impl<M: Middleware, T: Transport> Transport for MiddlewareTransport<M, T> {
    fn execute(&self, request: reqwest::Request) -> TransportFuture<'_> {
        self.middleware.handle(request, &self.inner)
    }
}
impl<T: Transport + ?Sized> Transport for std::sync::Arc<T> {
    fn execute(&self, request: reqwest::Request) -> TransportFuture<'_> { (**self).execute(request) }
}
#[derive(Default)]
pub struct DefaultTransport { client: reqwest::Client }
impl Transport for DefaultTransport {
    fn execute(&self, request: reqwest::Request) -> TransportFuture<'_> { Box::pin(self.client.execute(request)) }
}
"#;
