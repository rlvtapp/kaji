#[derive(Default)]
pub struct Workspace {
    pub(crate) graphql_package: Option<crate::graphql::NativePackage>,
    pub(crate) http_api: Option<poolster_core::Api>,
    pub(crate) operation_tests: bool,
    pub(crate) webhooks: bool,
    pub(crate) oauth: bool,
    pub(crate) models: bool,
    pub(crate) tests: bool,
    pub(crate) operations: bool,
    pub(crate) resources: bool,
    pub(crate) transport: Option<Transport>,
}
impl Workspace {
    pub fn finalize(cx: &mut FinalizeContext<'_, Rust>) -> Result<()> {
        if let Some(package) = cx.workspace.graphql_package.take() {
            return package.finalize(cx);
        }
        let selected_api = cx.workspace.http_api.clone();
        let api = selected_api.as_ref().unwrap_or(cx.api);
        if !cx.workspace.models && !cx.workspace.operations {
            return Ok(());
        }
        let mut exports = String::from(
            "// Generated by Poolster. Do not edit.\npub mod models;\n#[allow(unused_imports)]\npub use models::*;\n",
        );
        if cx.workspace.operations {
            let transport = cx.workspace.transport.as_ref().unwrap();
            let module = transport
                .module
                .strip_prefix("crate::")
                .unwrap_or(&transport.module);
            anyhow::ensure!(
                !module.contains("::")
                    && !module.is_empty()
                    && module
                        .chars()
                        .all(|ch| ch.is_ascii_alphanumeric() || ch == '_'),
                "Rust transport module must be a root module identifier"
            );
            exports.push_str(&format!(
                "pub mod {module};\npub mod client;\npub use client::*;\n"
            ));
            let runtime = render::render_client_runtime(api, cx.workspace.resources)
                .replace(
                    "crate::transport::Transport",
                    &format!("{}::Transport", transport.module),
                )
                .replace(
                    "crate::transport::DefaultTransport::default()",
                    &transport.constructor,
                );
            cx.files
                .emit(GeneratedFile::new("src/client/mod.rs", runtime)?)?;
        }
        if cx.workspace.oauth {
            exports.push_str("pub mod oauth;\npub use oauth::*;\n");
        }
        if cx.workspace.webhooks {
            exports.push_str("pub mod webhooks;\npub use webhooks::*;\n");
        }
        if cx.workspace.operation_tests {
            exports.push_str("#[cfg(test)] mod operation_tests;\n");
        }
        if cx.workspace.tests {
            exports.push_str("#[cfg(test)] mod roundtrip_tests;\n");
        }
        cx.files.emit(GeneratedFile::new("src/lib.rs", exports)?)?;
        let name = cx
            .settings
            .package_name
            .clone()
            .unwrap_or_else(|| format!("{}-sdk", render::kebab_case(&api.name)));
        cx.files.emit(GeneratedFile::new(
            "Cargo.toml",
            render::render_cargo_toml_for_api(&name, api) + if cx.workspace.oauth && !cx.workspace.webhooks { "base64 = \"0.22\"\n" } else { "" } + if cx.workspace.webhooks { "hmac = \"0.12\"\nsha2 = \"0.10\"\nbase64 = \"0.22\"\n" } else { "" } + if cx.workspace.operation_tests { "\n[dev-dependencies]\nhttp = \"1\"\ntokio = { version = \"1\", features = [\"macros\", \"rt-multi-thread\"] }\n" } else { "" },
        )?)
    }
}
#[derive(Clone, Copy)]
enum Part {
    Models,
    Transport,
    Operations,
    Client,
}
pub struct Provider {
    http_input: poolster_core::engine::HttpInput,
    meta: Meta,
    part: Part,
    models: Option<Handle<Models>>,
    transport: Option<Handle<Transport>>,
    operations: Option<Handle<Operations>>,
    prefix: Option<String>,
    namespaced: bool,
}
fn provider(part: Part) -> Provider {
    Provider {
        http_input: Default::default(),
        meta: Meta::new(),
        part,
        models: None,
        transport: None,
        operations: None,
        prefix: None,
        namespaced: true,
    }
}
pub fn models() -> Provider {
    provider(Part::Models)
}
pub fn transport() -> Provider {
    provider(Part::Transport)
}
pub fn operations() -> Provider {
    provider(Part::Operations)
}
pub fn client() -> Provider {
    provider(Part::Client)
}
impl Provider {
    pub fn using_models(mut self, value: Handle<Models>) -> Self {
        self.models = Some(value);
        self
    }
    pub fn using_transport(mut self, value: Handle<Transport>) -> Self {
        self.transport = Some(value);
        self
    }
    pub fn using_operations(mut self, value: Handle<Operations>) -> Self {
        self.operations = Some(value);
        self
    }
    pub fn models_handle(&self) -> Handle<Models> {
        self.meta.handle()
    }
    pub fn transport_handle(&self) -> Handle<Transport> {
        self.meta.handle()
    }
    pub fn operations_handle(&self) -> Handle<Operations> {
        self.meta.handle()
    }
    pub fn client_handle(&self) -> Handle<Client> {
        self.meta.handle()
    }
    pub fn operation_prefix(mut self, value: impl Into<String>) -> Self {
        self.prefix = Some(value.into());
        self
    }
    pub fn flat(mut self) -> Self {
        self.namespaced = false;
        self
    }
}
impl Plugin<Rust> for Provider {
    fn supports_native_input(&self) -> bool {
        self.http_input.is_explicit()
    }
    fn kind(&self) -> &'static str {
        match self.part {
            Part::Models => "rust-models",
            Part::Transport => "rust-transport",
            Part::Operations => "rust-operations",
            Part::Client => "rust-client",
        }
    }
    fn meta(&self) -> &Meta {
        &self.meta
    }
    fn provides(&self) -> Vec<Provision> {
        vec![match self.part {
            Part::Models => Provision::of::<Models>(),
            Part::Transport => Provision::of::<Transport>(),
            Part::Operations => Provision::of::<Operations>(),
            Part::Client => Provision::of::<Client>(),
        }]
    }
    fn requires(&self) -> Vec<Requirement> {
        let mut requirements = self.http_input.requirements();
        requirements.extend({
            match self.part {
                Part::Operations => vec![
                    Requirement::on(self.models),
                    Requirement::on(self.transport),
                ],
                Part::Client => vec![Requirement::on(self.operations)],
                _ => vec![],
            }
        });
        requirements
    }
    fn generate(&self, cx: &mut PluginContext<'_, Rust>) -> Result<()> {
        self.http_input.with_context(cx, |cx| {
            if matches!(self.part, Part::Operations) || cx.workspace.http_api.is_none() {
                cx.workspace.http_api = Some(cx.api.clone());
            }
            let mut options = render::RenderOptions {
                crate_name: cx.settings.package_name.clone(),
                client_style: SdkClientStyle::Flat,
                operation_prefix: self.prefix.clone(),
                open_unions: cx.settings.open_unions,
                open_enums: cx.settings.open_enums,
            };
            match self.part {
                Part::Models => {
                    for file in render::RustModels.generate(cx.api, &options)? {
                        cx.files.emit(file)?;
                    }
                    cx.workspace.models = true;
                    cx.publish(model_contract(cx.api))?;
                }
                Part::Transport => {
                    cx.files
                        .emit(GeneratedFile::new("src/transport.rs", DEFAULT_TRANSPORT)?)?;
                    cx.publish(default_transport())?;
                }
                Part::Operations => {
                    let _ = cx.inputs.get::<Models>()?;
                    let transport = cx.inputs.get::<Transport>()?.clone();
                    for file in render::render_operation_files(cx.api, &options)? {
                        cx.files.emit(file)?;
                    }
                    cx.workspace.operations = true;
                    cx.workspace.transport = Some(transport);
                    cx.publish(operation_contract(cx.api, self.prefix.clone()))?;
                }
                Part::Client => {
                    options.operation_prefix = cx.inputs.get::<Operations>()?.prefix.clone();
                    if self.namespaced {
                        options.client_style = SdkClientStyle::Namespaced;
                        for file in render::render_resource_files(cx.api, &options)? {
                            cx.files.emit(file)?;
                        }
                        cx.workspace.resources = true;
                    }
                    cx.publish(Client {
                        symbol: "crate::Client".into(),
                    })?;
                }
            }
            Ok(())
        })
    }
}
pub(crate) fn model_contract(api: &poolster_core::Api) -> Models {
    let prepared = render::prepare_api(api);
    Models {
        symbols: api
            .schemas
            .iter()
            .zip(prepared.schemas.iter())
            .map(|(schema, native)| {
                (
                    schema.name.clone(),
                    format!("crate::models::{}", render::type_name(&native.name)),
                )
            })
            .collect(),
    }
}
pub(crate) fn operation_contract(api: &poolster_core::Api, prefix: Option<String>) -> Operations {
    let prepared = render::prepare_api(api);
    Operations {
        methods: api
            .operations
            .iter()
            .zip(prepared.operations.iter())
            .map(|(operation, native)| {
                (
                    operation.id.clone(),
                    format!(
                        "{}{}",
                        prefix
                            .as_ref()
                            .map(|prefix| format!("{}_", render::rust_field_name(prefix)))
                            .unwrap_or_default(),
                        render::rust_field_name(&native.id)
                    ),
                )
            })
            .collect(),
        prefix,
    }
}
pub(crate) fn default_transport() -> Transport {
    Transport {
        module: "crate::transport".into(),
        constructor: "crate::transport::DefaultTransport::default()".into(),
    }
}

/// Emits executable decode/encode checks from shared schema-derived JSON fixtures.
pub struct RoundtripTests {
    http_input: poolster_core::engine::HttpInput,
    meta: Meta,
    models: Option<Handle<Models>>,
    options: poolster_core::samples::SampleOptions,
}
pub fn roundtrip_tests() -> RoundtripTests {
    RoundtripTests {
        http_input: Default::default(),
        meta: Meta::new(),
        models: None,
        options: Default::default(),
    }
}
impl RoundtripTests {
    pub fn using_models(mut self, value: Handle<Models>) -> Self {
        self.models = Some(value);
        self
    }
    pub fn options(mut self, value: poolster_core::samples::SampleOptions) -> Self {
        self.options = value;
        self
    }
}
impl Plugin<Rust> for RoundtripTests {
    fn supports_native_input(&self) -> bool {
        self.http_input.is_explicit()
    }
    fn kind(&self) -> &'static str {
        "rust-roundtrip-tests"
    }
    fn meta(&self) -> &Meta {
        &self.meta
    }
    fn requires(&self) -> Vec<Requirement> {
        let mut requirements = self.http_input.requirements();
        requirements.extend(vec![Requirement::on(self.models)]);
        requirements
    }
    fn generate(&self, cx: &mut PluginContext<'_, Rust>) -> Result<()> {
        self.http_input.with_context(cx, |cx| {
        let models = cx.inputs.get::<Models>()?;
        let mut source = String::from("// Generated by Poolster. Do not edit.\n");
        let mut diagnostics = BTreeMap::new();
        for (index, schema) in cx.api.schemas.iter().enumerate() {
            let symbol = models
                .symbols
                .get(&schema.name)
                .ok_or_else(|| anyhow::anyhow!("missing model symbol {}", schema.name))?;
            let report =
                poolster_core::samples::schema_samples(cx.api, &schema.value, self.options);
            diagnostics.insert(schema.name.clone(), report.diagnostics);
            for (sample_index, sample) in report.samples.iter().enumerate() {
                let json = serde_json::to_string(&sample.value)?;
                source.push_str(&format!("#[test]\nfn schema_{index}_sample_{sample_index}() {{\n let input: serde_json::Value = serde_json::from_str({json:?}).unwrap();\n let model: {symbol} = serde_json::from_value(input.clone()).unwrap();\n let output = serde_json::to_value(model).unwrap();\n assert_eq!(input, output, {:?});\n}}\n",format!("{} {}",schema.name,sample.name)));
            }
        }
        // Unit test module uses the published crate:: model symbols directly.
        source.insert_str(0, "#[cfg(test)]\nmod poolster_generated_roundtrips {\n");
        source.push_str("}\n");
        cx.files
            .emit(GeneratedFile::new("src/roundtrip_tests.rs", source)?)?;
        cx.workspace.tests = true;
        cx.files.emit(GeneratedFile::new(
            ".poolster/roundtrip-diagnostics.json",
            serde_json::to_string_pretty(&diagnostics)? + "\n",
        )?)
     })
    }
}

