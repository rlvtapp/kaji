fn operation_groups(api: &Api) -> Vec<String> {
    let mut groups = api
        .operations
        .iter()
        .map(operation_resource_name)
        .collect::<Vec<_>>();
    groups.sort();
    groups.dedup();
    groups
}

fn operation_resource_name(operation: &Operation) -> String {
    let tag = operation
        .annotations
        .get("tags")
        .and_then(serde_json::Value::as_array)
        .and_then(|tags| tags.first())
        .and_then(serde_json::Value::as_str);
    tag.map(pascal_case)
        .unwrap_or_else(|| pascal_case(&path_resource_segment(&operation.path)))
}

fn path_resource_segment(path: &str) -> String {
    path.split('/')
        .filter(|segment| !segment.is_empty() && !segment.starts_with('{'))
        .find(|segment| {
            let lowered = segment.to_ascii_lowercase();
            lowered != "api"
                && lowered != "email"
                && !(lowered.starts_with('v')
                    && lowered.len() > 1
                    && lowered[1..]
                        .chars()
                        .all(|character| character.is_ascii_digit()))
        })
        .unwrap_or("default")
        .into()
}

/// Elixir keeps pagination explicit: a generated pager exists only for a
/// declared string cursor that maps to an existing operation option. The
/// ordinary operation owns query/header/path serialization on every page.
#[derive(Clone, Debug)]
struct CursorPagination {
    parameter_name: String,
    next_cursor_path: String,
}

fn cursor_pagination(operation: &Operation) -> Option<CursorPagination> {
    let extension = poolster_core::poolster_extension(&operation.annotations, "pagination")
        .or_else(|| operation.annotations.get("x-speakeasy-pagination"))?
        .as_object()?;
    if extension.get("type").and_then(Value::as_str) != Some("cursor") {
        return None;
    }
    let input = extension
        .get("inputs")
        .and_then(Value::as_array)?
        .iter()
        .find(|input| input.get("type").and_then(Value::as_str) == Some("cursor"))?
        .as_object()?;
    if !matches!(
        input.get("in").and_then(Value::as_str),
        None | Some("parameters")
    ) {
        return None;
    }
    let parameter_name = input.get("name")?.as_str()?;
    let parameter = operation.parameters.iter().find(|parameter| {
        parameter.name == parameter_name
            && matches!(parameter.location.as_str(), "query" | "header" | "path")
            && parameter
                .schema
                .as_ref()
                .is_some_and(|schema| matches!(schema.kind, SchemaKind::String))
            && (parameter.location != "path" || parameter.required)
    })?;
    Some(CursorPagination {
        parameter_name: elixir_parameter_identifier(operation, parameter),
        next_cursor_path: extension
            .get("outputs")?
            .get("nextCursor")?
            .as_str()?
            .to_owned(),
    })
}

fn render_cursor_paginator(operation: &Operation, pagination: &CursorPagination) -> String {
    let name = elixir_identifier(&operation.id);
    format!(
        "  @doc \"Lazily yields declared cursor pages.\"\n  @spec {name}_pages(Client.t(), keyword()) :: Enumerable.t()\n  def {name}_pages(client, options \\\\ []) when is_list(options) do\n    Stream.resource(\n      fn -> {{:next, options}} end,\n      fn\n        :halt -> {{:halt, :halt}}\n        {{:next, current}} ->\n          case {name}(client, current) do\n            {{:ok, response}} ->\n              case Client.json_path(response, {:?}) do\n                cursor when is_binary(cursor) and cursor != \"\" -> {{[{{:ok, response}}], {{:next, Keyword.put(current, :{}, cursor)}}}}\n                _ -> {{[{{:ok, response}}], :halt}}\n              end\n            {{:error, reason}} -> {{[{{:error, reason}}], :halt}}\n          end\n      end,\n      fn _ -> :ok end\n    )\n  end\n\n",
        pagination.next_cursor_path, pagination.parameter_name,
    )
}

fn operation_is_sse(operation: &Operation) -> bool {
    operation.responses.iter().any(|response| {
        response.status.starts_with('2')
            && response
                .media_types
                .iter()
                .any(|media| media.content_type.eq_ignore_ascii_case("text/event-stream"))
    })
}

fn json_content_allows_null(parameter: &poolster_core::OperationParameter) -> bool {
    fn allows(value: &SchemaValue) -> bool {
        value.nullable
            || matches!(value.kind, SchemaKind::Any | SchemaKind::Null)
            || match &value.kind {
                SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => {
                    variants.iter().any(allows)
                }
                _ => false,
            }
    }
    parameter.schema.as_ref().is_none_or(allows)
}

fn is_json_parameter_content(parameter: &poolster_core::OperationParameter) -> bool {
    poolster_core::openapi32::parameter_content(parameter)
        .ok()
        .and_then(|items| items.into_iter().next())
        .is_some_and(|content| {
            content.content_type == "application/json" || content.content_type.ends_with("+json")
        })
}

fn render_operation(module: &str, api: &Api, operation: &Operation) -> String {
    let name = elixir_identifier(&operation.id);
    let return_type = if operation_is_sse(operation) {
        "Enumerable.t()".into()
    } else {
        response_type(api, operation, module)
    };
    let mut output = String::new();
    let _ = writeln!(
        output,
        "  @type {name}_option :: {}",
        operation_option_types(operation, module)
    );
    let _ = writeln!(
        output,
        "  @spec {name}(Client.t(), [{name}_option()]) :: {{:ok, {return_type}}} | {{:error, term()}}"
    );
    let _ = writeln!(
        output,
        "  def {name}(client, options \\\\ []) when is_list(options) do"
    );

    let required = operation
        .parameters
        .iter()
        .filter(|parameter| parameter.required)
        .collect::<Vec<_>>();
    if required.is_empty() && !request_body_required(operation) {
        render_operation_body(&mut output, module, api, operation, 4);
    } else {
        output.push_str("    with ");
        let mut checks = required
            .iter()
            .map(|parameter| {
                let variable = elixir_parameter_identifier(operation, parameter);
                let helper = if is_json_parameter_content(parameter)
                    && json_content_allows_null(parameter)
                {
                    "required_present"
                } else {
                    "required"
                };
                format!("{{:ok, {variable}}} <- Client.{helper}(options, :{variable})")
            })
            .collect::<Vec<_>>();
        if request_body_required(operation) {
            checks.push("{:ok, body} <- Client.required(options, :body)".into());
        }
        output.push_str(&checks.join(",\n         "));
        output.push_str(" do\n");
        render_operation_body(&mut output, module, api, operation, 6);
        output.push_str("    end\n");
    }
    output.push_str("  end\n\n");
    if let Some(page) = page_pagination::render(api, operation).ok().flatten() {
        output.push_str(&page);
    }
    if let Some(pagination) = cursor_pagination(operation) {
        output.push_str(&render_cursor_paginator(operation, &pagination));
    }
    output
}

fn parameter_content_value(parameter: &poolster_core::OperationParameter, value: &str) -> String {
    if let Some(content) = poolster_core::openapi32::parameter_content(parameter)
        .ok()
        .and_then(|items| items.into_iter().next())
    {
        let allow_null = parameter.required
            && is_json_parameter_content(parameter)
            && json_content_allows_null(parameter);
        format!(
            "Client.parameter_content({value}, \"{}\", {allow_null})",
            escape_elixir_string(&content.content_type)
        )
    } else {
        value.to_owned()
    }
}

fn render_operation_body(
    output: &mut String,
    module: &str,
    api: &Api,
    operation: &Operation,
    indent: usize,
) {
    let pad = " ".repeat(indent);
    let _ = writeln!(
        output,
        "{pad}path = \"{}\"",
        escape_elixir_string(&operation.path)
    );
    for parameter in operation
        .parameters
        .iter()
        .filter(|parameter| parameter.location == "path")
    {
        let value = elixir_parameter_identifier(operation, parameter);
        let value = if parameter.required {
            value
        } else {
            format!("Keyword.get(options, :{value})")
        };
        let value = parameter_content_value(parameter, &value);
        let _ = writeln!(
            output,
            "{pad}path = String.replace(path, \"{{{}}}\", URI.encode(to_string({value}), &URI.char_unreserved?/1))",
            escape_elixir_string(&parameter.name),
        );
    }
    if poolster_core::poolster_extension(&operation.annotations, "pagination")
        .or_else(|| operation.annotations.get("x-speakeasy-pagination"))
        .and_then(|value| value.get("type"))
        .and_then(Value::as_str)
        == Some("url")
    {
        let _ = writeln!(
            output,
            "{pad}path = case Keyword.fetch(options, :_poolster_pagination_url) do {{:ok, url}} -> {{:poolster_url, url}}; :error -> path end"
        );
    }
    let query = operation
        .parameters
        .iter()
        .filter(|parameter| parameter.location == "query")
        .map(|parameter| {
            let variable = elixir_parameter_identifier(operation, parameter);
            let value = if parameter.required {
                variable
            } else {
                format!("Keyword.get(options, :{variable})")
            };
            let value = parameter_content_value(parameter, &value);
            format!("{{\"{}\", {value}}}", escape_elixir_string(&parameter.name))
        })
        .collect::<Vec<_>>();
    let _ = writeln!(output, "{pad}query = [{}]", query.join(", "));
    if let Some(parameter) = operation
        .parameters
        .iter()
        .find(|parameter| parameter.location == "querystring")
    {
        let name = elixir_parameter_identifier(operation, parameter);
        let value = if parameter.required {
            name.clone()
        } else {
            format!("Keyword.get(options, :{name})")
        };
        let content = poolster_core::openapi32::parameter_content(parameter)
            .ok()
            .and_then(|items| items.into_iter().next())
            .map(|item| item.content_type)
            .unwrap_or_else(|| "text/plain".into());
        let allow_null = parameter.required
            && is_json_parameter_content(parameter)
            && json_content_allows_null(parameter);
        let _ = writeln!(
            output,
            "{pad}query = Client.whole_query({value}, \"{}\", {allow_null})",
            escape_elixir_string(&content)
        );
    }
    let headers = operation
        .parameters
        .iter()
        .filter(|parameter| parameter.location == "header")
        .map(|parameter| {
            let variable = elixir_parameter_identifier(operation, parameter);
            let value = if parameter.required {
                variable
            } else {
                format!("Keyword.get(options, :{variable})")
            };
            let value = parameter_content_value(parameter, &value);
            let value = if poolster_core::poolster_extension(
                &operation.annotations,
                "idempotency-resolved",
            )
            .is_some_and(|policy| {
                policy
                    .get("auto_generate")
                    .and_then(serde_json::Value::as_bool)
                    == Some(true)
                    && policy
                        .get("parameter_name")
                        .and_then(serde_json::Value::as_str)
                        == Some(parameter.name.as_str())
            }) {
                format!("case {value} do nil -> Client.idempotency_key(); provided -> provided end")
            } else {
                value
            };
            format!("{{\"{}\", {value}}}", escape_elixir_string(&parameter.name))
        })
        .collect::<Vec<_>>();
    let _ = writeln!(output, "{pad}headers = [{}]", headers.join(", "));
    let cookies = operation.parameters.iter().filter(|parameter| parameter.location == "cookie").map(|parameter| {
        let id = elixir_parameter_identifier(operation, parameter);
        let value = if parameter.required { id } else { format!("Keyword.get(options, :{id})") };
        let value = parameter_content_value(parameter, &value);
        format!("case {value} do nil -> nil; value -> \"{}=\" <> URI.encode(to_string(value), &URI.char_unreserved?/1) end", escape_elixir_string(&parameter.name))
    }).collect::<Vec<_>>();
    if !cookies.is_empty() {
        let _ = writeln!(
            output,
            "{pad}headers = headers ++ [{{\"cookie\", [{}] |> Enum.reject(&is_nil/1) |> Enum.join(\"; \")}}]",
            cookies.join(", ")
        );
    }

    let _ = writeln!(
        output,
        "{pad}headers = headers |> Enum.reject(fn {{_name, value}} -> is_nil(value) end) |> Enum.map(fn {{name, value}} -> {{name, to_string(value)}} end)"
    );
    let body: String = if operation.request_body.is_some() {
        if request_body_required(operation) {
            "body".into()
        } else {
            "Keyword.get(options, :body)".into()
        }
    } else {
        "nil".into()
    };
    let body = if let Some(content) = poolster_core::openapi32::request_content(operation)
        .ok()
        .and_then(|items| {
            items
                .into_iter()
                .find(|content| content.content_type.starts_with("multipart/"))
        }) {
        let definition = serde_json::to_string(&content).expect("multipart content metadata");
        let _ = writeln!(
            output,
            "{pad}body = case {body} do %{}.MultipartBody{{}} = value -> {}.MultipartBody.with_encoding(value, Jason.decode!(\"{}\")); other -> other end",
            module,
            module,
            escape_elixir_string(&definition)
        );
        "body".to_owned()
    } else {
        body
    };
    let response = response_decode(api, operation, module, "response");
    let body_kind = operation_body_kind(operation);
    let response_kind = operation_response_kind(operation);
    let error_types = operation_error_types(module, operation);
    let idempotency_argument =
        poolster_core::poolster_extension(&operation.annotations, "idempotency-resolved")
            .and_then(|policy| policy.get("header"))
            .and_then(serde_json::Value::as_str)
            .map(|header| format!(", \"{}\"", escape_elixir_string(header)))
            .unwrap_or_else(|| ", nil".into());
    let native_method = if matches!(
        &operation.method,
        poolster_core::HttpMethod::Query | poolster_core::HttpMethod::Custom(_)
    ) {
        format!("\"{}\"", escape_elixir_string(operation.method.as_str()))
    } else {
        format!(":{}", operation.method.as_str().to_ascii_lowercase())
    };
    if operation_is_sse(operation) {
        let _ = writeln!(
            output,
            "{pad}Client.event_stream(client, {}, path, query, headers, {body}, :{body_kind})",
            native_method,
        );
        return;
    }
    let _ = writeln!(
        output,
        "{pad}case Client.request(client, {}, path, query, headers, {body}, :{body_kind}, :{response_kind}, {error_types}{idempotency_argument}) do",
        native_method,
    );
    let _ = writeln!(output, "{pad}  {{:ok, response}} -> {{:ok, {response}}}");
    for response in operation
        .responses
        .iter()
        .filter(|response| is_error_status(&response.status))
    {
        let Some(schema) = response
            .media_types
            .iter()
            .find(|media| media.content_type.contains("json"))
            .or_else(|| response.media_types.first())
            .and_then(|media| media.schema.as_ref())
        else {
            continue;
        };
        let error = declared_error_name(operation, &response.status);
        let decoded = decode_value("reason.body", schema, module);
        let _ = writeln!(
            output,
            "{pad}  {{:error, %{module}.Errors.{error}{{}} = reason}} -> {{:error, %{{reason | body: {decoded}}}}}"
        );
    }
    let _ = writeln!(output, "{pad}  {{:error, reason}} -> {{:error, reason}}");
    let _ = writeln!(output, "{pad}end");
}

fn operation_option_types(operation: &Operation, module: &str) -> String {
    let mut items = operation
        .parameters
        .iter()
        .map(|parameter| {
            let value = parameter
                .schema
                .as_ref()
                .map(|schema| elixir_type(schema, module))
                .unwrap_or_else(|| "term()".into());
            format!(
                "{{:{}, {value}}}",
                elixir_parameter_identifier(operation, parameter)
            )
        })
        .collect::<Vec<_>>();
    if let Some(body) = &operation.request_body {
        let value = if operation_body_kind(operation) == "binary" {
            "binary()".into()
        } else {
            body.media_types
                .iter()
                .find(|media| media.content_type.contains("json"))
                .or_else(|| body.media_types.first())
                .and_then(|media| media.schema.as_ref())
                .map(|schema| elixir_type(schema, module))
                .unwrap_or_else(|| "term()".into())
        };
        items.push(format!("{{:body, {value}}}"));
    }
    if items.is_empty() {
        "term()".into()
    } else {
        items.join(" | ")
    }
}

fn operation_body_kind(operation: &Operation) -> &'static str {
    if operation.request_body.as_ref().is_some_and(|body| {
        body.media_types
            .iter()
            .any(|media| media.content_type.starts_with("multipart/"))
    }) {
        return if operation.request_body.as_ref().is_some_and(|body| {
            body.media_types.iter().any(|media| {
                media.content_type == "application/json" || media.content_type.ends_with("+json")
            })
        }) {
            "multipart_json"
        } else {
            "multipart"
        };
    }
    operation
        .request_body
        .as_ref()
        .and_then(|body| body.media_types.first())
        .map(|media| match media.content_type.as_str() {
            "application/x-www-form-urlencoded" => "form",
            "application/octet-stream" => "binary",
            _ => "json",
        })
        .unwrap_or("json")
}

fn operation_response_kind(operation: &Operation) -> &'static str {
    let content_type = operation
        .responses
        .iter()
        .find(|response| response.status.starts_with('2'))
        .and_then(|response| response.media_types.first())
        .map(|media| media.content_type.as_str());
    match content_type {
        Some("application/json-seq") => "json_seq",
        Some("application/x-ndjson" | "application/ndjson" | "application/jsonl") => "ndjson",
        Some(value) if value == "application/octet-stream" || value.starts_with("image/") => {
            "binary"
        }
        Some(value) if value.starts_with("text/") => "text",
        None => "void",
        _ => "json",
    }
}

fn is_error_status(status: &str) -> bool {
    status == "default"
        || status
            .parse::<u16>()
            .is_ok_and(|status| (400..600).contains(&status))
}

fn declared_error_name(operation: &Operation, status: &str) -> String {
    let suffix = if status == "default" {
        "Default".into()
    } else {
        format!("Status{status}")
    };
    format!("{}{}Error", pascal_case(&operation.id), suffix)
}

fn operation_error_types(module: &str, operation: &Operation) -> String {
    let entries = operation
        .responses
        .iter()
        .filter(|response| is_error_status(&response.status))
        .map(|response| {
            let key = response
                .status
                .parse::<u16>()
                .map(|status| status.to_string())
                .unwrap_or_else(|_| ":default".into());
            format!(
                "{key} => {module}.Errors.{}",
                declared_error_name(operation, &response.status)
            )
        })
        .collect::<Vec<_>>();
    if entries.is_empty() {
        "%{}".into()
    } else {
        format!("%{{{}}}", entries.join(", "))
    }
}

fn request_body_required(operation: &Operation) -> bool {
    operation
        .request_body
        .as_ref()
        .map(|body| body.required)
        .unwrap_or(false)
}

fn response_schema(operation: &Operation) -> Option<&SchemaValue> {
    operation
        .responses
        .iter()
        .find(|response| response.status.starts_with('2'))
        .and_then(|response| {
            response
                .media_types
                .iter()
                .find(|media| media.content_type.contains("json"))
        })
        .or_else(|| {
            operation
                .responses
                .iter()
                .find(|response| response.status.starts_with('2'))
                .and_then(|response| response.media_types.first())
        })
        .and_then(|media| media.schema.as_ref())
}

fn response_type(_api: &Api, operation: &Operation, module: &str) -> String {
    response_schema(operation)
        .map(|schema| elixir_type(schema, module))
        .unwrap_or_else(|| "nil".into())
}

fn response_decode(_api: &Api, operation: &Operation, module: &str, value: &str) -> String {
    response_schema(operation)
        .map(|schema| decode_value(value, schema, module))
        .unwrap_or_else(|| value.into())
}

fn decode_value(value: &str, schema: &SchemaValue, module: &str) -> String {
    match &schema.kind {
        SchemaKind::Reference { reference } => format!(
            "case {value} do nil -> nil; map when is_map(map) or is_list(map) -> {module}.Models.{}.from_map(map); other -> other end",
            pascal_case(reference.rsplit('/').next().unwrap_or(reference))
        ),
        SchemaKind::Array { items } => format!(
            "case {value} do nil -> nil; items when is_list(items) -> Enum.map(items, fn item -> {} end); other -> other end",
            decode_value("item", items, module)
        ),
        _ => value.into(),
    }
}

fn elixir_type(value: &SchemaValue, module: &str) -> String {
    let base = match &value.kind {
        SchemaKind::Any | SchemaKind::Not { .. } => "term()".into(),
        SchemaKind::Null => "nil".into(),
        SchemaKind::Boolean => "boolean()".into(),
        SchemaKind::Integer => "integer()".into(),
        SchemaKind::Number => "number()".into(),
        // Elixir typespecs cannot express binary literal unions. Keep wire
        // enums as strings rather than inventing atom values for the API.
        SchemaKind::String => "String.t()".into(),
        SchemaKind::Array { items } => format!("[{}]", elixir_type(items, module)),
        SchemaKind::Object {
            additional_properties: AdditionalProperties::Schema { value },
            ..
        } => format!(
            "%{{optional(String.t()) => {}}}",
            elixir_type(value, module)
        ),
        SchemaKind::Object { .. } => "map()".into(),
        SchemaKind::Reference { reference } => format!(
            "{module}.Models.{}.t()",
            pascal_case(reference.rsplit('/').next().unwrap_or(reference))
        ),
        SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => variants
            .iter()
            .map(|variant| elixir_type(variant, module))
            .collect::<Vec<_>>()
            .join(" | "),
        SchemaKind::AllOf { .. } => "map()".into(),
    };
    if value.nullable && base != "nil" {
        format!("{base} | nil")
    } else {
        base
    }
}

