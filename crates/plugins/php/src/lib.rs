fn pagination_annotation(operation: &Operation) -> Option<&Value> {
    operation
        .annotations
        .get("x-poolster-pagination")
        .or_else(|| operation.annotations.get("x-speakeasy-pagination"))
}

fn idempotency_annotation(operation: &Operation) -> Option<&Value> {
    operation.annotations.get("x-poolster-idempotency-resolved")
}

/// Generates an installable PHP 8.2+ package.
///
/// `output_dir` is a relative output prefix in the returned tree, allowing a
/// caller to generate this package alongside other language targets. When no
/// Composer package name is supplied, a stable `poolster/<api>-sdk` name is
/// derived from the API title.
#[cfg(test)]
fn render_test_sdk(
    api: &Api,
    output_dir: &str,
    package_name: Option<&str>,
) -> Result<GeneratedTree> {
    render_sdk(api, output_dir, package_name, SdkClientStyle::Flat)
}

/// Generates an installable PHP 8.2+ package with a selectable public client
/// surface. `Flat` exports the direct `Client::operation()` API, while
/// `Namespaced` additionally exports resource accessors such as
/// `$client->contacts()->create(...)`.
fn render_sdk(
    api: &Api,
    output_dir: &str,
    package_name: Option<&str>,
    style: SdkClientStyle,
) -> Result<GeneratedTree> {
    let prepared = symbols::prepare(api);
    let api = prepared.as_ref();
    for operation in &api.operations {
        poolster_core::openapi32::request_content(operation)?;
        poolster_core::openapi32::response_content(operation)?;
        for parameter in &operation.parameters {
            poolster_core::openapi32::parameter_content(parameter)?;
        }
    }
    let root = output_dir.trim_matches('/');
    let package_name = package_name
        .filter(|name| !name.trim().is_empty())
        .map(str::to_owned)
        .unwrap_or_else(|| format!("poolster/{}-sdk", package_slug(&api.name)));
    let namespace = namespace_for_package(&package_name);
    let named_types = NamedTypes::from_api(api);
    let mut tree = GeneratedTree::default();
    let diagnostics=api.operations.iter().filter_map(|operation|page_pagination::plan(api,operation).err().map(|error|serde_json::json!({"operation":operation.id,"status":"unsupported","reason":error.to_string()}))).collect::<Vec<_>>();
    if api
        .operations
        .iter()
        .any(|operation| pagination_annotation(operation).is_some())
    {
        insert(
            &mut tree,
            root,
            ".poolster/pagination-diagnostics.json",
            serde_json::to_string_pretty(&serde_json::json!({"diagnostics":diagnostics}))?,
        )?;
    }

    insert(
        &mut tree,
        root,
        "composer.json",
        composer_json(api, &package_name, &namespace),
    )?;
    insert(&mut tree, root, "README.md", readme(api, &namespace, style))?;
    insert(
        &mut tree,
        root,
        "STYLE_GUIDE.md",
        style_guide(api, &namespace, style),
    )?;
    insert(
        &mut tree,
        root,
        "src/Exceptions/ApiException.php",
        api_exception(&namespace),
    )?;
    insert(
        &mut tree,
        root,
        "src/MultipartBody.php",
        include_str!("../templates/multipart.php.tmpl").replace("__NAMESPACE__", &namespace),
    )?;
    for schema in &api.schemas {
        insert(
            &mut tree,
            root,
            &format!("src/Models/{}.php", type_name(&schema.name)),
            render_model(schema, &namespace, &named_types),
        )?;
    }
    for (part, range) in php_operation_groups(api, &namespace, &named_types)
        .into_iter()
        .enumerate()
    {
        let operations = &api.operations[range];
        insert(
            &mut tree,
            root,
            &format!("src/ClientOperations{part:03}.php"),
            render_operation_trait(api, operations, part, &namespace, &named_types),
        )?;
    }
    insert(
        &mut tree,
        root,
        "src/Client.php",
        render_client(api, &namespace, style),
    )?;
    if style == SdkClientStyle::Namespaced {
        for (resource, operations) in resource_operations(api) {
            let groups = php_resource_groups(api, &resource, &operations, &namespace, &named_types);
            let group_count = groups.len();
            insert(
                &mut tree,
                root,
                &format!("src/Resources/{resource}Resource.php"),
                render_resource(&resource, group_count, &namespace),
            )?;
            for (part, range) in groups.into_iter().enumerate() {
                let chunk = &operations[range];
                insert(
                    &mut tree,
                    root,
                    &format!("src/Resources/{resource}ResourceOperations{part:03}.php"),
                    render_resource_trait(api, &resource, chunk, part, &namespace, &named_types),
                )?;
            }
        }
    }
    Ok(tree)
}

fn readme(api: &Api, namespace: &str, style: SdkClientStyle) -> String {
    let usage = match style {
        SdkClientStyle::Flat => {
            "```php\n$client = new Client($httpClient, 'https://api.example.com', getenv('API_KEY'));\n$contact = $client->getContact($id);\n```"
        }
        SdkClientStyle::Namespaced => {
            "```php\n$client = new Client($httpClient, 'https://api.example.com', getenv('API_KEY'));\n$contact = $client->contacts()->get($id);\n```"
        }
    };
    let middleware = r#"## Runtime customization

Wrap the injected PSR-18 client to apply customer request and response policy:

```php
$policyClient = new class($httpClient) implements \Psr\Http\Client\ClientInterface {
    public function __construct(private \Psr\Http\Client\ClientInterface $next) {}
    public function sendRequest(\Psr\Http\Message\RequestInterface $request): \Psr\Http\Message\ResponseInterface {
        $request = $request->withHeader('X-Customer', 'customer-a');
        $response = $this->next->sendRequest($request);
        return $response->withHeader('X-Customer-Policy', 'applied');
    }
};
$client = new Client($policyClient, 'https://api.example.com', getenv('API_KEY'));
```

PSR-7 `withUri`, `withMethod` and `withBody` create replacement requests; return a
replacement response to rewrite its status/body or short circuit with a cached
PSR-7 response. Catch transport exceptions when translating customer errors,
preserving the PSR-18 exception interfaces for transport failures. Observer
callbacks do not return replacement messages. The decorator runs for each SDK
transport attempt, including retries. Preserve stream positions or replace the
stream when reading bodies; live SSE behavior depends on the chosen PSR-18 client.
"#;
    format!(
        "# {} PHP SDK\n\nGenerated PHP 8.2+ SDK. See [STYLE_GUIDE.md](STYLE_GUIDE.md) for the selected public API.\n\n```php\nuse {namespace}\\Client;\n```\n\n{usage}\n\n{middleware}\n## Pagination\n\nDeclared page-number operations expose `<operation>Pages(...)` as a lazy Generator, including resource facades. Values are complete response pages. Optional page controls start at 1; explicit 0 is preserved. Empty results or a page shorter than a positive limit terminate iteration. Required JSON body controls are copied without mutating the caller. Iteration is bounded to 10,000 pages with integer overflow checks. Invalid page declarations appear in `.poolster/pagination-diagnostics.json`. Existing cursor, offset/limit and same-origin URL continuation helpers retain their target-specific controls.\n",
        api.name
    )
}

fn style_guide(api: &Api, namespace: &str, style: SdkClientStyle) -> String {
    let surface = match style {
        SdkClientStyle::Flat => {
            "## Flat client\n\nOperations are exposed directly on `Client`, for example `$client->getContact($id)`.\n\nThe generator was invoked with `SdkClientStyle::Flat`."
        }
        SdkClientStyle::Namespaced => {
            "## Namespaced client\n\nOperations are grouped by their first OpenAPI tag, falling back to the stable path resource. Use `$client->contacts()->get($id)`. Direct methods remain available on `Client` for migration.\n\nThe generator was invoked with `SdkClientStyle::Namespaced`."
        }
    };
    format!(
        "# {} PHP SDK style guide\n\nNamespace: `{namespace}`.\n\n{surface}\n\n## Streaming\n\nOperations declared as `text/event-stream` return a PSR-7 `StreamInterface`. Poolster does not buffer, decode, or reconnect this stream: PSR-18 does not guarantee that every client implementation exposes a live socket. Choose a stream-capable PSR-18 client when live SSE delivery is required, and implement event decoding/reconnection (including any `Last-Event-ID` policy) in the application.\n",
        api.name
    )
}

fn insert(tree: &mut GeneratedTree, root: &str, path: &str, contents: String) -> Result<()> {
    let path = match root {
        "" | "." => path.to_owned(),
        root => format!("{root}/{path}"),
    };
    tree.insert(GeneratedFile::new(path, contents)?)
}

