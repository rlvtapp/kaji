fn render_sdk(
    api: &Api,
    output_dir: &str,
    package_name: Option<&str>,
    client_style: SdkClientStyle,
) -> Result<GeneratedTree> {
    let root = output_dir.trim_matches('/');
    if root.is_empty() {
        bail!("Ruby SDK output directory cannot be empty");
    }
    let gem = package_name
        .filter(|name| !name.trim().is_empty())
        .map(str::to_owned)
        .unwrap_or_else(|| format!("{}-sdk", kebab_case(&api.name)));
    let module = pascal_case(&gem);
    let file_module = ruby_file_name(&gem);
    let mut tree = GeneratedTree::default();
    let diagnostics=api.operations.iter().filter_map(|operation|pagination::plan(api,operation).err().map(|error|serde_json::json!({"operation":operation.id,"status":"unsupported","reason":error.to_string()}))).collect::<Vec<_>>();
    if api.operations.iter().any(|operation| {
        operation.annotations.contains_key("x-kaji-pagination")
            || operation.annotations.contains_key("x-speakeasy-pagination")
    }) {
        insert(
            &mut tree,
            root,
            ".kaji/pagination-diagnostics.json",
            serde_json::to_string_pretty(&serde_json::json!({"diagnostics":diagnostics}))?,
        )?;
    }

    insert(
        &mut tree,
        root,
        &format!("{gem}.gemspec"),
        gemspec(api, &gem),
    )?;
    insert(
        &mut tree,
        root,
        "Gemfile",
        "source \"https://rubygems.org\"\n\ngemspec\n".into(),
    )?;
    insert(
        &mut tree,
        root,
        "README.md",
        readme(api, &gem, &module, client_style),
    )?;
    insert(
        &mut tree,
        root,
        "STYLE_GUIDE.md",
        style_guide(api, &module, client_style),
    )?;
    insert(
        &mut tree,
        root,
        &format!("lib/{file_module}.rb"),
        format!(
            "{NOTICE}require_relative \"{file_module}/models\"\nrequire_relative \"{file_module}/client\"\n\nmodule {module}\nend\n"
        ),
    )?;
    insert(
        &mut tree,
        root,
        &format!("lib/{file_module}/models.rb"),
        render_models(api, &module),
    )?;
    insert(
        &mut tree,
        root,
        &format!("lib/{file_module}/client.rb"),
        render_client(api, &module, client_style),
    )?;
    insert(
        &mut tree,
        root,
        &format!("lib/{file_module}/response_validation.rb"),
        response_validation::render(api, module.as_str()),
    )?;
    Ok(tree)
}

fn insert(tree: &mut GeneratedTree, root: &str, path: &str, contents: String) -> Result<()> {
    tree.insert(GeneratedFile::new(format!("{root}/{path}"), contents)?)
}

fn gemspec(api: &Api, gem: &str) -> String {
    format!(
        "Gem::Specification.new do |spec|\n  spec.name = {}\n  spec.version = {}\n  spec.summary = {}\n  spec.required_ruby_version = \">= 3.1\"\n  spec.files = Dir[\"lib/**/*.rb\"]\n  spec.require_paths = [\"lib\"]\nend\n",
        ruby_string(gem),
        ruby_string(&ruby_version(&api.version)),
        ruby_string(&format!("Generated Ruby SDK for {}", api.name))
    )
}

fn readme(api: &Api, gem: &str, module: &str, style: SdkClientStyle) -> String {
    let usage = match style {
        SdkClientStyle::Flat => "client.get_contact(contact_id: \"contact_123\")",
        SdkClientStyle::Namespaced => "client.contacts.get(contact_id: \"contact_123\")",
    };
    format!(
        "# {} Ruby SDK\n\nGenerated by Kaji for Ruby 3.1+. It only uses the Ruby standard library.\n\n```sh\ngem install {gem}\n```\n\n```ruby\nrequire {}\n\nclient = {module}::Client.new(base_url: \"https://api.example.com\", api_key: ENV.fetch(\"API_KEY\", nil))\n{usage}\n```\n\nSee [STYLE_GUIDE.md](STYLE_GUIDE.md) for the selected client surface.\n",
        api.name,
        ruby_string(&ruby_file_name(gem)),
    ) + &include_str!("middleware_readme.md").replace("__MODULE__", module)
        + "\n## Pagination\n\nDeclared page-number operations expose `<operation>_pages(...)` as a lazy Enumerator, including resource facades. Each value is a complete response page. Optional page controls start at 1; explicit 0 is preserved. Empty results or a page shorter than a positive limit terminate iteration. Required JSON body controls are copied without mutating the caller. Iteration is bounded to 10,000 pages. Cursor, offset/limit and URL declarations are unsupported and appear in `.kaji/pagination-diagnostics.json`; ordinary operation calls remain available.\n"
}

fn style_guide(api: &Api, module: &str, style: SdkClientStyle) -> String {
    let surface = match style {
        SdkClientStyle::Flat => "Operations are direct methods such as `client.get_contact(...)`.",
        SdkClientStyle::Namespaced => {
            "Operations remain direct methods and are also grouped by resource, such as `client.contacts.get(...)`."
        }
    };
    format!(
        "# {} Ruby SDK style guide\n\nNamespace: `{module}`.\n\n{surface}\n",
        api.name
    )
}

fn render_models(api: &Api, module: &str) -> String {
    let mut out = format!("{NOTICE}require \"json\"\n\nmodule {module}\n  module Models\n");
    out.push_str(r#"    # Lazy aliases avoid evaluating forward constants or Ruby's unsupported class union operator.
    def self.wire_alias(shape)
      Class.new do
        define_singleton_method(:wire_shape) { shape }
        define_singleton_method(:from_hash) { |value| Models.decode_model_value(value, shape) }
        if shape && shape[0] == 'ref'
          define_singleton_method(:new) do |*args, **kwargs|
            target = Models.const_get(shape[1], false)
            raise ArgumentError, 'cyclic model alias' if target.equal?(self)
            target.new(*args, **kwargs)
          end
        end
      end
    end
    def self.decode_model_value(value, shape)
      return value if value.nil? || shape.nil?
      kind, inner = shape
      if kind == 'ref'
        model = const_get(inner, false) if const_defined?(inner, false)
        return model.from_hash(value) if model && model.respond_to?(:from_hash) && value.is_a?(Hash)
      elsif kind == 'array' && value.is_a?(Array)
        return value.map { |item| decode_model_value(item, inner) }
      elsif kind == 'object' && value.is_a?(Hash)
        return value if inner.empty?
        return value.each_with_object({}) { |(name, item), output| output[name] = decode_model_value(item, inner[name]) }
      end
      value
    end
    def self.to_wire(value)
      return value.map { |item| to_wire(item) } if value.is_a?(Array)
      return value.each_with_object({}) { |(name, item), output| output[name] = to_wire(item) } if value.is_a?(Hash)
      return value.to_h if value.respond_to?(:to_h) && !value.nil?
      value
    end

"#);
    for schema in &api.schemas {
        out.push_str(&render_model(api, schema));
    }
    out.push_str("  end\nend\n");
    out
}

fn ruby_decode_shape(value: &SchemaValue) -> String {
    match &value.kind {
        SchemaKind::Reference { reference } => format!(
            "[\"ref\", {}]",
            ruby_string(&pascal_case(
                reference.rsplit('/').next().unwrap_or(reference)
            ))
        ),
        SchemaKind::Array { items } => format!("[\"array\", {}]", ruby_decode_shape(items)),
        SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => format!(
            "[\"union\", [{}]]",
            variants
                .iter()
                .map(ruby_decode_shape)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        SchemaKind::Boolean => "[\"boolean\", nil]".into(),
        SchemaKind::Object { fields, .. } => format!(
            "[\"object\", {{{}}}]",
            fields
                .iter()
                .map(|field| format!(
                    "{} => {}",
                    ruby_string(&field.name),
                    ruby_decode_shape(&field.value)
                ))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        _ => "nil".into(),
    }
}

fn render_model(api: &Api, schema: &Schema) -> String {
    let name = pascal_case(&schema.name);
    let mut out = String::new();
    match &schema.value.kind {
        SchemaKind::Object {
            fields,
            additional_properties: _,
        } => {
            let mut extra_name = "additional_properties".to_owned();
            while fields
                .iter()
                .any(|field| ruby_identifier(&field.name) == extra_name)
            {
                extra_name.insert(0, '_');
            }
            let mut present_name = "__kaji_present_wire_fields".to_owned();
            while fields
                .iter()
                .any(|field| ruby_identifier(&field.name) == present_name)
                || present_name == extra_name
            {
                present_name.insert(0, '_');
            }
            out = format!("    class {name}\n");
            if fields.is_empty() {
                let _ = writeln!(out, "      attr_reader :{extra_name}");
            } else {
                let attrs = fields
                    .iter()
                    .map(|field| format!(":{}", ruby_identifier(&field.name)))
                    .collect::<Vec<_>>()
                    .join(", ");
                let _ = writeln!(out, "      attr_reader {attrs}");
                let _ = writeln!(out, "      attr_reader :{extra_name}");
            }
            let args = fields
                .iter()
                .map(|field| format!("{}: nil", ruby_identifier(&field.name)))
                .collect::<Vec<_>>()
                .join(", ");
            let extra = if args.is_empty() {
                &format!("{extra_name}: {{}}")
            } else {
                &format!(", {extra_name}: {{}}")
            };
            let _ = writeln!(out, "      def initialize({args}{extra})");
            for field in fields {
                let id = ruby_identifier(&field.name);
                let _ = writeln!(out, "        @{id} = {id}");
            }
            let _ = writeln!(out, "        @{extra_name} = {extra_name} || {{}}");
            out.push_str("      end\n\n      def self.from_hash(value)\n        return value unless value.is_a?(Hash)\n");
            let values = fields
                .iter()
                .map(|field| {
                    format!(
                        "{}: Models.decode_model_value(value[{}], {})",
                        ruby_identifier(&field.name),
                        ruby_string(&field.name),
                        ruby_decode_shape(&field.value)
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            {
                let known = fields
                    .iter()
                    .map(|field| ruby_string(&field.name))
                    .collect::<Vec<_>>()
                    .join(", ");
                let values = if values.is_empty() {
                    String::new()
                } else {
                    format!("{values}, ")
                };
                let _ = writeln!(
                    out,
                    "        instance = new({values}{extra_name}: value.reject {{ |key, _| [{}].include?(key) }})",
                    known
                );
            }
            let _ = writeln!(
                out,
                "        instance.instance_variable_set(:@{present_name}, value.keys)\n        instance"
            );
            out.push_str("      end\n\n      def to_h\n        value = {}\n");
            {
                let known = fields
                    .iter()
                    .map(|field| ruby_string(&field.name))
                    .collect::<Vec<_>>()
                    .join(", ");
                let _ = writeln!(
                    out,
                    "        value.merge!({extra_name}.reject {{ |key, _| [{known}].include?(key) }})"
                );
            }
            for field in fields {
                let id = ruby_identifier(&field.name);
                let condition = if field.required
                    && !response_validation::write_only(api, &field.value, &mut Default::default())
                {
                    String::new()
                } else {
                    format!(
                        " unless {id}.nil? && !(@{present_name} || []).include?({})",
                        ruby_string(&field.name)
                    )
                };
                let _ = writeln!(
                    out,
                    "        value[{}] = Models.to_wire({id}){condition}",
                    ruby_string(&field.name)
                );
            }
            out.push_str("        value\n      end\n    end\n\n");
        }
        SchemaKind::Reference { .. }
        | SchemaKind::OneOf { .. }
        | SchemaKind::AnyOf { .. }
        | SchemaKind::Boolean => {
            let _ = writeln!(
                out,
                "    {name} = Models.wire_alias({})\n",
                ruby_decode_shape(&schema.value)
            );
        }
        _ => {
            let ruby_type = ruby_type(&schema.value);
            let _ = writeln!(out, "    {name} = {ruby_type}\n");
        }
    }
    out
}

fn render_client(api: &Api, module: &str, style: SdkClientStyle) -> String {
    let mut out = format!(
        "{NOTICE}require \"net/http\"\nrequire \"uri\"\nrequire \"json\"\nrequire \"cgi\"\n\nmodule {module}\n"
    );
    out = out.replacen(
        &format!("module {module}\n"),
        &format!("require_relative \"response_validation\"\n\nmodule {module}\n"),
        1,
    );
    out.push_str(include_str!("multipart.rb.txt"));
    out.push_str("  class KajiCancellationError < StandardError; end\n  class KajiTimeoutError < Timeout::Error; end\n  class ApiError < StandardError\n    attr_reader :status, :body\n    def initialize(status, body)\n      @status = status\n      @body = body\n      super(\"API request failed with status #{status}\")\n    end\n  end\n\n  class Client\n    def initialize(base_url:, api_key: nil, bearer_token: nil, headers: {}, timeout: 30, transport: nil, middleware: [], validate_responses: false, max_attempts: 1, retry_base_delay: 0.5, retry_max_delay: 30, cancelled: nil, token_provider: nil)\n      @base_url = base_url.sub(%r{/$}, \"\")\n      @api_key = api_key\n      @bearer_token = bearer_token\n      @headers = headers.transform_keys(&:to_s)\n      @timeout = timeout\n      raise ArgumentError, \"invalid retry configuration\" unless max_attempts.is_a?(Integer) && max_attempts.between?(1, 10) && retry_base_delay.is_a?(Numeric) && retry_max_delay.is_a?(Numeric) && retry_base_delay.finite? && retry_max_delay.finite? && retry_base_delay >= 0 && retry_base_delay <= 60 && retry_max_delay >= 0 && retry_max_delay <= 60\n      @max_attempts = max_attempts\n      @retry_base_delay = retry_base_delay.to_f\n      @retry_max_delay = retry_max_delay.to_f\n      @cancelled = cancelled\n      @token_provider = token_provider\n      @transport = transport\n      @validate_responses = validate_responses\n      @middleware = middleware.to_a.dup.freeze\n      raise ArgumentError, \"middleware must be callable\" unless @middleware.all? { |item| item.respond_to?(:call) }\n");
    if style == SdkClientStyle::Namespaced {
        for resource in resource_operations(api).keys() {
            let _ = writeln!(
                out,
                "      @{} = {}Resource.new(self)",
                ruby_identifier(resource),
                pascal_case(resource)
            );
        }
    }
    out.push_str("    end\n\n");
    if style == SdkClientStyle::Namespaced {
        for resource in resource_operations(api).keys() {
            let _ = writeln!(out, "    attr_reader :{}", ruby_identifier(resource));
        }
        out.push('\n');
    }
    for operation in &api.operations {
        out.push_str(&render_operation(api, operation));
        if let Some(page) = pagination::render(api, operation) {
            out.push_str(&page);
        }
    }
    if api
        .operations
        .iter()
        .any(|operation| pagination::render(api, operation).is_some())
    {
        out.push_str(pagination::HELPERS);
        out.push_str("    private :kaji_json_path, :kaji_with_body_value\n\n");
    }
    out.push_str(include_str!("retry_runtime.rb.txt"));
    out.push_str(&render_runtime());
    out.push_str("  end\n\n");
    if style == SdkClientStyle::Namespaced {
        for (resource, operations) in resource_operations(api) {
            out.push_str(&render_resource(api, &resource, &operations));
        }
    }
    out.push_str("end\n");
    out
}

fn ruby_request_options_name(operation: &Operation) -> String {
    let mut name = "request_options".to_owned();
    while operation
        .parameters
        .iter()
        .any(|parameter| ruby_identifier(&parameter.name) == name)
    {
        name.insert(0, '_');
    }
    name
}

fn render_operation(api: &Api, operation: &Operation) -> String {
    let name = ruby_identifier(&snake_case(&operation.id));
    let mut args = Vec::new();
    for parameter in &operation.parameters {
        let name = ruby_identifier(&parameter.name);
        args.push(if parameter.required {
            format!("{name}:")
        } else {
            format!("{name}: nil")
        });
    }
    if let Some(body) = &operation.request_body {
        args.push(if body.required {
            "body:".into()
        } else {
            "body: nil".into()
        });
    }
    let request_options_name = ruby_request_options_name(operation);
    args.push(format!("{request_options_name}: nil"));
    let signature = args.join(", ");
    let mut out = format!(
        "    def {name}({signature})\n      path = {}\n",
        ruby_string(&operation.path)
    );
    if let Some(policy) = operation.annotations.get("x-kaji-idempotency-resolved") {
        if policy
            .get("auto_generate")
            .and_then(serde_json::Value::as_bool)
            == Some(true)
        {
            if let Some(parameter) = policy
                .get("parameter_name")
                .and_then(serde_json::Value::as_str)
            {
                let variable = ruby_identifier(parameter);
                let _ = writeln!(
                    out,
                    "      require 'securerandom'\n      {variable} = SecureRandom.uuid if {variable}.nil?"
                );
            }
        }
    }
    for parameter in operation
        .parameters
        .iter()
        .filter(|parameter| parameter.location == "path")
    {
        let id = ruby_identifier(&parameter.name);
        let _ = writeln!(
            out,
            "      path = path.gsub({}, CGI.escape({id}.to_s).gsub(\"+\", \"%20\"))",
            ruby_string(&format!("{{{}}}", parameter.name))
        );
    }
    out.push_str("      query = {}\n");
    for parameter in operation
        .parameters
        .iter()
        .filter(|parameter| parameter.location == "query")
    {
        let id = ruby_identifier(&parameter.name);
        let _ = writeln!(
            out,
            "      query[{}] = {id} unless {id}.nil?",
            ruby_string(&parameter.name)
        );
    }
    out.push_str("      headers = {}\n");
    for parameter in operation
        .parameters
        .iter()
        .filter(|parameter| parameter.location == "header")
    {
        let id = ruby_identifier(&parameter.name);
        let _ = writeln!(
            out,
            "      headers[{}] = {id}.to_s unless {id}.nil?",
            ruby_string(&parameter.name)
        );
    }
    let response = response_model(api, operation);
    let body = if operation.request_body.is_some() {
        "body"
    } else {
        "nil"
    };
    let multipart = operation.request_body.as_ref().is_some_and(|body| {
        body.media_types
            .iter()
            .any(|media| media.content_type == "multipart/form-data")
    });
    let retry_header = kaji_core::idempotency::resolved(operation)
        .map(|p| ruby_string(&p.header))
        .unwrap_or_else(|| "nil".into());
    let _ = writeln!(
        out,
        "      result = request({}, path, query: query, headers: headers, body: {body}, response_schemas: ResponseShapes[\"operations\"][{}], idempotency_header: {retry_header}, request_options: {request_options_name}, multipart: {multipart})",
        ruby_string(operation.method.as_str()),
        ruby_string(&operation.id)
    );
    match response.as_deref() {
        Some(model) => {
            let _ = writeln!(
                out,
                "      result.is_a?(Hash) ? Models::{model}.from_hash(result) : result\n    end\n\n"
            );
        }
        None => out.push_str("      result\n    end\n\n"),
    }
    out
}

fn render_runtime() -> String {
    include_str!("request_runtime.rb.txt").into()
}

fn render_resource(api: &Api, resource: &str, operations: &[&Operation]) -> String {
    let class = format!("{}Resource", pascal_case(resource));
    let mut out =
        format!("  class {class}\n    def initialize(client)\n      @client = client\n    end\n\n");
    for operation in operations {
        let name = ruby_identifier(&snake_case(&operation.id));
        let args = operation
            .parameters
            .iter()
            .map(|parameter| {
                let name = ruby_identifier(&parameter.name);
                if parameter.required {
                    format!("{name}:")
                } else {
                    format!("{name}: nil")
                }
            })
            .chain(operation.request_body.as_ref().map(|body| {
                if body.required {
                    "body:".to_owned()
                } else {
                    "body: nil".to_owned()
                }
            }))
            .collect::<Vec<_>>()
            .join(", ");
        let options_name = ruby_request_options_name(operation);
        let args = if args.is_empty() {
            format!("{options_name}: nil")
        } else {
            format!("{args}, {options_name}: nil")
        };
        let forwards = operation
            .parameters
            .iter()
            .map(|parameter| {
                let id = ruby_identifier(&parameter.name);
                format!("{id}: {id}")
            })
            .chain(
                operation
                    .request_body
                    .as_ref()
                    .map(|_| "body: body".to_owned()),
            )
            .collect::<Vec<_>>()
            .join(", ");
        let forwards = if forwards.is_empty() {
            format!("{options_name}: {options_name}")
        } else {
            format!("{forwards}, {options_name}: {options_name}")
        };
        let _ = writeln!(
            out,
            "    def {name}({args})\n      @client.{name}({forwards})\n    end\n"
        );
        if pagination::render(api, operation).is_some() {
            let _ = writeln!(
                out,
                "    def {name}_pages({args}, &block)\n      @client.{name}_pages({forwards}, &block)\n    end\n"
            );
        }
    }
    out.push_str("  end\n\n");
    out
}

fn resource_operations(api: &Api) -> BTreeMap<String, Vec<&Operation>> {
    let mut groups = BTreeMap::new();
    for operation in &api.operations {
        let resource = operation
            .path
            .trim_matches('/')
            .split('/')
            .next()
            .filter(|part| !part.is_empty())
            .unwrap_or("default");
        groups
            .entry(snake_case(resource))
            .or_insert_with(Vec::new)
            .push(operation);
    }
    groups
}

fn response_model(api: &Api, operation: &Operation) -> Option<String> {
    let reference = operation.success_schema()?.kind.reference_name()?;
    api.schemas
        .iter()
        .find(|schema| schema.name == reference)
        .and_then(|schema| {
            matches!(schema.value.kind, SchemaKind::Object { .. }).then(|| pascal_case(reference))
        })
}

fn ruby_type(value: &SchemaValue) -> String {
    match &value.kind {
        SchemaKind::Any | SchemaKind::Not { .. } => "Object".into(),
        SchemaKind::Null => "NilClass".into(),
        SchemaKind::Boolean => "TrueClass | FalseClass".into(),
        SchemaKind::Integer => "Integer".into(),
        SchemaKind::Number => "Numeric".into(),
        SchemaKind::String => "String".into(),
        SchemaKind::Array { items } => format!("Array # {}", ruby_type(items)),
        SchemaKind::Object { .. } => "Hash".into(),
        SchemaKind::Reference { reference } => {
            pascal_case(reference.rsplit('/').next().unwrap_or(reference))
        }
        SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => variants
            .iter()
            .map(ruby_type)
            .collect::<Vec<_>>()
            .join(" | "),
        SchemaKind::AllOf { .. } => "Hash".into(),
    }
}

fn ruby_version(version: &str) -> String {
    let parts = version.split('.').collect::<Vec<_>>();
    if parts.len() == 3 && parts.iter().all(|part| part.parse::<u32>().is_ok()) {
        version.into()
    } else {
        "0.1.0".into()
    }
}

fn ruby_string(value: &str) -> String {
    serde_json::to_string(value).expect("strings serialize")
}

fn ruby_file_name(value: &str) -> String {
    snake_case(value)
}

fn ruby_identifier(value: &str) -> String {
    let value = snake_case(value);
    let value = if value.is_empty() {
        "value".into()
    } else {
        value
    };
    if value.starts_with(|c: char| c.is_ascii_digit()) {
        return format!("value_{value}");
    }
    match value.as_str() {
        "alias" | "and" | "begin" | "break" | "case" | "class" | "def" | "defined" | "do"
        | "else" | "elsif" | "end" | "ensure" | "false" | "for" | "if" | "in" | "module"
        | "next" | "nil" | "not" | "or" | "redo" | "rescue" | "retry" | "return" | "self"
        | "super" | "then" | "true" | "undef" | "unless" | "until" | "when" | "while" | "yield"
        | "private" | "public" => format!("{value}_"),
        _ => value,
    }
}

fn snake_case(value: &str) -> String {
    let mut output = String::new();
    let mut previous_is_lower = false;
    for character in value.chars() {
        if character.is_ascii_alphanumeric() {
            if character.is_ascii_uppercase() && previous_is_lower {
                output.push('_');
            }
            output.push(character.to_ascii_lowercase());
            previous_is_lower = character.is_ascii_lowercase() || character.is_ascii_digit();
        } else if !output.ends_with('_') && !output.is_empty() {
            output.push('_');
            previous_is_lower = false;
        }
    }
    output.trim_matches('_').into()
}

fn kebab_case(value: &str) -> String {
    snake_case(value).replace('_', "-")
}

fn pascal_case(value: &str) -> String {
    let mut output = String::new();
    let mut capitalize = true;
    for character in value.chars() {
        if character.is_ascii_alphanumeric() {
            if capitalize {
                output.push(character.to_ascii_uppercase());
                capitalize = false;
            } else {
                output.push(character);
            }
        } else {
            capitalize = true;
        }
    }
    if output.is_empty() {
        "GeneratedSdk".into()
    } else if output
        .chars()
        .next()
        .is_some_and(|character| character.is_ascii_digit())
    {
        format!("Sdk{output}")
    } else {
        output
    }
}

