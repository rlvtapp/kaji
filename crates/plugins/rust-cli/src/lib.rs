//! Generates a distributable Rust command-line client from Kaji's neutral API.
//!
//! The generated `kaji_extension.rs` is emitted as a custom file. It is the
//! stable, user-owned place for provider-specific login, request signing, and
//! observability without editing generated command wiring.

use anyhow::{Result, bail};
use kaji_core::{
    Api, GeneratedFile, Operation, SchemaKind, SchemaValue, SecuritySchemeCatalog,
    SecuritySchemeKind,
    engine::{Language, Meta, Package, Plugin, PluginContext},
};

const NOTICE: &str = "// Generated by Kaji. Do not edit.\n";

