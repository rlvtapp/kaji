/// Emits `index.ts`, package metadata, and a strict TypeScript configuration.
///
/// Supported scalar config values are `output_dir`, `package_name`, `clients`
/// (a comma-separated `fetch,axios` list), and `naming` (`camelCase`,
/// `PascalCase`, or `snake_case`). Matching and ordered overrides remain the
/// compiler's responsibility; these values are its resolved inputs.
#[derive(Default)]
pub struct TypeScriptPackage;

impl CodegenPlugin for TypeScriptPackage {
    fn name(&self) -> &'static str {
        "typescript-package"
    }

    fn generate(&self, api: &Api, config: &GeneratorConfig) -> Result<Vec<GeneratedFile>> {
        let clients = client_modules(config);
        let mut index = format!("{NOTICE}\nexport * from './models';\n");
        for client in &clients {
            let _ = writeln!(index, "export * from './{client}';");
        }

        let package_name = config
            .get("package_name")
            .cloned()
            .unwrap_or_else(|| format!("@kaji/{}", package_slug(&api.name)));
        let mut package = json!({
            "name": package_name,
            "version": api.version,
            "description": format!("{} API client generated by Kaji Codegen", api.name),
            "type": "module",
            "sideEffects": false,
            "exports": { ".": { "types": "./dist/index.d.ts", "import": "./dist/index.js" } },
            "files": ["dist"],
            "scripts": { "build": "tsc -p tsconfig.json" },
            "devDependencies": { "typescript": "^5.0.0" }
        });
        if clients.contains(&"axios") {
            package["peerDependencies"] = json!({ "axios": "^1.0.0" });
        }

        Ok(vec![
            GeneratedFile::new(output_path(config, "index.ts"), index)?,
            GeneratedFile::new(
                output_path(config, "package.json"),
                format!("{}\n", serde_json::to_string_pretty(&package)?),
            )?,
            GeneratedFile::new(output_path(config, "tsconfig.json"), tsconfig())?,
        ])
    }
}

fn output_path(config: &GeneratorConfig, file: &str) -> String {
    let directory = config
        .get("output_dir")
        .map(String::as_str)
        .unwrap_or("typescript")
        .trim_matches('/');
    match directory {
        "" | "." => file.to_owned(),
        _ => format!("{directory}/{file}"),
    }
}

fn render_models(api: &Api) -> String {
    let mut output = format!("{NOTICE}\n");
    for schema in &api.schemas {
        render_description(&mut output, schema.value.description.as_deref());
        let _ = writeln!(
            output,
            "export type {} = {};\n",
            type_identifier(&schema.name),
            render_value(&schema.value)
        );
    }
    output
}

fn render_value(value: &SchemaValue) -> String {
    let primitive = match &value.kind {
        SchemaKind::Any => "unknown".to_owned(),
        SchemaKind::Null => "null".to_owned(),
        SchemaKind::Boolean => "boolean".to_owned(),
        SchemaKind::Integer | SchemaKind::Number => "number".to_owned(),
        SchemaKind::String => "string".to_owned(),
        SchemaKind::Array { items } => format!("Array<{}>", render_value(items)),
        SchemaKind::Object {
            fields,
            additional_properties,
        } => render_object(fields, additional_properties),
        SchemaKind::Reference { reference } => {
            type_identifier(reference.rsplit('/').next().unwrap_or(reference))
        }
        SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => {
            join_types(variants, " | ")
        }
        SchemaKind::AllOf { variants } => join_types(variants, " & "),
        // TypeScript has no sound type-level complement operator. `unknown` is
        // safer than emitting an invented constraint that rejects valid values.
        SchemaKind::Not { .. } => "unknown".to_owned(),
    };

    let constrained = if let Some(constant) = value.const_value.as_ref().and_then(ts_literal) {
        constant
    } else if !value.enum_values.is_empty() {
        let members = value
            .enum_values
            .iter()
            .filter_map(ts_literal)
            .collect::<Vec<_>>();
        if members.is_empty() {
            primitive
        } else {
            members.join(" | ")
        }
    } else {
        primitive
    };

    if value.nullable && constrained != "null" {
        format!("{constrained} | null")
    } else {
        constrained
    }
}

fn render_object(
    fields: &[crate::ast::Field],
    additional_properties: &AdditionalProperties,
) -> String {
    let mut members = Vec::new();
    for field in fields {
        let optional = if field.required { "" } else { "?" };
        let mut member = String::new();
        if let Some(description) = field.value.description.as_deref() {
            member.push_str("/** ");
            member.push_str(&description.replace("*/", "* /"));
            member.push_str(" */ ");
        }
        let _ = write!(
            member,
            "{}{}: {}",
            property_name(&field.name),
            optional,
            render_value(&field.value)
        );
        members.push(member);
    }
    match additional_properties {
        AdditionalProperties::Any | AdditionalProperties::Unspecified => {
            members.push("[key: string]: unknown".to_owned());
        }
        AdditionalProperties::Schema { value } => {
            members.push(format!("[key: string]: {}", render_value(value)));
        }
        AdditionalProperties::Forbidden => {}
    }
    if members.is_empty() {
        "Record<string, never>".to_owned()
    } else {
        format!("{{ {} }}", members.join("; "))
    }
}

fn join_types(values: &[SchemaValue], separator: &str) -> String {
    if values.is_empty() {
        "unknown".to_owned()
    } else {
        values
            .iter()
            .map(|value| {
                let rendered = render_value(value);
                // `&` binds more tightly than `|` in TypeScript. Parenthesize
                // union members of an intersection so `allOf` keeps its JSON
                // Schema grouping instead of changing its meaning on render.
                if separator == " & " && rendered.contains(" | ") {
                    format!("({rendered})")
                } else {
                    rendered
                }
            })
            .collect::<Vec<_>>()
            .join(separator)
    }
}

fn ts_literal(value: &Value) -> Option<String> {
    match value {
        Value::Null | Value::Bool(_) | Value::Number(_) | Value::String(_) => {
            serde_json::to_string(value).ok()
        }
        Value::Array(values) => values
            .iter()
            .map(ts_literal)
            .collect::<Option<Vec<_>>>()
            .map(|values| format!("readonly [{}]", values.join(", "))),
        Value::Object(values) => values
            .iter()
            .map(|(name, value)| {
                ts_literal(value).map(|value| format!("{}: {value}", js_string(name)))
            })
            .collect::<Option<Vec<_>>>()
            .map(|values| format!("{{ {} }}", values.join("; "))),
    }
}

fn render_description(output: &mut String, description: Option<&str>) {
    if let Some(description) = description {
        output.push_str("/**\n");
        for line in description.lines() {
            let _ = writeln!(output, " * {}", line.replace("*/", "* /"));
        }
        output.push_str(" */\n");
    }
}

fn render_fetch_client(api: &Api, config: &GeneratorConfig) -> String {
    let mut output = format!(
        "{NOTICE}\n{}
export class ApiError extends Error {{
  constructor(public readonly status: number, public readonly response: Response) {{
    super(`Request failed: ${{status}}`);
    this.name = 'ApiError';
  }}
}}

export interface FetchClientConfig {{
  baseUrl: string;
  fetch?: typeof globalThis.fetch;
  headers?: HeadersInit;
}}

export class FetchClient {{
  private readonly fetch: typeof globalThis.fetch;

  constructor(private readonly config: FetchClientConfig) {{
    this.fetch = config.fetch ?? globalThis.fetch;
  }}

",
        model_import(api)
    );
    for operation in &api.operations {
        output.push_str(&render_fetch_operation(operation, config));
    }
    output.push_str("}\n");
    output
}

fn render_fetch_operation(operation: &Operation, config: &GeneratorConfig) -> String {
    let parameters = parameters(operation);
    let body = if operation.request_type.is_some() {
        ",\n      body: JSON.stringify(body),\n      headers: { ...this.config.headers, 'content-type': 'application/json' },"
    } else {
        ",\n      headers: this.config.headers,"
    };
    let response = type_reference(&operation.response_type);
    format!(
        "  async {}({parameters}): Promise<{response}> {{\n    const response = await this.fetch(`${{this.config.baseUrl}}${{path}}`, {{\n      method: {},{body}\n    }});\n    if (!response.ok) throw new ApiError(response.status, response);\n    if (response.status === 204) return undefined as {response};\n    return (await response.json()) as {response};\n  }}\n\n",
        operation_identifier(&operation.id, config),
        js_string(operation.method.as_str()),
    )
}

fn render_axios_client(api: &Api, config: &GeneratorConfig) -> String {
    let mut output = format!(
        "{NOTICE}\nimport axios, {{ type AxiosInstance }} from 'axios';\n{}
export interface AxiosClientConfig {{ baseUrl: string; client?: AxiosInstance; }}

export class AxiosClient {{
  private readonly client: AxiosInstance;
  constructor(config: AxiosClientConfig) {{
    this.client = config.client ?? axios.create({{ baseURL: config.baseUrl }});
  }}

",
        model_import(api)
    );
    for operation in &api.operations {
        output.push_str(&render_axios_operation(operation, config));
    }
    output.push_str("}\n");
    output
}

fn render_axios_operation(operation: &Operation, config: &GeneratorConfig) -> String {
    let response = type_reference(&operation.response_type);
    let data = if operation.request_type.is_some() {
        ",\n      data: body,"
    } else {
        ""
    };
    format!(
        "  async {}({}): Promise<{response}> {{\n    const response = await this.client.request<{response}>({{\n      url: path,\n      method: {},{data}\n    }});\n    return response.data;\n  }}\n\n",
        operation_identifier(&operation.id, config),
        parameters(operation),
        js_string(operation.method.as_str()),
    )
}

fn parameters(operation: &Operation) -> String {
    match operation.request_type.as_deref() {
        Some(request) => format!(
            "path = {}, body: {}",
            js_string(&operation.path),
            type_reference(request)
        ),
        None => format!("path = {}", js_string(&operation.path)),
    }
}

fn model_import(api: &Api) -> String {
    if api.schemas.is_empty() {
        String::new()
    } else {
        format!(
            "import type {{ {} }} from './models';\n",
            api.schemas
                .iter()
                .map(|schema| type_identifier(&schema.name))
                .collect::<Vec<_>>()
                .join(", ")
        )
    }
}

fn client_modules(config: &GeneratorConfig) -> Vec<&str> {
    let mut clients = config
        .get("clients")
        .map(String::as_str)
        .unwrap_or("fetch")
        .split(',')
        .map(str::trim)
        .filter(|client| matches!(*client, "fetch" | "axios"))
        .collect::<Vec<_>>();
    clients.sort_unstable();
    clients.dedup();
    clients
}

