/// Emits SWR hooks backed by `FetchClient`.
#[derive(Default)]
pub struct TypeScriptSwr;

impl CodegenPlugin for TypeScriptSwr {
    fn name(&self) -> &'static str {
        "typescript-swr"
    }

    fn generate(&self, api: &Api, config: &GeneratorConfig) -> Result<Vec<GeneratedFile>> {
        let mut output = format!(
            "{NOTICE}\nimport useSWR from 'swr';\nimport type {{ FetchClient }} from './fetch';\n\n"
        );
        for operation in &api.operations {
            if !matches!(operation.method, crate::ast::HttpMethod::Get) {
                continue;
            }
            let name = operation_identifier(&operation.id, config);
            let pascal = type_identifier(&operation.id);
            let _ = writeln!(
                output,
                "export const {name}SwrKey = (path = {}) => ['{}', path] as const;",
                js_string(&operation.path),
                operation.id
            );
            let _ = writeln!(
                output,
                "export function use{pascal}SWR(client: FetchClient, path = {}) {{",
                js_string(&operation.path)
            );
            let _ = writeln!(
                output,
                "  return useSWR({name}SwrKey(path), () => client.{name}(path));
}}\n"
            );
        }
        Ok(vec![GeneratedFile::new(
            extra_output_path(config, "typescript", "swr.ts"),
            output,
        )?])
    }
}

