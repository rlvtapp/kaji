const NOTICE: &str = "// Generated by Kaji Codegen. Do not edit.\n";

/// Emits reusable TypeScript types from the normalized schema graph.
#[derive(Default)]
pub struct TypeScriptModels;

impl CodegenPlugin for TypeScriptModels {
    fn name(&self) -> &'static str {
        "typescript-models"
    }

    fn generate(&self, api: &Api, config: &GeneratorConfig) -> Result<Vec<GeneratedFile>> {
        Ok(vec![GeneratedFile::new(
            output_path(config, "models.ts"),
            render_models(api),
        )?])
    }
}

