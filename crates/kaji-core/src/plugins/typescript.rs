fn render_faker(value: &SchemaValue) -> String {
    if let Some(constant) = value.const_value.as_ref().and_then(ts_literal) {
        return constant;
    }
    if !value.enum_values.is_empty() {
        let values = value
            .enum_values
            .iter()
            .filter_map(ts_literal)
            .collect::<Vec<_>>();
        if !values.is_empty() {
            return format!("faker.helpers.arrayElement([{}])", values.join(", "));
        }
    }
    match &value.kind {
        SchemaKind::Any => {
            "faker.helpers.arrayElement([null, true, faker.string.alpha({ length: 8 })])".to_owned()
        }
        SchemaKind::Null => "null".to_owned(),
        SchemaKind::Boolean => "faker.datatype.boolean()".to_owned(),
        SchemaKind::Integer => "faker.number.int()".to_owned(),
        SchemaKind::Number => "faker.number.float()".to_owned(),
        SchemaKind::String => "faker.string.alpha({ length: 12 })".to_owned(),
        SchemaKind::Array { items } => {
            format!("Array.from({{ length: 2 }}, () => {})", render_faker(items))
        }
        SchemaKind::Object { fields, .. } => format!(
            "{{ {} }}",
            fields
                .iter()
                .map(|field| format!("{}: {}", js_string(&field.name), render_faker(&field.value)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        SchemaKind::Reference { reference } => format!(
            "create{}()",
            type_identifier(reference.rsplit('/').next().unwrap_or(reference))
        ),
        SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => variants
            .first()
            .map(render_faker)
            .unwrap_or_else(|| "undefined".to_owned()),
        SchemaKind::AllOf { variants } => variants
            .first()
            .map(render_faker)
            .unwrap_or_else(|| "undefined".to_owned()),
        SchemaKind::Not { .. } => "undefined".to_owned(),
    }
}

fn openapi_path_to_msw(path: &str) -> String {
    let mut output = String::new();
    for character in path.chars() {
        match character {
            '{' => output.push(':'),
            '}' => {}
            _ => output.push(character),
        }
    }
    output
}

fn html_escape(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

