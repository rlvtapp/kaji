/// Emits a Cypress smoke suite. It deliberately exercises request routing, not
/// business assertions, so generated tests stay useful before users add data.
#[derive(Default)]
pub struct TypeScriptCypress;

impl CodegenPlugin for TypeScriptCypress {
    fn name(&self) -> &'static str {
        "typescript-cypress"
    }

    fn generate(&self, api: &Api, config: &GeneratorConfig) -> Result<Vec<GeneratedFile>> {
        let mut output = format!(
            "{NOTICE}\nconst baseUrl = Cypress.env('API_BASE_URL') ?? 'http://localhost:3000';\n\ndescribe({}, () => {{\n",
            js_string(&format!("{} API", api.name))
        );
        for operation in &api.operations {
            let _ = writeln!(
                output,
                "  it({}, () => {{",
                js_string(&format!(
                    "calls {} {}",
                    operation.method.as_str(),
                    operation.path
                ))
            );
            let _ = writeln!(
                output,
                "    cy.request({{ method: {}, url: `${{baseUrl}}${{${}}}` , failOnStatusCode: false }}).its('status').should('be.gte', 100);",
                js_string(operation.method.as_str()),
                js_string(&operation.path)
            );
            output.push_str("  });\n");
        }
        output.push_str("});\n");
        Ok(vec![GeneratedFile::new(
            extra_output_path(config, "cypress/e2e", "api.cy.ts"),
            output,
        )?])
    }
}

/// Emits a self-contained ReDoc entry point and a small Redocly config.
#[derive(Default)]
pub struct ReDoc;

impl CodegenPlugin for ReDoc {
    fn name(&self) -> &'static str {
        "redoc"
    }

    fn generate(&self, api: &Api, config: &GeneratorConfig) -> Result<Vec<GeneratedFile>> {
        let spec = config
            .get("openapi_spec")
            .map(String::as_str)
            .unwrap_or("openapi.yaml");
        let title = config.get("title").map(String::as_str).unwrap_or(&api.name);
        let html = format!(
            "<!doctype html>\n<html><head><meta charset=\"utf-8\"><title>{}</title></head><body><redoc spec-url=\"{}\"></redoc><script src=\"https://cdn.redoc.ly/redoc/latest/bundles/redoc.standalone.js\"></script></body></html>\n",
            html_escape(title),
            html_escape(spec)
        );
        let yaml = format!(
            "theme:\n  openapi:\n    htmlTemplate: ./redoc.html\n    theme:\n      typography:\n        fontSize: 15px\n# {} {}\n",
            api.name, api.version
        );
        Ok(vec![
            GeneratedFile::new(extra_output_path(config, "redoc", "redoc.html"), html)?,
            GeneratedFile::new(extra_output_path(config, "redoc", "redocly.yaml"), yaml)?,
        ])
    }
}

/// Emits a portable MCP tool manifest. A future server runtime can consume the
/// same manifest without making the codegen crate depend on an MCP SDK.
#[derive(Default)]
pub struct McpToolManifest;

impl CodegenPlugin for McpToolManifest {
    fn name(&self) -> &'static str {
        "mcp-tool-manifest"
    }

    fn generate(&self, api: &Api, config: &GeneratorConfig) -> Result<Vec<GeneratedFile>> {
        let tools = api.operations.iter().map(|operation| {
            let mut properties = serde_json::Map::from_iter([(
                "path".to_owned(),
                json!({ "type": "string", "default": operation.path }),
            )]);
            if operation.request_type.is_some() {
                properties.insert("body".to_owned(), json!({}));
            }
            json!({
                "name": operation_identifier(&operation.id, config),
                "description": format!("{} {}", operation.method.as_str(), operation.path),
                "inputSchema": {
                    "type": "object",
                    "properties": properties,
                    "required": if operation.request_type.is_some() { json!(["body"]) } else { json!([]) },
                },
            })
        }).collect::<Vec<_>>();
        let manifest = json!({ "name": api.name, "version": api.version, "tools": tools });
        Ok(vec![GeneratedFile::new(
            extra_output_path(config, "mcp", "tools.json"),
            format!("{}\n", serde_json::to_string_pretty(&manifest)?),
        )?])
    }
}

fn extra_output_path(config: &GeneratorConfig, default_directory: &str, file: &str) -> String {
    if config.contains_key("output_dir") {
        output_path(config, file)
    } else {
        format!("{default_directory}/{file}")
    }
}

fn render_zod(value: &SchemaValue) -> String {
    let primitive = match &value.kind {
        SchemaKind::Any => "z.unknown()".to_owned(),
        SchemaKind::Null => "z.null()".to_owned(),
        SchemaKind::Boolean => "z.boolean()".to_owned(),
        SchemaKind::Integer => "z.number().int()".to_owned(),
        SchemaKind::Number => "z.number()".to_owned(),
        SchemaKind::String => "z.string()".to_owned(),
        SchemaKind::Array { items } => format!("z.array({})", render_zod(items)),
        SchemaKind::Object {
            fields,
            additional_properties,
        } => {
            let fields = fields
                .iter()
                .map(|field| {
                    let optional = if field.required { "" } else { ".optional()" };
                    format!(
                        "{}: {}{}",
                        js_string(&field.name),
                        render_zod(&field.value),
                        optional
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            let object = format!("z.object({{ {fields} }})");
            match additional_properties {
                AdditionalProperties::Forbidden => format!("{object}.strict()"),
                AdditionalProperties::Any | AdditionalProperties::Unspecified => {
                    format!("{object}.catchall(z.unknown())")
                }
                AdditionalProperties::Schema { value } => {
                    format!("{object}.catchall({})", render_zod(value))
                }
            }
        }
        SchemaKind::Reference { reference } => format!(
            "z.lazy(() => {}Schema)",
            type_identifier(reference.rsplit('/').next().unwrap_or(reference))
        ),
        SchemaKind::OneOf { variants } | SchemaKind::AnyOf { variants } => {
            match variants.as_slice() {
                [] => "z.unknown()".to_owned(),
                [one] => render_zod(one),
                values => format!(
                    "z.union([{}])",
                    values.iter().map(render_zod).collect::<Vec<_>>().join(", ")
                ),
            }
        }
        SchemaKind::AllOf { variants } => match variants.as_slice() {
            [] => "z.unknown()".to_owned(),
            [one] => render_zod(one),
            values => values
                .iter()
                .skip(1)
                .fold(render_zod(&values[0]), |current, next| {
                    format!("z.intersection({current}, {})", render_zod(next))
                }),
        },
        SchemaKind::Not { .. } => "z.unknown()".to_owned(),
    };
    let constrained = if let Some(constant) = value.const_value.as_ref().and_then(zod_literal) {
        constant
    } else if !value.enum_values.is_empty() {
        let values = value
            .enum_values
            .iter()
            .filter_map(zod_literal)
            .collect::<Vec<_>>();
        if values.len() == 1 {
            values[0].clone()
        } else if values.is_empty() {
            primitive
        } else {
            format!("z.union([{}])", values.join(", "))
        }
    } else {
        primitive
    };
    if value.nullable {
        format!("{constrained}.nullable()")
    } else {
        constrained
    }
}

fn zod_literal(value: &Value) -> Option<String> {
    ts_literal(value).map(|literal| format!("z.literal({literal})"))
}

fn render_react_query(operation: &Operation, config: &GeneratorConfig) -> String {
    let name = operation_identifier(&operation.id, config);
    let pascal = type_identifier(&operation.id);
    if matches!(operation.method, crate::ast::HttpMethod::Get) {
        format!(
            "export const {name}QueryKey = (path = {}) => ['{}', path] as const;\nexport function use{pascal}(client: FetchClient, path = {}) {{\n  return useQuery({{ queryKey: {name}QueryKey(path), queryFn: () => client.{name}(path) }});\n}}\n\n",
            js_string(&operation.path),
            operation.id,
            js_string(&operation.path)
        )
    } else if let Some(request) = operation.request_type.as_deref() {
        format!(
            "export function use{pascal}(client: FetchClient, path = {}) {{\n  return useMutation({{ mutationFn: (body: {}) => client.{name}(path, body) }});\n}}\n\n",
            js_string(&operation.path),
            type_reference(request)
        )
    } else {
        format!(
            "export function use{pascal}(client: FetchClient, path = {}) {{\n  return useMutation({{ mutationFn: () => client.{name}(path) }});\n}}\n\n",
            js_string(&operation.path)
        )
    }
}

